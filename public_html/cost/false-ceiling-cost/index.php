<h2>Cost saving tips</h2>
<ul>
  <li><strong>Ceiling only where it does a job.</strong> A peripheral ceiling in the living room and master bedroom hides cove lights, curtain tracks and AC pipes; most other rooms do not need one.</li>
  <li><strong>Gypsum board for large flat areas.</strong> It goes up faster than POP and avoids the long curing time, which shortens the labour bill.</li>
  <li><strong>Freeze the light layout first.</strong> Moving downlights after the boards are up means cutting and patching.</li>
  <li><strong>Get frame spacing and board brand in writing</strong>, so two quotes compare like for like.</li>
  <li><strong>Do the ceiling with the electrical work</strong>, so wiring is run once.</li>
</ul>
