<h2>Where not to save</h2>
<ul>
  <li><strong>Waterproofing:</strong> floor and walls to 1 ft (6–7 ft in the shower), with a 48-hour ponding test before tiles.</li>
  <li><strong>Plumbing:</strong> replace old GI pipes with CPVC; use branded traps and floor drains.</li>
  <li><strong>Floor slope:</strong> towards the drain, checked with water before the tiler leaves.</li>
  <li><strong>Vanity board:</strong> BWP plywood only; MDF and particle board swell within a year. See <a href="/materials/marine-plywood/">marine plywood</a>.</li>
</ul>

<h2>Where you can save</h2>
<ul>
  <li>Tile-on-tile on sound walls, if the plumbing does not need changing.</li>
  <li>Large tiles only in the shower; standard sizes elsewhere.</li>
  <li>A mid-range fittings series from a major brand rather than its designer range.</li>
  <li>A shower curtain or a half-height glass panel instead of a full enclosure.</li>
</ul>

<h2>Timeline</h2>
<ol class="steps">
  <li><strong>Demolition</strong>2–3 days, including debris removal.</li>
  <li><strong>Plumbing and waterproofing</strong>3–4 days, with a 48-hour ponding test.</li>
  <li><strong>Tiling</strong>4–5 days for floor and walls.</li>
  <li><strong>Fixtures and vanity</strong>2–3 days, then a leak check.</li>
</ol>
