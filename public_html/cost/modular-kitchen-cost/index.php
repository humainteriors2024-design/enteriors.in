<h2>Costs that are often left out</h2>
<ul>
  <li><strong>Appliances:</strong> chimney (₹12,000–40,000), hob (₹9,000–18,000), built-in oven, dishwasher.</li>
  <li><strong>Site work:</strong> removing an old kitchen (about ₹12,000), plumbing changes (about ₹10,000), new electrical points (about ₹8,000), wall or floor tiling (about ₹18,000).</li>
  <li><strong>Handles and profile lights</strong> if the quote lists "handle-less" but prices a profile separately.</li>
  <li><strong>GST</strong>, if rates are quoted before tax.</li>
</ul>

<h2>Five ways to spend less without regret</h2>
<ol>
  <li>Use laminate on base units and keep acrylic or PU for the wall units, where they stay clean.</li>
  <li>Pay for BWP plywood only near the sink; BWR or HDHMR is enough elsewhere.</li>
  <li>Choose dark granite over quartz if you can seal it once a year.</li>
  <li>Buy a corner unit and a cutlery tray; skip accessories you will not use daily.</li>
  <li>Keep the layout simple: every extra corner adds fittings and fillers.</li>
</ol>
