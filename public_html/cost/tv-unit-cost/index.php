<h2>Saving without looking cheap</h2>
<ul>
  <li>Use one strong panel finish and keep the unit itself in plain laminate.</li>
  <li>Choose a floating unit; it looks lighter and uses less material than a floor-standing one.</li>
  <li>Skip the display unit if you do not have things to display.</li>
  <li>Spend on concealed wiring: visible cables ruin even an expensive wall.</li>
</ul>

<h2>Before the panel goes up</h2>
<ol>
  <li>Fix the TV size and the bracket position.</li>
  <li>Run two sockets and an HDMI conduit behind the TV, and a socket in the unit for a set-top box or soundbar.</li>
  <li>Add a separate switch for any cove or backlight.</li>
  <li>Check the wall for damp; panels on a damp wall swell and grow mould.</li>
</ol>
