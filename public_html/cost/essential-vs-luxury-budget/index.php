<p>Functional, essential furniture. Standard modular designs, economy ply and hardware. Ideal for rental properties, first homes on tight budgets, or investment properties.</p>
<h4>Mid-Range Interiors</h4>
<p>The most popular choice among Indian homeowners. Better materials, branded hardware, some customisation. Good balance of quality and cost for a family home.</p>
