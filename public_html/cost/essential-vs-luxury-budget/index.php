<p>Category 01</p>
<h2>Basic Interiors — Fully Explained</h2>
<p>Basic interiors are exactly what the name implies: functional, clean, and no-frills. They cover the essential furniture needs of a home without decorative extras, premium materials, or custom design work. This is the entry point into the interior world and serves a very specific audience well.</p>
<h3>Basic Interiors — At a Glance</h3>
<p>₹800 – ₹1,200 per sq.ft | 2BHK: ₹3–5 Lakhs</p>
<p>What's Included</p>
<ul>
  <li>Standard modular kitchen (L or straight layout)</li>
  <li>Single-door or sliding wardrobe per bedroom</li>
  <li>Basic TV unit (wall-mounted or floor-standing)</li>
  <li>Loft storage units</li>
  <li>Basic laminate finish on shutters</li>
  <li>Economy hinges, channels and handles</li>
</ul>
<p>What's NOT Included</p>
<ul>
  <li>False ceilings or profile lighting</li>
  <li>Custom or bespoke furniture design</li>
  <li>Soft-close hardware systems</li>
  <li>Wallpapers, wall textures or cladding</li>
  <li>Dedicated interior designer</li>
  <li>Long-term warranty (typically 1–2 years)</li>
</ul>
<h3>Materials Used in Basic Interiors</h3>
<h4>Commercial Plywood</h4>
<p>Commercial plywood (also called commercial MR ply or bwp low-grade) is the most commonly used substrate in basic interiors. It has basic moisture resistance suitable for dry interior environments but should not be used in kitchens or bathrooms without additional sealing. Density is lower, and long-term screw-holding strength diminishes faster than higher grades.</p>
<h4>Basic Laminates</h4>
<p>Economy-grade laminates (0.8mm thickness, domestic brands) are applied as the shutter finish. The colour and texture options are limited to standard catalogues — typically plain solid colours, basic woodgrain, and a few textures. Scratch resistance and UV stability are lower than premium laminates.</p>
<h4>Economy Hardware</h4>
<p>Hinges, channels and handles in basic interiors are typically non-branded or entry-level Indian-manufactured hardware. These function adequately for light to moderate use but do not offer soft-close movement, and their lifespan under heavy daily use is typically 3–5 years before squeaking or misalignment begins.</p>
<h3>Design Options in Basic Interiors</h3>
<p>Design options are standard and catalogue-driven. A homeowner typically chooses from 8–12 pre-designed kitchen layouts and 4–6 wardrobe configurations. Customisation to room dimensions is done, but creative design input is minimal. What you see in the catalogue is broadly what you get.</p>
<h3>Who Should Choose Basic Interiors?</h3>
<ul>
  <li>Homeowners buying an investment property or rental apartment</li>
  <li>Young couples furnishing their first home on a limited starting budget</li>
  <li>Homeowners planning to upgrade interiors in 5–7 years anyway</li>
  <li>Properties that are not permanent residences (holiday homes, in-laws' quarters)</li>
</ul>
<div class="callout"><span class="callout__title">Note</span><strong>Reality check:</strong> Basic interiors are not "bad" — they are appropriate for the right use case. The mistake is choosing basic interiors for a home you plan to live in for 15+ years, because the lower-grade materials and hardware will begin showing wear and failure much sooner than the home itself.</div>
<p>Category 02</p>
<h2>Mid-Range Interiors — Fully Explained</h2>
<p>Mid-range interiors represent the sweet spot of the Indian interior market — and for good reason. They offer meaningfully better materials and hardware than basic interiors, allow for real customisation, and stay within a budget range that most urban homeowners can comfortably justify.</p>
<p>This is the category most recommended for permanent family residences in metro and tier-2 cities.</p>
<h3>Mid-Range Interiors — At a Glance</h3>
<p>₹1,200 – ₹1,800 per sq.ft | 2BHK: ₹6–9 Lakhs</p>
<p>What's Included</p>
<ul>
  <li>Kitchen with better layout flexibility</li>
  <li>Custom wardrobe configurations</li>
  <li>HDHMR or MDF shutters (better flatness)</li>
  <li>BWR plywood for carcasses</li>
  <li>Branded hardware (Ebco, Hettich entry range)</li>
  <li>Better laminate brands with more design options</li>
  <li>Basic profile lighting in kitchen</li>
  <li>3–5 year warranty</li>
</ul>
<p>What's NOT Included</p>
<ul>
  <li>Full designer involvement</li>
  <li>Imported or acrylic finishes</li>
  <li>Full soft-close tandem drawers throughout</li>
  <li>Elaborate false ceiling concepts</li>
  <li>PU painted or veneered finishes</li>
  <li>Bespoke furniture pieces</li>
</ul>
<h3>Materials Used in Mid-Range Interiors</h3>
<h4>BWR Plywood (Boiling Water Resistant)</h4>
<p>BWR-grade plywood is the most important upgrade from basic to mid-range. BWR ply uses a phenol formaldehyde resin that gives it significantly better water and humidity resistance than commercial ply. For a family home that will see monsoons, steam from cooking, and bathroom condensation for 10–15 years, BWR ply in the carcasses (boxes) is the baseline minimum. Do not accept commercial ply for a permanent residence.</p>
<h4>HDHMR Shutters</h4>
<p>High Density High Moisture Resistant (HDHMR) board is an upgraded alternative to standard MDF for shutters. It is denser, harder, more resistant to moisture at the edges, and holds screws better than standard MDF. HDHMR shutters with factory-applied laminates give a cleaner, more uniform finish than basic shutter boards.</p>
<h4>Better Quality Laminates</h4>
<p>Mid-range interiors use 1mm thick laminates from established manufacturers with a wider design palette — more textures, wood grains, solid mattes and semi-gloss options. These laminates have better scratch resistance and longer colour stability under UV exposure.</p>
<h4>Branded Hardware</h4>
<p>Entry-level branded hardware from companies like Ebco or Hettich's economy range enters the picture. Hinges have a longer rated life (typically 50,000 open/close cycles vs 15,000–20,000 for economy hardware). Drawer channels become smoother and more consistent.</p>
<p>"For most Indian families living in their permanent home, mid-range interiors with BWR ply carcasses and branded hardware is the minimum that makes long-term sense. Going below this is a false economy."</p>
<h3>Design Possibilities in Mid-Range</h3>
<p>This is where real customisation begins. Kitchen layouts adapt to actual room measurements with some creative input. Wardrobes can be fully customised — loft heights, drawer placement, shoe rack depth, and internal organiser configurations can all be specified. TV units can include open shelves, closed cabinets, and integrated back panels in different finishes.</p>
<p>However, the design is still largely furniture-led. There is no room concept, no lighting story, no architectural intervention — just well-made, well-fitted furniture designed to function comfortably for 7–12 years.</p>
<p>Category 03</p>
<h2>Premium Interiors — Fully Explained</h2>
<p>Premium interiors cross the threshold from "well-made furniture" into "designed home". At this level, the materials become noticeably different to the eye and touch, the hardware systems work with a quietness and precision that feels qualitatively different, and the design starts to reflect a homeowner's personality rather than a catalogue.</p>
<h3>Premium Interiors — At a Glance</h3>
<p>₹1,800 – ₹3,000 per sq.ft | 2BHK: ₹10–16 Lakhs</p>
<p>What's Included</p>
<ul>
  <li>BWP 710 / marine grade plywood for carcasses</li>
  <li>Acrylic, PU or imported laminate shutters</li>
  <li>Full soft-close hardware throughout</li>
  <li>Tandem box drawer systems</li>
  <li>Profile lighting in kitchen and wardrobes</li>
  <li>False ceiling concepts in living and bedroom</li>
  <li>Fluted or textured wall panels</li>
  <li>Dedicated design consultant</li>
  <li>5–10 year warranty</li>
</ul>
<p>What's NOT Included</p>
<ul>
  <li>Lead interior designer / concept design</li>
  <li>Natural stone cladding or metal inlays</li>
  <li>Completely bespoke furniture</li>
  <li>Luxury imports (Italian surfaces, etc.)</li>
  <li>Full 3D walkthrough presentations</li>
</ul>
<h3>Premium Materials</h3>
<h4>BWP 710 Grade Plywood (Boiling Waterproof)</h4>
<p>BWP 710 is the gold standard plywood for Indian residential interiors. It can withstand boiling water for a minimum of 72 hours without delamination — which in practical terms means it will survive decades of kitchen steam, monsoon humidity, and bathroom vapour without swelling or coming apart at the joints. This is non-negotiable for premium kitchen carcasses.</p>
<h4>Acrylic Finishes</h4>
<p>Acrylic shutters are made from a high-gloss acrylic film laminated onto an MDF or HDHMR substrate. They produce a mirror-like depth of colour that no regular laminate can replicate. The visual effect — particularly in kitchens and wardrobe sliding doors — is immediately striking. Scratch resistance is moderate; acrylic is not ideal for homes with pets or children who make rough contact with furniture daily.</p>
<h4>PU Painted Surfaces</h4>
<p>Polyurethane (PU) paint applied in a controlled spray environment produces a finish that is smooth, uniform, extremely hard, and available in virtually any colour. Unlike laminates that come in standard sheets, PU can be custom-mixed to any RAL or NCS colour code. PU-painted MDF shutters are the preferred finish for high-end kitchens and wardrobes in premium homes.</p>
<h4>Veneers</h4>
<p>Real wood veneer sliced from natural timber logs and bonded to an MDF substrate gives the warmth, depth and individuality of solid wood without its warping tendencies and cost. No two veneer sheets are identical, making every veneered surface unique. Premium homes often use veneers on wardrobe shutters, TV back panels, and bedroom feature walls.</p>
<h3>Premium Hardware Systems</h3>
<h4>Soft-Close Hinges and Channels</h4>
<p>At this level, every hinge and every drawer channel is soft-close as a minimum standard. Soft-close mechanisms use a hydraulic damper to slow down the last 30° of movement, preventing slamming and the long-term structural damage it causes. This is not a luxury — it is a noise and durability investment that pays back every day for a decade.</p>
<h4>Tandem Box Drawers</h4>
<p>Tandem box drawers (like Hettich's InnoTech or Blum's Tandembox) replace flat-base drawers with a side-walled steel drawer box system. They are stronger, allow full-extension pull-out, are easier to clean, hold greater weight, and the action is noticeably smoother and quieter. Any kitchen claiming to be premium without tandem drawers is cutting corners.</p>
<h4>Lift-Up and Corner Solutions</h4>
<p>Premium kitchens include solutions for difficult corners (magic corners, carousel systems, pull-out units) and upper cabinet lift-up mechanisms (like Blum's Aventos) that replace conventional hinged doors with fluid upward-opening shutters. These dramatically improve the kitchen experience and are invisible differentiators that homeowners feel daily.</p>
<h3>Premium Design Features</h3>
<h4>False Ceiling Concepts</h4>
<p>Premium interiors almost always include a designed false ceiling — not just a plain gypsum box, but a layered concept that incorporates coves, recesses, different ceiling heights, and integrated lighting. The false ceiling ties the room together and frames the furniture below it architecturally.</p>
<h4>Profile Lighting and Fluted Panels</h4>
<p>Integrated LED strip lighting behind or below profiles, inside wardrobes, under kitchen wall cabinets, and within TV units transforms a room from furniture-in-a-box to a curated environment. Fluted wood or MDF panels on feature walls, behind beds, or as wardrobe shutter fronts have become the defining visual language of premium Indian interiors in 2024–26.</p>
<p>Category 04</p>
<h2>Designer Interiors — Fully Explained</h2>
<p>Designer interiors are a fundamentally different product from the other three categories. They are not just more expensive premium interiors — they represent a shift in approach from furniture-making to space design. A designer interior begins not with a catalogue or a module, but with a concept: who lives here, how do they live, what should this space feel like, what story should it tell?</p>
<h3>Designer Interiors — At a Glance</h3>
<p>₹3,000 – ₹6,000+ per sq.ft | 2BHK: ₹18–35+ Lakhs</p>
<p>What's Included</p>
<ul>
  <li>Lead interior designer + design team</li>
  <li>Detailed concept development and mood boards</li>
  <li>Full 3D visualisations and walkthroughs</li>
  <li>Completely bespoke furniture (no catalogues)</li>
  <li>Natural materials: stone, veneer, metal inlays</li>
  <li>Architectural ceiling and wall interventions</li>
  <li>Curated lighting design (fixture selection + layout)</li>
  <li>Lifestyle and storage planning as a whole</li>
  <li>Site supervision by design team</li>
</ul>
<p>The Designer Difference</p>
<ul>
  <li>Every piece is unique to this home and owner</li>
  <li>Materials sourced globally when needed</li>
  <li>The home functions as a complete composition</li>
  <li>Design fees are separate from execution cost</li>
  <li>Longer project timelines (4–9 months typical)</li>
  <li>Multiple revision rounds are standard</li>
</ul>
<h3>What Makes a Home a Designer Home</h3>
<h4>Design-Driven Approach</h4>
<p>In a designer interior, every decision — from the direction of wood grain to the exact height of a ledge, from the depth of a recess to the temperature of a light fitting — is made by a designer who understands how these details accumulate into an experience. Nothing is default. Nothing is picked from a catalogue because it was available.</p>
<h4>Lifestyle Planning</h4>
<p>A good designer doesn't just design rooms — they design for how you actually live. How do you use your kitchen — are you a daily serious cook, or does the kitchen mostly serve weekend guests? Do you work from home? Do you have guests who stay over regularly? These answers shape space planning decisions that a catalogue-driven approach never considers.</p>
<h4>Space Storytelling</h4>
<p>Designer homes have a coherent visual language that runs from the entrance foyer through to the bedroom — a palette, a material vocabulary, a signature detail that repeats and evolves. Walking through the home feels intentional. This is the hardest thing to manufacture — it can only be designed.</p>
<h3>Exclusive Materials in Designer Interiors</h3>
<h4>Natural Veneers and Stone Claddings</h4>
<p>Bookmatched natural stone panels (where two slabs are opened like a book to create a mirror pattern), large-format stone claddings on walls and islands, and rare-species natural veneers are signature materials in designer interiors. These materials are specified, sourced, and supervised by the design team — not off the shelf from a showroom.</p>
<h4>Metal Inlays and Leather Finishes</h4>
<p>Brass, bronze or blackened steel inlays within furniture joinery, leather-wrapped panel surfaces, hand-applied plaster finishes, and hand-beaten metal cabinet pulls are design elements that exist only in the bespoke space. They create a tactile richness that photographs beautifully and ages graciously.</p>
<h3>Advanced Design Deliverables</h3>
<p>A designer project includes a full documentation package before a single piece of wood is cut: mood boards establishing the visual language, material boards showing actual samples of every specified surface, detailed 3D renders of each room from multiple angles, and in many cases a full video walkthrough of the home before execution begins. This investment in pre-visualisation prevents costly changes mid-execution.</p>
