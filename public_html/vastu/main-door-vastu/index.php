<h2>The entrance area</h2>
<ul>
  <li>Bright and well lit, inside and outside.</li>
  <li>Clean and uncluttered; no shoes, dustbins or broken items in front of the door.</li>
  <li>A nameplate on the door or beside it.</li>
  <li>Shoes in a closed cabinet to one side. See <a href="/rooms/foyer-entrance/">foyer and entrance</a>.</li>
  <li>Toranam or a doorway decoration, if the family follows the custom.</li>
</ul>

<h2>What flat owners can do</h2>
<ol>
  <li>Replace a weak or warped door with a solid-core door that opens inwards fully.</li>
  <li>Add a threshold strip and a nameplate.</li>
  <li>Light the entrance well and keep the landing clean.</li>
  <li>Move shoes into a closed cabinet inside, to one side.</li>
</ol>
