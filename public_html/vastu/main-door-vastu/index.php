<h2>Door size, opening and material</h2>
<ul>
  <li><strong>Size:</strong> traditionally the largest door in the home; a common size is 3.5×7 ft.</li>
  <li><strong>Opening:</strong> inwards, clockwise, opening fully without hitting a wall or furniture.</li>
  <li><strong>Material:</strong> solid wood such as teak, or a solid-core engineered or veneered door. See <a href="/doors/flush-vs-solid-wood-door/">flush vs solid wood doors</a>.</li>
  <li><strong>Threshold:</strong> a raised strip of wood, stone or metal at the base.</li>
  <li><strong>Hardware:</strong> a sturdy lock, a door viewer and a quiet hinge.</li>
</ul>
