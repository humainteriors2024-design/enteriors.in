<h2>Applying it to common layouts</h2>
<ul>
  <li><strong>L-shape:</strong> put the hob on the leg nearer the south-east and the sink on the leg nearer the north or east, so the corner separates them.</li>
  <li><strong>Parallel:</strong> hob on one run, sink on the other, the most natural way to keep fire and water apart.</li>
  <li><strong>Straight:</strong> hob at the south or east end, sink at the other, with the longest stretch of counter between.</li>
  <li><strong>Open kitchen:</strong> keep the hob on a wall, not on an island, if you want the cook facing east.</li>
</ul>
<p>Layout trade-offs are explained in <a href="/modular-kitchen/l-shape-vs-u-shape/">L-shape vs U-shape</a>.</p>

<h2>Colours and materials</h2>
<p>Warm and light colours are traditionally preferred: cream, ivory, yellow, peach, orange and light green. Very dark walls are usually avoided, though a dark granite counter is common and accepted. For colour pairings that suit these preferences, see <a href="/blogs/kitchen-colour-combinations/">two-colour kitchen combinations</a>.</p>

<h2>What you can do without building work</h2>
<ol>
  <li>Place the hob and sink as above when the modular kitchen is designed.</li>
  <li>Keep the north-east corner of the kitchen light and free of heavy units.</li>
  <li>Choose light, warm colours for walls and shutters.</li>
  <li>Keep the kitchen clean, ventilated and well lit, which is good practice in any tradition.</li>
</ol>
