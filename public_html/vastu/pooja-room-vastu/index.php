<h2>Inside the pooja space</h2>
<ul>
  <li><strong>Idols:</strong> slightly above floor level, not touching the back wall; larger idols traditionally kept smaller in homes.</li>
  <li><strong>Lamps:</strong> on a stone or brass base, towards the south-east of the unit, with ventilation above.</li>
  <li><strong>Storage:</strong> a drawer or cabinet below for samagri, books and spare lamps.</li>
  <li><strong>Door:</strong> two leaves, or a jaali or glass door that keeps the space visible and ventilated. See <a href="/doors/pooja-room-door-design/">pooja room doors</a>.</li>
  <li><strong>Bells:</strong> on the door or hung inside.</li>
</ul>

<h2>Colours and materials</h2>
<p>Light colours (white, cream, light yellow, light blue) and natural materials are traditionally preferred: marble or light stone for the base, wood or veneer for the unit, and a back panel of Corian, quartz or marble that will not stain with oil or kumkum. Materials and designs are in the <a href="/rooms/pooja-room/">pooja room guide</a>.</p>

<h2>In a small flat</h2>
<ol>
  <li>Choose a quiet corner on the north-east side of the living or dining area.</li>
  <li>A wall-mounted unit at chest height saves floor space.</li>
  <li>Keep it off a shared wall with a toilet.</li>
  <li>Plan a light point and a 5A socket, and a stone base for lamps.</li>
</ol>
