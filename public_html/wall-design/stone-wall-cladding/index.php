<h2>Formats: what you are actually buying</h2>
<ul>
  <li><strong>Ledge or stack panels:</strong> strips of split stone pre-assembled on a backing, usually 150 × 600 mm. The quickest to install and the most popular for feature walls.</li>
  <li><strong>Mosaic or random pieces:</strong> individual stones set by hand. More labour, more natural.</li>
  <li><strong>Thin veneer slabs:</strong> 10–20 mm slabs with a sawn back, for a smooth or honed wall.</li>
  <li><strong>Engineered stone and faux panels:</strong> cast or moulded copies, lighter and uniform.</li>
</ul>

