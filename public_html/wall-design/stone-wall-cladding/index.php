<h2>Faux stone: when it makes sense</h2>
<p>Moulded polyurethane, polymer-concrete and fibre-cement panels copy the look of stone at a fraction of the weight. They suit gypsum partitions, upper-floor flats where weight matters, rentals and quick makeovers. Their weaknesses are repetition (the same mould pattern appearing again), lower durability, and, for PU panels, softening and fading in direct sun. Indoors and away from heat, a good faux panel lit well can be convincing; outdoors, natural stone or fibre-cement is safer.</p>

<h2>Lighting stone</h2>
<p>Split-face stone is all about shadow. Light it from above at a grazing angle: a linear LED in a ceiling slot 100–200 mm from the wall, or narrow-beam downlights close to it. Warm white (2700–3000 K) brings out sandstone and slate; neutral white (3500–4000 K) suits grey quartzite and granite. Light from straight ahead makes even the best stone look flat.</p>
