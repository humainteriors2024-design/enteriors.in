<h2>Fixing stone safely</h2>
<ol>
  <li><strong>Prepare the wall.</strong> Sound, dry, clean plaster or block. Hack smooth plaster for grip, or apply a bonding coat.</li>
  <li><strong>Use the right adhesive.</strong> A polymer-modified, cement-based stone adhesive (often specified as C2 class) applied to both the wall and the back of the stone. Ordinary cement mortar alone is not enough above head height.</li>
  <li><strong>Add mechanical anchors</strong> for heavy stone, exterior walls above about 3 m and any piece over roughly 20 kg: stainless steel clamps or pins into the wall.</li>
  <li><strong>Leave movement joints</strong> on large exterior walls, as advised by the stone supplier.</li>
  <li><strong>Seal</strong> natural stone with a penetrating (impregnating) sealer once the adhesive has cured.</li>
</ol>
<div class="callout callout--warn"><span class="callout__title">Never on a drywall alone</span>Gypsum board partitions cannot carry natural stone. Use a lightweight faux panel, or build the wall with a cement board backing and extra studs designed for the load.</div>

<h2>Keeping stone looking good</h2>
<ul>
  <li><strong>Efflorescence:</strong> white salts mean water is moving through the wall. Fix the water source; brush the salts off dry; reseal.</li>
  <li><strong>Algae on exteriors:</strong> common on north-facing and shaded walls in the monsoon. A biocidal wash and a breathable water-repellent sealer help.</li>
  <li><strong>Oil and dust indoors:</strong> sealed stone can be dusted and wiped; avoid acidic cleaners on marble and limestone.</li>
</ul>

<h2>Designing with stone</h2>
<p>Stone works best as one strong surface: the TV wall, the foyer wall, a staircase wall or a façade band. Pair rough stone with smooth, quiet surfaces around it, warm wood and matt paint, and graze it with light from above. Combine it with panelling in the <a href="/wall-design/wall-panelling/">wall panelling guide</a>, or see the cheaper, lighter options in <a href="/wall-design/pvc-vs-wpc-wall-panels/">PVC vs WPC panels</a>.</p>
<h2>Indian stones by region</h2>
