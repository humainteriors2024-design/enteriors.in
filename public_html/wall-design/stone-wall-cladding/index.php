<h2>Stone on façades and balconies</h2>
<ul>
  <li><strong>Waterproof first:</strong> a cementitious or polymer waterproof coat on the wall behind the stone.</li>
  <li><strong>Drip details:</strong> sills and copings that throw rain away from the stone face.</li>
  <li><strong>Mechanical anchors</strong> above head height and on large pieces, in stainless steel.</li>
  <li><strong>Light colours on west faces:</strong> dark stone absorbs heat and warms the room behind.</li>
  <li><strong>Algae:</strong> shaded walls need a breathable water-repellent and occasional cleaning.</li>
</ul>
