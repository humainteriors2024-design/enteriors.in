<h2>Before you decide</h2>
<ul>
  <li>Can the wall carry the weight (brick, block or concrete), or is it a drywall partition?</li>
  <li>Is the wall dry, with no seepage history? Check after a heavy rain.</li>
  <li>Indoors or outdoors? Choose low-absorption stone outside and seal it.</li>
  <li>Where will the light come from? Plan a grazing light before the ceiling is closed.</li>
  <li>Have you seen a full box of the stone? Natural stone varies; one sample tile can mislead.</li>
</ul>
