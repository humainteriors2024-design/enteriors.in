<h2>Common mistakes</h2>
<ul>
  <li>Cladding a damp wall: the stone stains and efflorescence appears within months.</li>
  <li>Using ordinary cement mortar alone on high or heavy stone.</li>
  <li>Unsealed sandstone in kitchens and dining rooms: oil marks are permanent.</li>
  <li>Acid cleaners on marble and limestone.</li>
  <li>Too much stone: a whole room in split-face stone feels like a cave. One wall is enough.</li>
</ul>
