<h2>Terms explained</h2>
<dl class="terms">
  <dt>Split face</dt><dd>A rough, natural surface made by splitting stone rather than sawing it; shows strong shadows.</dd>
  <dt>Ledge (stack) panel</dt><dd>Strips of stone bonded in an interlocking pattern on a backing, usually 150 × 600 mm, installed like large tiles.</dd>
  <dt>Water absorption</dt><dd>How much water a stone takes up by weight. Low-absorption stones (granite, quartzite, slate) stain and weather less than high-absorption ones (many sandstones).</dd>
  <dt>Efflorescence</dt><dd>White, powdery salts left on the surface when water moving through the wall or adhesive evaporates.</dd>
  <dt>Back-buttering</dt><dd>Applying adhesive to the back of the stone as well as the wall, so there are no hollow spots behind it.</dd>
  <dt>Impregnating sealer</dt><dd>A sealer that soaks into the stone and repels water and oil without forming a shiny film.</dd>
  <dt>Mechanical anchor</dt><dd>A stainless steel clamp, pin or bracket that holds stone to the wall independently of the adhesive.</dd>
</dl>
