<h2>How to judge an applicator</h2>
<ul>
  <li><strong>Portfolio of finished walls</strong> you can visit, not just photographs.</li>
  <li><strong>The product system</strong> named in the quote: primer, texture and top coat by brand and product.</li>
  <li><strong>Sample on your wall</strong>, approved and kept until the job is finished, as the reference.</li>
  <li><strong>One person per wall:</strong> two applicators on the same wall produce two textures.</li>
  <li><strong>Masking and cleanliness:</strong> textures splatter; floors, switches and adjoining walls must be covered.</li>
</ul>
