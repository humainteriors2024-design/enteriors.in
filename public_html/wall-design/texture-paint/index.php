<h2>Texture trends in 2026</h2>
<p>The strongest direction is soft, mineral and warm: limewash, clay-look and microcement-style finishes in beige, greige, clay and muted terracotta. Rough "rustic" combing and metallic gold textures are fading. Matt finishes dominate; sheen is used only as a subtle burnish. See <a href="/trends/limewash-textures/">limewash textures</a> and <a href="/trends/warm-neutrals/">warm neutrals</a>.</p>
