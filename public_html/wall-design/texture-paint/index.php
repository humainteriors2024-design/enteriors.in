<h2>Before you decide</h2>
<ul>
  <li>Which single wall will carry the texture, and what light will graze it?</li>
  <li>Is the plaster dry and cured, with cracks repaired?</li>
  <li>Indoor or exterior product? They are not interchangeable.</li>
  <li>Will anything be fixed to the wall later? Drill and fix it before texturing.</li>
  <li>Is the colour mid or light? Very dark textures show every touch-up.</li>
  <li>Is the product system (primer, texture, top coat) named in the quote?</li>
</ul>
<p>Texture is a craft finish: the same product looks different in different hands. A visit to a finished wall by the same applicator is worth more than any brochure.</p>
