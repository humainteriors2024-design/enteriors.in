<h2>Common mistakes</h2>
<ul>
  <li>Texture on every wall: heavy, dusty and hard to repaint.</li>
  <li>Dark colours on deep textures: every touch-up shows.</li>
  <li>Texturing over damp or fresh plaster: blistering and efflorescence.</li>
  <li>No light planned: the texture disappears at night.</li>
  <li>Drilling after finishing: patches never match. Fix brackets, curtain rods and art hooks before the texture goes on.</li>
</ul>
