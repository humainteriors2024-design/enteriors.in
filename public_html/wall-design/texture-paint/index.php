<p>Texture paint is the most affordable way to make one wall feel designed. It hides small imperfections in the plaster, adds shadow and depth, and works outdoors as well as indoors. The catch is that the result depends almost entirely on the applicator's hand, so it pays to understand the types and to approve a large sample. This page is part of the <a href="/wall-design/">wall design guide</a>.</p>

<h2>What texture paint is</h2>
<p>Texture coatings are acrylic or mineral binders loaded with fillers such as fine sand, calcium carbonate or marble powder. They go on thicker than paint, typically 1–3 mm, and are shaped while wet. Most systems have three layers: a primer, the texture coat, and one or two finish coats of emulsion or a glaze that colour and protect it.</p>

