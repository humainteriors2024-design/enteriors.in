<h2>Choosing a texture for the room</h2>
<ul>
  <li><strong>Living room:</strong> soft trowel, stucco or limewash on the TV or sofa wall; fine sand finishes for a modern look.</li>
  <li><strong>Bedroom:</strong> low-relief finishes only. Deep textures behind a bed collect dust and are rough to lean on.</li>
  <li><strong>Passages and stair walls:</strong> sand or comb textures hide scuffs better than smooth paint.</li>
  <li><strong>Exteriors and balconies:</strong> exterior-grade textures with a dirt-resistant top coat; avoid deep patterns that hold algae in heavy-rain areas.</li>
  <li><strong>Avoid:</strong> kitchens and bathrooms (grease and moisture settle in the relief), and walls you plan to wallpaper later.</li>
</ul>

<h2>Light decides how a texture looks</h2>
<p>Texture is shadow. Light falling straight onto a wall flattens it; light grazing across it from the top or side brings out every ridge. A linear LED wall washer or a cove 150–300 mm from the wall shows the texture at night. The same grazing light also exaggerates poor work, so check samples under it before approving.</p>
<div class="callout callout--tip"><span class="callout__title">Approve a real sample</span>Ask the applicator for a 2 × 2 ft sample on your own wall, in your chosen colour, finished with the top coat. Look at it in daylight and at night with your planned lighting. Photos on a phone never show texture accurately.</div>

<h2>Colour with texture</h2>
<p>Most textures are finished in a mid or light colour; very dark colours on a textured wall exaggerate unevenness and make touch-ups visible. Two-tone systems (a darker base glazed with a lighter top, or the reverse) give depth. For combinations, see the <a href="/colour/living-room-colour-combination/">living room colour combinations</a> and the <a href="/colour/paint-finishes/">paint finishes guide</a>.</p>

<h2>Preparation and process</h2>
<ol>
  <li>Repair cracks and seepage; let new plaster cure for at least four weeks.</li>
  <li>Apply a primer suited to the product (alkali-resistant on fresh plaster).</li>
  <li>Apply and shape the texture coat in one session per wall, so there are no joint lines.</li>
  <li>Allow it to dry fully, often 12–24 hours.</li>
  <li>Apply the finish coats or glaze.</li>
</ol>
<p>A single feature wall usually takes two to three days including drying. Plan it after electrical and carpentry work, so that nobody drills into the finished wall.</p>

<h2>Texture paint or panelling?</h2>
<p>For a 90 sq ft TV wall, texture costs roughly ₹4,000–13,500 against ₹16,000–34,000 for WPC fluted panels and ₹32,000 or more for veneer panelling (indicative, before GST). Texture cannot hide wiring or hold a TV bracket by itself, so if the wall needs both, combine a panelled TV section with texture around it. Compare the options in <a href="/wall-design/wall-panelling/">wall panelling design</a>.</p>
