<h2>Terms explained</h2>
<dl class="terms">
  <dt>Texture coat</dt><dd>The thick, filler-rich middle layer that is shaped into a pattern while wet.</dd>
  <dt>Stucco</dt><dd>A plaster-like finish built from several thin trowelled layers; can be left matt or burnished to a soft sheen.</dd>
  <dt>Limewash</dt><dd>A paint based on slaked lime, brushed on in crossing strokes for a cloudy, breathable, chalky finish.</dd>
  <dt>Glaze</dt><dd>A thin, translucent tinted coat over a texture that settles into the recesses and adds depth.</dd>
  <dt>Elastomeric coating</dt><dd>A flexible exterior coating that stretches over hairline cracks and keeps rain out.</dd>
  <dt>Alkali-resistant primer</dt><dd>A primer that protects paint from the alkalis in fresh cement plaster, which otherwise cause patchy colour and peeling.</dd>
  <dt>Grazing light</dt><dd>Light that strikes a wall at a shallow angle, revealing every ridge and hollow of a texture.</dd>
</dl>
