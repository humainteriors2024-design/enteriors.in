<h2>Profiles and joint patterns</h2>
<p>The joint pattern decides the style more than the material does.</p>
<ul>
  <li><strong>Vertical grooves</strong> (V or U grooves, 3–6 mm wide, every 75–150 mm) make a ceiling look higher. The safest choice for TV walls.</li>
  <li><strong>Horizontal planks</strong> widen a narrow room and suit bedrooms with low ceilings.</li>
  <li><strong>Large square or rectangular panels</strong> with shadow gaps give a calm, gallery look and suit veneer.</li>
  <li><strong>Fluting</strong> (rounded ribs) adds strong texture; keep it to one section of the wall and light it from above.</li>
  <li><strong>Classic moulded panels</strong> (picture-frame mouldings) suit transitional and neoclassical interiors, usually painted.</li>
</ul>
<div class="callout callout--tip"><span class="callout__title">Plan the joints around fixed points</span>Draw the panel layout so that joints, not panel faces, fall at switchboards, the TV bracket and the edges of furniture. Cut-outs in the middle of a veneer sheet always look like an afterthought.</div>

<h2>Wiring, TV mounting and lighting</h2>
<ul>
  <li><strong>Back the TV bracket.</strong> Fix a block of 18 mm plywood into the frame behind the bracket position, or bolt the bracket through to the wall. Panel faces alone will not carry a 55-inch TV.</li>
  <li><strong>Run conduits before boarding.</strong> HDMI, power and LAN in a 25–32 mm conduit from the TV to the set-top box or media unit, with a pull cord left inside.</li>
  <li><strong>Leave access.</strong> One removable panel near the TV makes later changes possible.</li>
  <li><strong>Light it.</strong> A slim LED profile at the top or along a vertical joint brings out grain and grooves. Use warm white (2700–3000 K) with a CRI of 90 or more for wood.</li>
</ul>
<p>The <a href="/furniture/tv-unit-design/">TV unit design guide</a> covers mounting heights and viewing distances.</p>

<h2>Moisture, heat and termites</h2>
<p>Panels fail at the edges. Edge-band or seal every cut edge, keep a 3–5 mm expansion gap at the floor and ceiling, and never panel a wall with active damp. In termite-prone ground-floor homes, use treated battens and a borer-proof board, and ask for anti-termite treatment of the wall behind. WPC panels resist both moisture and termites but expand in heat, so they need the expansion gaps specified by the maker; see <a href="/wall-design/pvc-vs-wpc-wall-panels/">PVC vs WPC wall panels</a>.</p>

