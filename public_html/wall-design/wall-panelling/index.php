<h2>Care and repair</h2>
<ul>
  <li><strong>Laminate:</strong> wipe with a damp cloth and mild soap; avoid abrasive pads.</li>
  <li><strong>Veneer with PU:</strong> dust with microfibre; a fresh PU coat every 7–10 years if worn.</li>
  <li><strong>Painted panels:</strong> touch up chips with the original paint code.</li>
  <li><strong>Fabric:</strong> vacuum monthly with a brush head; spot-clean with upholstery cleaner.</li>
  <li><strong>Damage:</strong> one advantage of batten fixing is that a single damaged panel can be unscrewed and replaced.</li>
</ul>

<h2>Panelling trends for 2026</h2>
<p>The look has moved from busy to calm. Full-height veneer with fine grooves, warm mid-tone woods (walnut, smoked oak), slim fluting used in one band, and fabric or leather panels behind beds are the strongest directions. Mixed mirror strips, high-gloss laminates and multiple materials on one wall are fading. See <a href="/trends/fluted-panels/">fluted panels</a> and <a href="/trends/warm-neutrals/">warm neutrals</a>.</p>
