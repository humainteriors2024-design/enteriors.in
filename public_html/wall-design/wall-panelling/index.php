<h2>Installation sequence</h2>
<ol>
  <li>Mark the elevation on the wall: TV centre (about 1000–1100 mm from the floor), switches, joints.</li>
  <li>Fix conduits and test them with a pull cord.</li>
  <li>Fix battens with plugs and screws, packed level; add the TV backing block.</li>
  <li>Fix boards with screws into battens (concealed in grooves) or with clips; keep expansion gaps.</li>
  <li>Edge-band or seal all cut edges; fit skirting and end trims.</li>
  <li>For veneer: sand, stain if needed, and apply PU in several coats with drying time between.</li>
  <li>Fit lights, switch plates and finally the TV.</li>
</ol>
