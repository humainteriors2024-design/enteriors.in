<h2>Terms explained</h2>
<dl class="terms">
  <dt>PVC (polyvinyl chloride)</dt><dd>A rigid plastic made stable for building use with additives called stabilisers. Older stabilisers contained lead; modern ones use calcium-zinc or organic systems.</dd>
  <dt>WPC (wood-plastic composite)</dt><dd>A blend of polymer (often PVC) and fine wood flour, extruded into boards and profiles. The wood content adds stiffness and a wood-like feel.</dd>
  <dt>UV marble sheet</dt><dd>A thin PVC sheet printed with a stone pattern and finished with an ultraviolet-cured coating that gives a hard, glossy surface.</dd>
  <dt>Fluted panel</dt><dd>A panel with rounded vertical ribs. Louvred panels have flat-faced, angled ribs.</dd>
  <dt>Expansion gap</dt><dd>A small gap left at panel ends and edges so the panel can grow in heat without buckling; usually hidden by a trim.</dd>
  <dt>VOC</dt><dd>Volatile organic compounds: chemicals that evaporate at room temperature from adhesives, plastics and paints and affect indoor air quality.</dd>
</dl>
