<p>PVC and WPC panels are sold side by side in every hardware market, often by the same shop, and often described with the same words: waterproof, termite-proof, no polish needed. That is true of both. Where they differ is density, stiffness and how they behave with heat, and those decide where each belongs. This comparison is part of the <a href="/wall-design/">wall design guide</a>.</p>

<h2>What each panel is made of</h2>
<p><strong>PVC panels</strong> are extruded or calendered from rigid polyvinyl chloride with stabilisers and fillers. They come as hollow tongue-and-groove strips (common for ceilings and utility walls) or as thin solid sheets, often 2.5–3 mm, printed with stone or wood and finished with a UV-cured gloss coat (sold as "UV marble sheets").</p>
<p><strong>WPC panels</strong> (wood-plastic composite) are extruded from PVC or another polymer mixed with fine wood flour and a foaming agent. The result is a solid or ribbed profile, typically 8–15 mm deep for fluted panels, that is much denser than PVC strips and can be sanded and screwed like wood.</p>

