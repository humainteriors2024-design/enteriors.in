<h2>Before you decide</h2>
<ul>
  <li>Is the wall dry and sound? If not, fix it first.</li>
  <li>Will the panel face direct sun, a heater or a stove? Choose WPC with UV stabilisers, or another material.</li>
  <li>Does the wall need to hide wiring? Plan battens and conduits.</li>
  <li>Is it a rental? Choose clip-fixed WPC or PVC on a ply backing that can be removed.</li>
  <li>Have you seen a large sample in your own light, beside your floor and furniture?</li>
</ul>
