<h2>Heat, sun and expansion: the main failure</h2>
<p>Most complaints about plastic panels are not about water but about heat: panels bowing behind a TV, warping beside a west-facing window, or softening above a stove. Plastics expand far more with temperature than wood or plaster do. The fixes are simple:</p>
<ul>
  <li>Leave the expansion gaps the manufacturer specifies at all ends and edges.</li>
  <li>Fix WPC mechanically (clips or concealed screws), so panels can move without buckling.</li>
  <li>Keep a ventilated gap behind TVs and amplifiers; do not box electronics against panels.</li>
  <li>Use exterior-grade, UV-stabilised panels on walls that get direct afternoon sun.</li>
  <li>Keep at least 300 mm between panels and any cooking flame or heater.</li>
</ul>
