<h2>Where neither belongs</h2>
<ul>
  <li>Directly behind a gas hob or tandoor.</li>
  <li>Escape routes and common corridors in buildings that require fire-rated finishes.</li>
  <li>Walls with active seepage: panels hide the problem while it grows. Fix the wall first.</li>
  <li>Bedrooms where the family is sensitive to smells, unless the product's emission tests are available.</li>
</ul>

<h2>The alternatives</h2>
<p>If you want water resistance without plastic, consider tiles or quartz in wet areas, sealed stone on feature walls (<a href="/wall-design/stone-wall-cladding/">stone cladding</a>), or BWR plywood panelling with laminate in humid rooms (<a href="/wall-design/wall-panelling/">wall panelling</a>). For colour and pattern on a budget, <a href="/wall-design/wallpaper-guide/">vinyl wallpaper</a> is often the better choice than printed PVC.</p>
