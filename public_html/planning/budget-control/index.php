<p>A good interior budget is not a single number. It is a number, a split by room, a reserve for surprises and a set of rules for change. This page walks through each, using the same rates as our <a href="/cost/">interior cost guide</a>. It is part of the <a href="/planning/">home planning guide</a>.</p>

