<h2>Step 3: keep a contingency</h2>
<p>Keep 10–15% of the contract outside it. Typical surprises: damp walls that need treatment, extra electrical points, a countertop upgrade, society charges, a wardrobe that has to move a switchboard. If none happen, the contingency buys furniture. Common surprises are listed in <a href="/blogs/hidden-costs-home-interiors/">hidden costs in home interiors</a>.</p>

<h2>Step 4: tie payments to milestones</h2>
<ol class="steps">
  <li><strong>Booking</strong>A small amount to start the design.</li>
  <li><strong>Design sign-off and production</strong>The largest share, once drawings, specification and quote are final.</li>
  <li><strong>Delivery</strong>Before modules leave the factory.</li>
  <li><strong>Handover</strong>The balance, with 5–10% held until the snag list is closed.</li>
</ol>

<h2>Step 5: control change</h2>
<ul>
  <li>Freeze the scope and specification before signing.</li>
  <li>Every change gets a written price and your signature before work starts.</li>
  <li>Keep a running sheet: contract + approved changes = current total.</li>
  <li>Say no to "while we are here" additions unless they come out of the contingency.</li>
</ul>

