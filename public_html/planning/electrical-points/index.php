<h3>False Ceiling Lighting Zones — Best Practice</h3>
<ul>
  <li><strong>Zone 1 — General (Downlights):</strong> Main functional lighting, switched separately</li>
  <li><strong>Zone 2 — Cove / Mood (LED Strip):</strong> Warm ambience, on dimmer or separate switch</li>
  <li><strong>Zone 3 — Accent (Spots/Pendants):</strong> Feature highlighting, switchable independently</li>
  <li>Never put all ceiling lights on one switch — you lose all lighting control flexibility</li>
  <li>Plan LED driver box locations in false ceiling cavities BEFORE board is installed</li>
  <li>Allow minimum 4-inch (100mm) depth for recessed downlights from bottom of slab</li>
  <li>Cove LED strips need continuous conduit run — plan the strip length before ordering</li>
</ul>
