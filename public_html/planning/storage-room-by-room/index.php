<h2>Five rules that add storage</h2>
<ol>
  <li><strong>Go to the ceiling.</strong> A loft over every wardrobe and kitchen wall unit adds 25–30% storage.</li>
  <li><strong>Drawers, not deep shelves,</strong> at waist height in the kitchen and wardrobes.</li>
  <li><strong>Store by frequency:</strong> daily items between knee and eye level, rarely used items above.</li>
  <li><strong>Use hidden spaces:</strong> bed bases, under stairs, window seats, above doors, inside the false ceiling for suitcases (with a hatch).</li>
  <li><strong>One closed tall unit per room</strong> keeps clutter off open shelves.</li>
</ol>

