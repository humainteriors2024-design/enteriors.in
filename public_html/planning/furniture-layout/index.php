<h2>Room by room</h2>
<h3>Living room</h3>
<ul>
  <li>Place the sofa on the longest solid wall facing the TV wall, not with its back to the front door if you can avoid it.</li>
  <li>Keep the walkway from the door to the rest of the home behind the sofa or beside it, never between the sofa and the TV.</li>
  <li>A rug under the front legs of all seats ties the group together.</li>
</ul>
<h3>Dining</h3>
<ul>
  <li>Put the table near the kitchen door and 3 ft clear all round. See <a href="/rooms/dining-room/">dining room design</a>.</li>
</ul>
<h3>Bedroom</h3>
<ul>
  <li>Bed head against a solid wall, not under a window if possible.</li>
  <li>Wardrobe on the wall where the gap to the bed is greatest; under 2.5 ft, choose sliding doors.</li>
  <li>Keep switches for the main light reachable from the bed.</li>
</ul>
<p>Details are in <a href="/rooms/master-bedroom/">master bedroom design</a>.</p>
<h3>Study</h3>
<ul>
  <li>Desk at right angles to the window; see <a href="/rooms/study-home-office/">study and home office</a>.</li>
</ul>

<h2>How to plan on paper</h2>
<ol class="steps">
  <li><strong>Measure</strong>Wall lengths, door and window positions and widths, ceiling height, beams, switches, AC and plumbing points.</li>
  <li><strong>Draw to scale</strong>Graph paper at 1 square = 6 inches, or a free planning app.</li>
  <li><strong>Mark door swings</strong>Every door's arc, including wardrobe shutters.</li>
  <li><strong>Place the large pieces first</strong>Bed, sofa, dining table, wardrobes and the TV wall.</li>
  <li><strong>Check the routes</strong>Draw the walking lines; each should be at least 2–3 ft wide.</li>
  <li><strong>Fix the electricals</strong>Move switches and sockets to suit the layout before walls are painted. See <a href="/planning/electrical-points/">electrical points</a>.</li>
</ol>

<h2>Common mistakes</h2>
<ul>
  <li>Buying an L-shaped sofa before measuring the room.</li>
  <li>A wardrobe that covers a switchboard or an AC point.</li>
  <li>A dining table in the main walkway.</li>
  <li>The TV opposite a window, so glare washes out the screen.</li>
</ul>
