</ul>
<h4>Ergonomics</h4>
<ul>
  <li>Work triangle optimisation (hob–sink–fridge)</li>
  <li>Counter height (standard 850mm, adjust for height)</li>
  <li>Storage accessibility at different heights</li>
</ul>
