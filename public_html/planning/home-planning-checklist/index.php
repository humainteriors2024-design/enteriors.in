<h2>Finish Selection Checklist</h2>
<h4>Laminates — Consider</h4>
<ul>
  <li>Matte</li>
  <li>Glossy</li>
  <li>Suede</li>
  <li>Textured</li>
  <li>Acrylic</li>
  <li>Scratch resistance</li>
