  <li>Crockery storage</li>
  <li>Buffet unit requirement</li>
</ul>
<h4>Bedrooms</h4>
<ul>
  <li>Bed size</li>
  <li>Wardrobe capacity</li>
  <li>Study area</li>
  <li>Dressing area</li>
  <li>TV provision</li>
</ul>
<h4>Kitchen</h4>
<ul>
  <li>Cooking style</li>
  <li>Storage volume</li>
  <li>Appliance requirements</li>
  <li>Utility area planning</li>
</ul>
