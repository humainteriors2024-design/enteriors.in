  <li>Corner storage units</li>
</ul>
<p>06 / 20</p>
<h2>Material Selection Checklist</h2>
<p>The longevity of your interiors depends almost entirely on the materials used beneath the finishes. Don't compromise here.</p>
<h4>Plywood Selection</h4>
<ul>
  <li>MR Grade — Moisture Resistant (dry areas)</li>
  <li>BWR Grade — Boiling Water Resistant (kitchens, bathrooms)</li>
  <li>BWP Grade — Boiling Water Proof (maximum durability)</li>
</ul>
<h4>Board Materials Comparison</h4>
<ul>
  <li>Plywood — high strength, best for structural use</li>
  <li>HDHMR — dense, smooth, good for painted finishes</li>
  <li>MDF — uniform, ideal for routed profiles</li>
  <li>Particle Board — budget option, avoid in wet areas</li>
</ul>
<h4>Selection Factors</h4>
<ul>
  <li>Moisture resistance</li>
  <li>Load-bearing capacity</li>
  <li>Durability</li>
  <li>Budget</li>
  <li>Warranty</li>
</ul>
