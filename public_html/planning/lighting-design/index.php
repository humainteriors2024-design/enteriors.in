<h4>❌ Kitchen Lighting Don'ts</h4>
<ul>
  <li>Never use only one central ceiling fitting</li>
  <li>Avoid 2700K — it distorts food colour accuracy</li>
  <li>Don't place downlights behind where you stand to cook</li>
  <li>Avoid decorative pendants as primary kitchen light</li>
  <li>Don't skip dimming on island pendants if you have them</li>
</ul>
