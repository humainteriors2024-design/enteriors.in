</ul>
<h3>Under-Cabinet Lighting: Non-Negotiable</h3>
<p>Under-cabinet LED strips are the single most impactful addition to any Indian modular kitchen — and the most commonly skipped. Without them, the upper cabinet casts a shadow exactly where you need light most: on the chopping board and stove. A 4000K LED strip recessed into an aluminium channel under every upper cabinet costs under ₹3,000 for a typical kitchen and completely transforms usability.</p>
<h4>✅ Kitchen Lighting Dos</h4>
<ul>
  <li>Use 4000K throughout for accurate colour rendering</li>
  <li>Install under-cabinet strips as a priority</li>
  <li>Place a dedicated downlight directly above the hob</li>
  <li>Use IP44-rated fittings near wet zones</li>
  <li>Ensure minimum 300 lux at all work surfaces</li>
