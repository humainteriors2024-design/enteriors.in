<p>Block board looks like plywood from the face but is built differently inside: instead of many thin cross-laid veneers, it has a thick core of softwood strips. That gives it different strengths. This page explains when to choose it. It is part of our <a href="/materials/">interior materials guide</a>.</p>

<h2>How block board is made</h2>
<p>Strips of softwood, typically pine or a similar species, about 25 mm wide, are glued edge to edge to form a core. One or two veneers are glued crosswise on each face and the board is pressed. The standard in India is IS 1659. Common thicknesses are 19, 25 and 30 mm.</p>

