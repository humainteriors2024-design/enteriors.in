<h2>Where block board works best</h2>
<ul>
  <li>Long book and display shelves.</li>
  <li>Bed bases and headboards.</li>
  <li>Dining and study tabletops.</li>
  <li>Large doors and sliding wardrobe shutters, where low weight helps the track.</li>
</ul>

<h2>Where to avoid it</h2>
<ul>
  <li>Kitchen and bathroom cabinets.</li>
  <li>Carcass sides with many hinges and drawer channels.</li>
  <li>Thin cuts and narrow strips, where the core can split.</li>
</ul>

<h2>Buying tips</h2>
<ol>
  <li>Look for the IS 1659 mark and the brand on the face.</li>
  <li>Check the edge: strips should be tight with no gaps or filler.</li>
  <li>Use a 1 mm laminate or a veneer on both faces to balance the board.</li>
  <li>Seal all edges with edge banding.</li>
</ol>
