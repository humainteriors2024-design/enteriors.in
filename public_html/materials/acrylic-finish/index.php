<h2>Common problems and how to prevent them</h2>
<h3>Fingerprints</h3>
<p>Gloss reflects light so evenly that skin oil shows as a smudge. It is not a defect. Use matte on every door you open daily, and keep gloss for upper cabinets, island fronts and panels you rarely touch.</p>
<h3>Fine scratches</h3>
<p>They come from gritty cloths, rings and keys, and sliding utensils against doors. Clean only with a clean microfibre cloth, fit soft-close hinges and channels, and avoid dark gloss on lower cabinets.</p>
<h3>Visible or lifting edges</h3>
<p>Poorly matched or poorly glued edge bands are the most common acrylic complaint. Ask for PUR (polyurethane reactive) edge banding, which gives a thinner, more water-resistant joint than ordinary EVA glue, and check the colour match on a sample before approving.</p>
<h3>Glare</h3>
<p>Strong sun or badly aimed downlights can bounce off gloss doors into your eyes while you cook. Aim under-cabinet lights at the counter, not the doors, and choose matte in very sunny kitchens.</p>
<h3>Repairs</h3>
<p>Unlike PU paint, acrylic cannot be touched up on site. A chipped or heat-damaged shutter is replaced. Order one or two spare shutters from the same production batch so the colour matches later.</p>
