<p>Acrylic is the finish most people point at in a showroom: the deep red kitchen, the mirror-smooth white wardrobe. It is also the finish with the widest gap between what is sold and what is delivered, because several different products share the name. This guide explains what to ask for, where acrylic is worth paying for, and how to avoid the fingerprints and scratches that give it a bad reputation.</p>

<h2>What an acrylic shutter actually is</h2>
<p>An acrylic shutter has three layers. A coloured polymer sheet, usually about 1 mm thick, gives the colour and shine. It is pressed onto a core board, normally 18 mm MDF or HDHMR, which provides strength and holds the hinge screws. The four edges are then sealed with a matching edge band. The sheet is never used on its own as furniture.</p>
<p>Two quite different sheets are sold as "acrylic":</p>
<div class="pros-cons">
  <div><span class="pros-cons__title">PMMA acrylic sheet</span><ul><li>Solid polymethyl methacrylate, colour through its thickness</li><li>Deep, glass-like colour, especially in dark shades</li><li>Better UV stability when made with stabilisers</li><li>The more expensive option</li></ul></div>
  <div><span class="pros-cons__title">Gloss-coated PVC or PET film</span><ul><li>A thinner plastic film with a glossy top layer</li><li>Looks similar at a distance, flatter up close</li><li>More prone to yellowing and surface wear over time</li><li>Cheaper, and common in budget "acrylic" kitchens</li></ul></div>
</div>
<div class="callout callout--warn"><span class="callout__title">Ask in writing</span>Ask whether the product is a PMMA sheet or a coated film, the sheet thickness, and the core board. Get all three written into the quotation.</div>

<h3>Which core board to use</h3>
<ul>
  <li><strong>HDHMR:</strong> the right choice for kitchens and anywhere near water. It resists swelling better than MDF.</li>
  <li><strong>MDF:</strong> fine for bedroom wardrobes and TV units in dry rooms. Its very flat surface gives a clean gloss.</li>
  <li><strong>Plywood:</strong> strong and good at holding screws, but its layers can show as a faint ripple under high gloss. Better with matte sheets.</li>
</ul>

