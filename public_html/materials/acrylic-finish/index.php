<h2>Cleaning and care</h2>
<div class="pros-cons">
  <div><span class="pros-cons__title">Do</span><ul><li>Dust with a dry microfibre cloth</li><li>Use a few drops of mild dish soap in water for grease</li><li>Wipe in straight lines, then dry at once</li><li>Spray cleaner onto the cloth, never onto the door</li><li>Check edge bands near the sink every few months</li></ul></div>
  <div><span class="pros-cons__title">Don't</span><ul><li>Scrubbers, steel wool or melamine sponges</li><li>Ammonia, alcohol, acetone or thinner</li><li>Powder cleaners of any kind</li><li>Hot pans or kettles leaning on doors</li><li>Leaving water standing on edges</li></ul></div>
</div>
<p>Share these rules with anyone who cleans the kitchen. Most early scratches come from a single wrong scrubber.</p>

<h2>Checking quality before you approve</h2>
<ul class="ticks">
  <li>Sheet type (PMMA or film) and thickness are written on the quotation</li>
  <li>The core is HDHMR for kitchen shutters, MDF or HDHMR for dry rooms</li>
  <li>Edge banding is PUR and matches the face colour in daylight and warm light</li>
  <li>A sample shows a clean reflection: hold a straight edge near it and check the reflected line is not wavy</li>
  <li>The sheet has UV stabilisers if the kitchen gets direct sun</li>
  <li>The warranty covers edge lifting and delamination, not just the board</li>
  <li>Spare shutters from the same batch are included or priced</li>
</ul>
