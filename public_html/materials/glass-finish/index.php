<h3>Fluted Glass — The Defining Interior Finish of 2026</h3>
<p>Fluted glass features a series of parallel vertical channels (the "flutes") pressed or rolled into the glass surface during manufacture. These channels catch and refract light, creating a visual play of shadow and brightness that shifts as the viewer moves. The pattern provides partial privacy — interior objects are visible as blurred forms, not sharp outlines.</p>
<p>Fluted glass has become the single most talked-about glass finish in Indian interiors in the 2024–26 period. It appears on wardrobe shutters, TV unit display sections, partition screens, bathroom cabinet doors, and as standalone decorative panels. Its visual appeal spans from minimal contemporary to warm transitional design styles.</p>
<p>Best Applications</p>
<ul>
  <li>Wardrobe shutter panels (most popular use)</li>
  <li>TV unit glass display sections</li>
  <li>Crockery and bar unit doors</li>
  <li>Bathroom cabinet shutters</li>
  <li>Decorative room partition screens</li>
  <li>Walk-in wardrobe entry glass panels</li>
</ul>
<p>Specification Notes</p>
<ul>
  <li>Standard thickness: 4mm–6mm for shutters</li>
  <li>Always toughen before use in doors or accessible positions</li>
  <li>Vertical flutes are most common (horizontal = reeded)</li>
  <li>Available in clear and ultra-clear base glass</li>
  <li>Combines beautifully with brass or black aluminium frames</li>
  <li>Cost: ₹120–₹220 per sq.ft (glass only)</li>
</ul>
<h3>Frosted &amp; Acid-Etched Glass</h3>
<p>Frosted glass is created through sandblasting (which creates a slightly rough, coarser surface) or acid etching (which creates a smoother, more refined satin surface). Both produce a white, translucent appearance that diffuses light and blocks direct visibility. The acid-etched version is preferred for interior applications due to its smoother feel and resistance to fingerprint marks.</p>
<div class="callout"><span class="callout__title">Note</span><strong>Maintenance note:</strong> Sandblasted frosted glass is significantly harder to keep clean than acid-etched — the rough surface traps oils, fingerprints and dust. For kitchen shutters, bathroom panels and wardrobe glass, specify acid-etched frosted rather than sandblasted frosted for a lower-maintenance surface.</div>
<h3>Back Painted Glass (Lacobel / Coloured Glass)</h3>
<p>Back painted glass is created by applying a high-adhesion paint or lacquer to the reverse face of a clear or ultra-clear glass panel, creating a solid, high-gloss or matte coloured surface. The result is a surface that looks deeper, richer and more saturated than any laminate or paint on a wood substrate.</p>
<p>It is the dominant finish for kitchen shutters in contemporary Indian interiors. Available in literally any colour — custom RAL or NCS colour matching is standard — it allows complete freedom in kitchen colour design while providing a surface that is waterproof, heat-resistant, easy to clean, and highly scratch-resistant.</p>
<p>Back Painted Glass — Specification Guide</p>
<p>Glass BaseUltra-clear for maximum colour accuracy</p>
<p>Thickness4mm standard / 5mm–6mm for larger shutters</p>
<p>Finish OptionsGloss (reflective) / Matte (non-reflective)</p>
<p>Colour RangeAny RAL / NCS custom colour</p>
<p>Heat ResistanceUp to 70°C — adequate for kitchen walls and shutters</p>
<p>Cost Range₹180–₹380 per sq.ft installed</p>
<h3>Mirror, Antique Mirror &amp; Tinted Glass</h3>
<p>Standard clear mirrors are produced by depositing a silver coating on the back of float glass, then protecting it with copper and paint layers. The quality of a mirror is determined by the flatness of the glass, the uniformity of the silver coating, and the edge treatment. For interior mirrors, always specify float glass mirrors rather than low-cost pressed glass — the distortion-free reflection is immediately noticeable.</p>
<p><strong>Antique mirror</strong> — currently one of the most sought-after decorative glass finishes in Indian premium interiors — features intentional oxidation patterns, veining, and silvering variations that create an aged, characterful appearance. Used as wardrobe back panels, feature wall cladding, bar back-panels, and cabinet door inserts. No two antique mirror panels are identical, making them intrinsically unique.</p>
<p><strong>Tinted glass</strong> (grey, bronze, blue, green) incorporates metal oxides during the float process to produce a permanently coloured glass. Bronze tinted glass is the stand-out trend in 2025–26 Indian interiors — its warm, golden-brown tone adds richness to wardrobe shutters and partition screens without the coldness of grey or blue tints.</p>
