<p>Safety Guide</p>
<h2>Glass Safety for Homeowners — What Every Family Must Know</h2>
<h3>When Toughened Glass Is Non-Negotiable</h3>
<ul>
  <li>Any glass door — entrance, room, shower, wardrobe sliding door</li>
  <li>Any glass panel within 400mm of a door edge (risk of impact from swinging door)</li>
  <li>Any glass below 800mm height (accessible to sitting adults and children)</li>
  <li>All shower and bath enclosures — thermal shock risk from hot water on cold glass</li>
  <li>Staircase railings — impact and fall protection</li>
  <li>Balcony railings — wind load and impact protection</li>
  <li>Any overhead glass — skylight, glass ceiling, canopy</li>
</ul>
<h3>Child Safety</h3>
<p>In homes with children under 12, specify laminated glass rather than toughened alone for any glass within arm's reach below 1.5m height. Laminated glass holds together even when broken — eliminating the risk of children encountering glass fragments at floor level. The cost premium is modest; the safety benefit is absolute.</p>
