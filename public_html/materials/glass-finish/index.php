<h4>Kitchen Glass Rules — Non-Negotiables</h4>
<ul>
  <li>All kitchen glass shutters must be <strong>toughened</strong> — thermal shock from steam and heat can crack annealed glass</li>
  <li>Back panel / backsplash glass must be rated for <strong>heat resistance up to at least 70°C</strong></li>
  <li>For shutters adjacent to the hob, use <strong>minimum 5mm toughened glass</strong></li>
  <li>Edge protection is essential — exposed glass edges in kitchens must be polished, not raw-cut</li>
  <li>Frosted glass in kitchens should always be <strong>acid-etched, not sandblasted</strong> — the rough texture of sandblasted glass traps grease and is nearly impossible to clean thoroughly in a kitchen environment</li>
</ul>
