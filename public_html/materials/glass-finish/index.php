<p>The Foundation</p>
<h2>Understanding Glass — How It's Made, What It Contains, and Why Thickness Matters</h2>
<p>All interior glass originates as float glass — molten glass poured onto a bed of liquid tin, creating a perfectly flat, uniform sheet. From this base product, all other types of glass are manufactured through secondary processes: tempering, laminating, acid etching, sand blasting, printing, or coating.</p>
<p>Glass is primarily silicon dioxide (silica, from sand), combined with sodium oxide, calcium oxide and small quantities of other oxides. The greenish tint visible on the edge of standard float glass is caused by iron oxide content — a detail that becomes significant when you compare standard glass to ultra-clear (low-iron) glass.</p>
<p>Understanding glass thickness is essential for both safety and application. Indian interior projects commonly use 4mm through 19mm thickness, each with specific applications, load capacities and safety requirements.</p>
<p>Glass Types · Complete Guide</p>
<h2>All Types of Glass Used in Home Interiors — Explained</h2>
<p>Toughened (Tempered) Glass Safety Standard</p>
<p>Toughened glass is produced by heating float glass to approximately 620°C and then rapidly cooling it — a process called quenching. This creates compressive stress on the surface and tensile stress in the core, making the glass 4–5× stronger than ordinary annealed glass of the same thickness. Crucially, when toughened glass breaks, it shatters into small, blunt, pebble-like fragments rather than large, sharp shards — dramatically reducing injury risk.</p>
<p>Where It's Mandatory</p>
<ul>
  <li>Shower enclosures and bath screens</li>
  <li>Balcony and staircase railings</li>
  <li>Glass doors (entrance and room)</li>
  <li>Glass flooring panels</li>
  <li>Any glass at height below 900mm</li>
  <li>Overhead glass panels and skylights</li>
</ul>
<p>Key Properties</p>
<ul>
  <li>4–5× stronger than standard glass</li>
  <li>Safe fragmentation (blunt pebbles)</li>
  <li>Cannot be cut after tempering</li>
  <li>Slight surface distortion possible</li>
  <li>Available in all thicknesses 4mm+</li>
  <li>Can be combined with any finish</li>
</ul>
<div class="callout"><span class="callout__title">Note</span><strong>Critical rule:</strong> Any glass used in areas accessible to children, any door glass, any railing glass, and any glass below hip height <strong>must be toughened</strong>. This is not a luxury specification — it is a safety requirement. Standard annealed glass in these positions is a serious injury risk.</div>
<p>Laminated Glass Safety + Acoustic</p>
<p>Laminated glass consists of two or more glass panes bonded together with a polyvinyl butyral (PVB) interlayer under heat and pressure. When broken, the fragments adhere to the interlayer — the glass "crazes" but does not scatter. This makes it the preferred safety glass for overhead applications, skylights, glass floors, and any situation where a broken pane must remain in place until replaced.</p>
<p>The PVB interlayer also provides significant acoustic dampening — laminated glass is the glass of choice for noise reduction in home studies, bedrooms facing busy roads, and home theatres.</p>
<p>Laminated Glass — Key Specs</p>
<p>ConstructionTwo glass panes + PVB interlayer</p>
<p>Break BehaviourFragments adhere to interlayer — no scatter</p>
<p>Acoustic BenefitReduces noise by 35–40 dB (vs standard glass)</p>
<p>Typical UseSkylights, glass floors, acoustic partitions</p>
<p>Cost Premium1.8–2.5× vs standard toughened glass</p>
<p>Ultra Clear (Low-Iron) Glass Premium Visual Quality</p>
<p>Standard float glass contains iron oxide that gives it a greenish tint — most visible when looking at the edge of a thick pane or when the glass is used as a mirror backing. Ultra-clear glass reduces iron content to below 0.015%, producing a glass that is virtually colour-neutral with 91–92% light transmission (vs 88% for standard glass). The difference is immediately visible in mirrors, display cabinets, and any application where colour accuracy matters.</p>
<ul>
  <li>Always specify ultra-clear glass for high-quality mirrors — the colour rendering difference is dramatic</li>
  <li>Use for museum-quality display cabinets where product colour must read accurately through the glass</li>
  <li>Specify for glass used against white or light-coloured surfaces — the green tint of standard glass is most visible in these contexts</li>
  <li>Cost premium: 25–40% over standard float glass of the same thickness</li>
</ul>
<p>Smart Glass (Switchable Privacy Glass) Premium · 2025–26 Trending</p>
<p>Smart glass — also called switchable glass, electrochromic glass, or PDLC (Polymer Dispersed Liquid Crystal) glass — changes from transparent to opaque with the flip of a switch or the touch of an app. In its powered-off state, the liquid crystal molecules align randomly, scattering light and creating an opaque white appearance. When voltage is applied, the crystals align, allowing light to pass through and making the glass transparent.</p>
<p>In Indian home interiors, smart glass is increasingly specified for master bathroom glass walls between the bedroom and bathroom, for home office partitions that need situational privacy, and for meeting rooms in home-office hybrid setups.</p>
<p>Smart Glass Specifications</p>
<p>Transparency RangeOpaque white ↔ Fully clear</p>
<p>Power RequirementLow voltage AC (typically 60–120V at &lt;5W/m²)</p>
<p>Switching Speed&lt;100 milliseconds</p>
<p>Control OptionsWall switch / remote / app / voice (smart home integration)</p>
<p>Cost Range India₹800–₹1,800 per sq.ft (installed)</p>
