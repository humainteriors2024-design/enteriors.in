<h2>Finishes and design</h2>
<ul>
  <li><strong>Matte or satin</strong> hides water spots in hard-water areas.</li>
  <li><strong>Gloss</strong> brightens small, dim bathrooms but shows marks.</li>
  <li><strong>One highlighter band or wall</strong> is enough; patterned tiles everywhere look busy.</li>
  <li><strong>Large format</strong> in bathrooms means fewer joints to clean.</li>
</ul>

<h2>Laying tips</h2>
<ol>
  <li>Waterproof bathroom walls (at least the shower area) before tiling.</li>
  <li>Use a polymer-modified tile adhesive, not plain cement, especially for vitrified tiles.</li>
  <li>Plan the layout so cut tiles fall in corners and behind fixtures.</li>
  <li>Centre sockets and taps on a tile or a joint.</li>
  <li>Use epoxy grout in showers and behind kitchen hobs.</li>
</ol>
