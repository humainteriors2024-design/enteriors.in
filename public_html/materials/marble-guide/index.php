<h2>Where marble works</h2>
<ul>
  <li><strong>Living and dining rooms:</strong> cool underfoot and timeless. See <a href="/rooms/living-room-flooring/">living room flooring</a>.</li>
  <li><strong>Pooja rooms:</strong> the traditional choice. See the <a href="/rooms/pooja-room/">pooja room guide</a>.</li>
  <li><strong>Stairs and foyers:</strong> with an anti-skid finish or grooves on the nosing.</li>
  <li><strong>Avoid:</strong> kitchen counters, bathroom floors near showers and outdoor areas.</li>
</ul>

<h2>Laying and finishing</h2>
<ol>
  <li>Lay on a full mortar bed, not spot-fixed, so no hollows crack later.</li>
  <li>Allow the floor to cure before grinding.</li>
  <li>Grind, polish and fill joints on site with colour-matched epoxy.</li>
  <li>Seal with a penetrating sealer.</li>
</ol>

<h2>Care</h2>
<ul>
  <li>Mop with water and a pH-neutral stone cleaner; never vinegar, lemon or acidic floor cleaners.</li>
  <li>Use mats at entrances to catch grit, the main cause of scratches.</li>
  <li>Wipe spills at once, especially tea, coffee, wine and oil.</li>
  <li>Reseal every one to two years; re-polish every 5–7 years.</li>
</ul>
