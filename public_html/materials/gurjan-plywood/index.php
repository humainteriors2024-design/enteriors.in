<h2>Pre-Delivery Inspection Checklist</h2>
<ul>
  <li>Cross-section (where accessible) shows consistent colour and grain through all layers, not just the face.</li>
  <li>Sheet weight feels appropriately dense for genuine hardwood plywood of that thickness.</li>
  <li>Edges are sealed or banded cleanly with no exposed raw layers visible.</li>
  <li>No delamination, bubbling, or layer separation visible at any cut edge.</li>
  <li>Supplier can produce species and bonding-grade documentation on request.</li>
