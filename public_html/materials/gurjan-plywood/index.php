<h2>What is Gurjan Plywood?</h2>
<h3>Definition</h3>
<p>Gurjan plywood is a structural plywood manufactured using veneer sheets peeled from the Gurjan tree (Dipterocarpus species), a dense hardwood native to Southeast Asia and parts of Northeast India and Myanmar, known for long, straight fibres and natural resistance to moisture and insects. Genuine Gurjan plywood uses Gurjan veneer through most or all of its internal layers, not just as a decorative face — this internal consistency is what gives it superior strength and warping resistance compared to plywood that mixes in softer, cheaper core species.</p>
<div class="callout"><span class="callout__title">Note</span><strong>In plain terms:</strong> Gurjan plywood is named after the actual tree species used to make it — unlike MR, BWR, or BWP, which describe the adhesive bonding rather than the wood itself. A board can technically be "BWP Gurjan plywood," combining both a strong wood species and a strong bonding grade.</div>
<h2>How Gurjan Plywood is Manufactured</h2>
<p>The manufacturing sequence is similar to other plywood types, but the choice of veneer species at every layer is what separates genuine Gurjan from a board merely finished with a Gurjan face.</p>
<p>1. Gurjan logs are debarked and rotary-peeled into continuous thin veneer sheets.</p>
<p>2. Veneer sheets are dried in controlled kilns to reduce moisture content to a stable, workable level.</p>
<p>3. Sheets are graded for thickness, defects, and grain quality before layer assembly begins.</p>
<p>4. Layers are arranged with grain direction alternating at 90 degrees in each successive sheet, then coated with adhesive resin — phenolic for BWP grade, melamine-urea for BWR, urea-formaldehyde for MR.</p>
<p>5. The assembled stack is hot-pressed under high temperature and pressure, fusing the layers into a single rigid panel.</p>
<p>6. Panels are trimmed to standard sheet sizes, sanded smooth, and quality-checked for bonding strength and surface finish.</p>
<p>The critical quality variable isn't just the press cycle — it's whether Gurjan veneer was actually used at the core layers, or whether a manufacturer substituted a cheaper softwood core and reserved genuine Gurjan veneer only for the outer faces. Both can be marketed loosely as "Gurjan plywood," but their long-term strength is not the same.</p>
<h2>Real vs Face-Veneered "Gurjan" Plywood</h2>
<p>This is the single most important section for any buyer evaluating a Gurjan quote — and the one most competitor articles skip entirely.</p>
<div class="callout"><span class="callout__title">Note</span><strong>The common substitution:</strong> A manufacturer uses a softer, cheaper species (often poplar, eucalyptus, or mixed hardwood) for the internal core layers, then applies a thin Gurjan veneer only on the visible top and bottom face. The sheet looks like Gurjan from the surface and may even be invoiced as "Gurjan plywood," but its strength and moisture behaviour are closer to the cheaper core species.</div>
<h3>How to Check the Cross-Section</h3>
<p>Ask the supplier to show — or cut — a sample cross-section. Genuine full-Gurjan plywood shows a consistent reddish-brown tone with tight, uniform grain through every internal layer. A face-veneered substitute typically shows a visibly lighter, looser-grained core sandwiched between two thin darker face layers.</p>
<h3>Weight Test</h3>
<p>Genuine Gurjan plywood is noticeably heavier per sheet than softwood-core alternatives of the same thickness, since Gurjan is a dense hardwood throughout. An unusually light "Gurjan" sheet is a strong signal of a softwood core.</p>
<h3>Sound Test</h3>
<p>Tapping genuine Gurjan plywood produces a denser, slightly higher-pitched knock compared to the duller, hollow-sounding knock typical of a lighter softwood-core board.</p>
<h3>Certification and Batch Documentation</h3>
<p>Reputable manufacturers can provide species and bonding-grade documentation for a specific batch. Vague verbal assurances without paperwork are a reasonable cause for hesitation on a premium-priced order.</p>
