<p>Note that "Gurjan" describes the wood species used, while MR/BWR/BWP describe the adhesive bonding grade — the two are independent variables. A genuinely strong board combines a hardwood species like Gurjan with a high bonding grade like BWP, rather than relying on either factor alone.</p>
<h2>Types &amp; Bonding Grades of Gurjan Plywood</h2>
<h4>MR Grade Gurjan</h4>
<p>Bonded with moisture-resistant (urea-formaldehyde based) adhesive, suitable only for dry indoor furniture with no real water exposure.</p>
<h4>BWR Grade Gurjan</h4>
<p>Bonded with boiling-water-resistant adhesive, tolerating regular humidity and occasional splashing — a strong fit for kitchens and wardrobes.</p>
<h4>BWP Grade Gurjan</h4>
<p>Bonded with phenolic, boiling-water-proof adhesive, combining Gurjan's natural hardwood strength with the highest available moisture tolerance — the premium standard for bathroom and kitchen base units.</p>
<h4>Marine-Grade Gurjan</h4>
<p>Manufactured to stricter density and bonding standards intended for marine or heavy structural use, often exceeding what residential interiors actually require.</p>
<h4>Full Gurjan (Core-to-Face)</h4>
<p>Uses Gurjan veneer at every internal layer, delivering the genuine strength and weight the species is known for.</p>
<h4>Gurjan-Faced Plywood</h4>
<p>Uses a cheaper core species with Gurjan veneer only on the outer faces — cosmetically similar but structurally weaker; always confirm which type you're being quoted.</p>
<h2>Thickness &amp; Ply Count</h2>
<p>Gurjan plywood is commonly available in 6mm, 9mm, 12mm, 18mm, and 25mm thicknesses, with ply count (the number of veneer layers) increasing with thickness — typically 5-ply for 12mm sheets up to 11 or more thin layers for 19mm structural-grade sheets. More layers at a given thickness generally indicate finer veneer slicing and a more balanced, warp-resistant panel, since stress is distributed across more alternating grain directions. For load-bearing applications like wardrobe shelving or cabinet carcasses, ask specifically for the ply count, not just the thickness, since two 18mm sheets from different manufacturers can have meaningfully different internal layer counts.</p>
