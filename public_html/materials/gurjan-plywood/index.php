    <tr><td>Higher price always means genuine Gurjan.</td><td>Mislabelled or face-veneered boards are sometimes priced at a premium specifically to appear genuine — price alone isn't proof of authenticity.</td></tr>
  </tbody>
</table>
</div>
<h2>Questions to Ask Your Interior Designer</h2>
<ul>
  <li>Is this full Gurjan plywood, or Gurjan-faced plywood with a different core species?</li>
  <li>What bonding grade — MR, BWR, or BWP — is being used, and does it match the room's moisture exposure?</li>
  <li>Can the supplier show a cross-section sample or batch certification?</li>
  <li>What is the ply count at this specific thickness?</li>
  <li>What warranty specifically covers delamination or structural failure?</li>
  <li>Is genuine Gurjan necessary here, or would a more economical board perform just as well for this specific panel?</li>
</ul>
