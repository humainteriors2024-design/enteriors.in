<p>Plan sockets before tiling, and centre them on a tile or a joint. Ask the tiler to start the layout from the centre of the hob so that cut tiles fall at the ends, not in the middle.</p>

<h2>Grout</h2>
<p>Cement grout is porous: behind the hob it soaks up oil and turmeric and turns yellow within months. <strong>Epoxy grout</strong> costs more but is non-porous and stain-proof. Use it behind the hob and sink at least. Choose a mid-grey or a grout close to the tile colour; bright white grout behind an Indian hob does not stay white.</p>

<h2>Kitchen floor tiles</h2>
<ul>
  <li><strong>Slip resistance:</strong> R10 or better, matte or structured surface.</li>
  <li><strong>Body:</strong> vitrified (full-body or double-charge) for chip resistance.</li>
  <li><strong>Size:</strong> 2×2 ft is easy to lay and replace; 2×4 ft gives fewer joints but needs a flat bed.</li>
  <li><strong>Colour:</strong> mid-tones hide spills and dust best.</li>
  <li><strong>Skirting:</strong> 4 inches of the same tile, with the cabinet plinth set in front.</li>
</ul>
<p>Flooring costs and types for the whole home are in the <a href="/flooring/">flooring guide</a> and <a href="/cost/flooring-cost-per-sqft/">flooring cost per sq ft</a>.</p>

<h2>Tiles for hard water</h2>
<p>In areas with hard water, such as much of South-East Bengaluru, white scale builds up on glossy tiles and glass around the sink. Use matte tiles and epoxy grout there, and keep glass to the hob wall. Our <a href="/modular-kitchen/electronic-city-chandapura/">kitchen guide for Electronic City, Chandapura and Bommasandra</a> covers sinks and countertops for hard water.</p>
