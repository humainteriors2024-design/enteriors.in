<h2>Finish: matte, satin or gloss</h2>
<ul>
  <li><strong>Matte</strong> hides fingerprints, oil haze and hard-water marks; slightly harder to wipe.</li>
  <li><strong>Satin</strong> is the easy middle ground for most kitchens.</li>
  <li><strong>Gloss</strong> reflects light and wipes fast, but shows every streak and water spot. Use it away from the sink.</li>
</ul>

