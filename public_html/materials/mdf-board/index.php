<p>Application Guide</p>
<h2>Room-by-Room MDF Selection Guide</h2>
<p>Here is the most practical section of this guide — a room-by-room breakdown of exactly which MDF to specify:</p>
<h4>Living Room</h4>
<p>Standard MDF (18mm) for TV units, feature wall panelling, shelving and built-in display cabinetry. Use 9mm for false ceiling infill panels.</p>
<h4>Kitchen</h4>
<p>MR MDF (16mm–18mm) for all shutters. Plywood for carcasses. Avoid standard MDF entirely. Seal all edges before fitting.</p>
<h4>Bedroom</h4>
<p>Standard MDF (16mm–18mm) for wardrobe shutters and bed head panels. Veneered or pre-lam MDF for a premium finish.</p>
<h4>Bathroom</h4>
<p>MR MDF (12mm–16mm) for vanity shutters only. All edges fully sealed. Prefer PVC or WPC boards for areas near wet zones like shower enclosures.</p>
<h4>Study / Home Office</h4>
<p>Standard MDF (16mm–18mm) for desk tops, bookshelf sides, and wall-mounted storage. 9mm for desk modesty panels.</p>
<h4>Kids' Room</h4>
<p>Standard MDF with rounded CNC edges for safety. Opt for pre-laminated finishes with bright, durable laminates that wipe clean easily.</p>
<h4>Porch / Balcony</h4>
<p>Exterior-grade MDF for covered outdoor applications. Fully prime and paint all surfaces before installation. Not for exposed rain contact.</p>
<h4>Commercial Spaces</h4>
<p>FR MDF or combined MR + FR MDF for all commercial projects. Essential for RERA/fire compliance in offices, shops and hospitality.</p>
<p>Buyer's Checklist</p>
<h2>What to Check Before You Buy MDF — 8 Non-Negotiables</h2>
<p>Walking into a hardware store or ordering from a dealer without this checklist is how homeowners end up with warped cabinets two monsoons in. Go prepared:</p>
<ul>
  <li><strong>Ask for the grade, not just the product name.</strong> Confirm whether it is standard, MR (moisture-resistant), FR (fire-retardant), or exterior grade. The product name alone rarely tells you.</li>
  <li><strong>Check the core colour.</strong> A green or blue tint in the core generally indicates moisture-resistant treatment. A plain beige/brown core is standard grade.</li>
  <li><strong>Verify the density rating.</strong> Standard MDF typically ranges from 650–800 kg/m³. Higher density means better screw hold and surface quality.</li>
  <li><strong>Check the formaldehyde emission rating.</strong> Look for E1 or E0 rated boards. Lower formaldehyde emission is safer for interior air quality — essential for bedrooms and children's spaces.</li>
  <li><strong>Inspect the face surface.</strong> Run your hand across it. Good MDF has no bumps, depressions, or fibre patches. The face should be uniformly smooth and consistent in colour.</li>
  <li><strong>Check edge quality.</strong> Look at the cut edge under light. A uniform, tight fibre pattern indicates consistent density throughout. Loose or flaky core fibres indicate lower quality.</li>
  <li><strong>Confirm the thickness with a calliper.</strong> Poorly produced MDF often varies in thickness by 0.5–1mm across a sheet, which causes problems in modular furniture fitting.</li>
  <li><strong>Ask for the test certificate.</strong> Reputable manufacturers provide IS:12406 (Indian Standard) compliance certificates or equivalent for moisture resistance and mechanical strength.</li>
</ul>
