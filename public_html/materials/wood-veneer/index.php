<h2>Finishes: sealing the wood</h2>
<ul>
  <li><strong>Matte PU:</strong> low sheen that lets the grain lead. The most requested finish now.</li>
  <li><strong>Satin PU:</strong> a soft glow, slightly easier to wipe than matte.</li>
  <li><strong>High-gloss PU:</strong> deepens colour dramatically; shows dust and scratches.</li>
  <li><strong>Open-grain finish:</strong> pores stay slightly open so you feel the wood. Needs a little more care.</li>
  <li><strong>Closed-grain finish:</strong> pores are filled before polishing for a glass-smooth surface.</li>
  <li><strong>Oil finish:</strong> soaks in and looks natural; needs re-oiling and protects less against spills.</li>
  <li><strong>Melamine polish:</strong> cheaper than PU and fine for low-use pieces, but less durable.</li>
</ul>

