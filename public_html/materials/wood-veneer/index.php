<h2>Grades, and why they vary</h2>
<p>Suppliers grade sheets by colour consistency, knots, splits and figure, often with labels such as A, AA or premium. The labels are not standardised across companies, so compare the actual sheets rather than the grade names. For large surfaces, pay for consistency; for a rustic look, a lower grade with visible character can be the better choice.</p>

<h2>Factory-pressed or carpenter-made</h2>
<p>A factory hot press bonds veneer evenly, and a spray booth lays PU in controlled, dust-free coats. Site pressing and brush polishing can work in skilled hands, but bubbles, lifting edges and uneven sheen are more common. For wardrobes and panels, factory-pressed and factory-polished boards are the safer route; keep site polishing for touch-ups.</p>

<h2>Problems to watch for</h2>
<ul>
  <li><strong>Bubbles:</strong> trapped air from uneven glue or pressure during pressing.</li>
  <li><strong>Delamination:</strong> the sheet lifting from the board, usually from moisture getting in at the edges.</li>
  <li><strong>Colour change:</strong> wood darkens or lightens in sunlight; UV-filter film or curtains slow it.</li>
  <li><strong>Hairline cracks:</strong> from fast humidity swings or a thin, dry sheet.</li>
  <li><strong>Warping:</strong> a board veneered on one face only can bow; balance both faces.</li>
</ul>

<h2>Caring for veneer</h2>
<ul>
  <li>Dust with a soft dry cloth; use a barely damp cloth for marks and dry at once.</li>
  <li>Wipe spills immediately and never leave wet glasses or planters on the surface.</li>
  <li>Keep large veneer panels out of hours of direct afternoon sun.</li>
  <li>Plan a professional polish refresh every few years on high-use pieces.</li>
</ul>

<h2>Buying checklist</h2>
<ul class="ticks">
  <li>Natural or recon veneer, species and sheet thickness written in the quote</li>
  <li>Board named: BWR or MR plywood, or HDHMR for shutters</li>
  <li>Matching pattern agreed, and panels taken from one batch or flitch</li>
  <li>Polish type, sheen and number of coats specified</li>
  <li>A physical sample approved in your own room's light</li>
  <li>Warranty covers delamination and polish failure</li>
  <li>Back faces balanced with a veneer or laminate to prevent bowing</li>
</ul>
