<p>A laminate "wood" door is a photograph of wood. A veneer door is wood: every sheet carries the growth rings, colour shifts and figure of the tree it came from. That difference is why veneer is chosen for master wardrobes, TV walls and panelling. It is also why veneer needs more care in choosing, installing and cleaning than printed finishes.</p>

<h2>What veneer is and how it differs from solid wood</h2>
<p>Veneer is a thin leaf of wood sliced from a log and pressed onto a stable board such as plywood, MDF or HDHMR. Decorative veneer sold in India is usually around 0.5–0.6 mm thick; thicker sheets exist for work that will be sanded and refinished several times.</p>
<p>Solid wood swells and shrinks with humidity, which is why solid panels crack or warp in Indian monsoons. A veneered board keeps the wood on the surface only, while the engineered core stays dimensionally stable. You get the look of timber with far less movement, and one log covers many times more surface area than it would as planks.</p>

<h3>Natural veneer and recon veneer</h3>
<div class="pros-cons">
  <div><span class="pros-cons__title">Natural veneer</span><ul><li>Sliced straight from one species</li><li>Unique grain; no two sheets match exactly</li><li>Colour varies between logs and batches</li><li>Higher cost, more selection effort</li></ul></div>
  <div><span class="pros-cons__title">Recon (engineered) veneer</span><ul><li>Fast-growing wood, dyed and re-glued into blocks, then sliced</li><li>Repeatable pattern and colour across large areas</li><li>Can imitate rarer species</li><li>Less character; cheaper than rare naturals</li></ul></div>
</div>

<h2>From log to finished panel</h2>
<ol class="steps">
  <li><strong>Log selection and conditioning</strong>Straight, sound logs are chosen and soaked or steamed so the fibres slice cleanly.</li>
  <li><strong>Slicing</strong>The log is peeled or sliced into thin leaves. The cutting method sets the grain pattern (see below).</li>
  <li><strong>Drying and grading</strong>Leaves are dried to a stable moisture level, then sorted by colour, figure and defects. Sheets from one log are kept together in sequence.</li>
  <li><strong>Matching and splicing</strong>Neighbouring leaves are joined edge to edge in a chosen pattern to make a full-size sheet.</li>
  <li><strong>Pressing</strong>The sheet is glued and hot-pressed onto the core board, ideally in a factory press for even bonding.</li>
  <li><strong>Sanding and polishing</strong>The surface is sanded smooth, sealed and finished, usually with PU polish, in matte, satin or gloss.</li>
</ol>

