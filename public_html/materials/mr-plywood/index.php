<h2>How to check a sheet</h2>
<ol>
  <li><strong>Stamp:</strong> brand, grade (MR), IS 303 and the batch number on every sheet.</li>
  <li><strong>Thickness:</strong> measure with a vernier at several points; 18 mm should not read 16.</li>
  <li><strong>Core:</strong> look at the edge for gaps, overlaps or filler between plies.</li>
  <li><strong>Flatness:</strong> a good sheet lies flat; a warped one will twist a shutter.</li>
  <li><strong>Weight:</strong> a very light 18 mm sheet often means a soft or hollow core.</li>
</ol>
