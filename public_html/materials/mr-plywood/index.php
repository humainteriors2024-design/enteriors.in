<p>Plywood grades are named for what their glue can withstand. MR, short for moisture-resistant, is the interior grade, and it makes up most of the furniture in a typical Indian home. It is good at that job and poor at others. This page explains where MR plywood belongs. For all grades, see the <a href="/materials/plywood-guide/">plywood guide</a>.</p>

<h2>What MR plywood is</h2>
<p>MR plywood is made of thin wood veneers glued crosswise with urea-formaldehyde (UF) resin and pressed under heat. It is covered by IS 303, the Indian standard for general-purpose plywood. UF glue handles room humidity and the occasional splash but softens if the board stays wet, which is why MR plywood swells and delaminates near leaks.</p>

