<p>Quartz has become the countertop of choice for modern Indian kitchens because it combines the look of stone with almost no upkeep. It is an engineered material, though, and slabs vary more than brochures suggest. This page explains what quartz is, where it shines, where it does not, and how to buy a good slab. It is part of our <a href="/materials/">interior materials guide</a>.</p>

<h2>What quartz is</h2>
<p>Engineered quartz is made by mixing about 90–93% crushed natural quartz with polymer resin and pigments, pressing the mix under vacuum and vibration, and curing it in an oven. The result is a dense, uniform, non-porous slab, usually about 3 × 1.5 m (roughly 10 × 5 ft), in 15, 20 or 30 mm thicknesses.</p>

<h2>Strengths and limits</h2>
<div class="pros-cons">
  <div><span class="pros-cons__title">Strengths</span><ul><li>Non-porous: no sealing, no stains</li><li>Very hard and scratch-resistant</li><li>Uniform colour from slab to slab</li><li>Hides hard-water rings better than polished granite</li></ul></div>
  <div><span class="pros-cons__title">Limits</span><ul><li>Resin can scorch under direct heat</li><li>Strong UV can fade some colours (not for outdoor kitchens)</li><li>Visible joints on long counters</li><li>Costs about twice granite</li></ul></div>
</div>

<h2>Finishes and colours</h2>
<ul>
  <li><strong>Polished:</strong> glossy, the easiest to clean; the most common.</li>
  <li><strong>Honed or matte:</strong> soft and modern; shows oily fingerprints a little more.</li>
  <li><strong>Plain whites and greys:</strong> brighten a small kitchen; light colours hide edge chips.</li>
  <li><strong>Marble-look veined quartz:</strong> the look of marble without etching.</li>
  <li><strong>Dark solid colours:</strong> dramatic, but show dust and scratches in raking light.</li>
</ul>

<h2>How to buy a good slab</h2>
<ol>
  <li><strong>Name the brand and series</strong> in the quotation, with the slab thickness.</li>
  <li><strong>See the actual slab</strong> before cutting, in daylight. Check for colour patches, pits and resin pools.</li>
  <li><strong>Do a stain test</strong> on an offcut: a drop of turmeric paste and oil left for an hour should wipe off completely.</li>
  <li><strong>Plan joints</strong> away from the sink and hob, with colour-matched epoxy.</li>
  <li><strong>Ask about cutting</strong>: quartz should be cut wet with dust control, ideally in the workshop rather than in your kitchen.</li>
</ol>

<h2>Care</h2>
<ul>
  <li>Wipe with warm water and a mild detergent; avoid bleach and scouring powder.</li>
  <li>Use a trivet for vessels straight off the flame and a board for chopping.</li>
  <li>Do not stand on the counter at the overhang.</li>
</ul>

