<h2>Working with WPC</h2>
<ul>
  <li>Use hinges with full mounting plates and the right screws; drill pilot holes.</li>
  <li>Keep shelf spans short or add a middle support.</li>
  <li>Edge-band or paint the edges for a clean finish, even though they are waterproof.</li>
  <li>Allow for weight on wall units and use strong wall brackets.</li>
</ul>

