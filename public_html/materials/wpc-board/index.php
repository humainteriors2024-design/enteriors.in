<p>Most furniture failures in Indian homes start with water: a slow leak under a sink, a splash zone around a vanity, a washing machine on a balcony. WPC board was made for those places. This page explains what it is and where it beats plywood. It is part of our <a href="/materials/">interior materials guide</a>.</p>

<h2>What WPC is</h2>
<p>WPC (wood-plastic composite) board is extruded from wood flour and PVC with stabilisers. The result is a uniform, closed-cell board that does not absorb water. Interior WPC boards come in 6–25 mm thicknesses, usually white, and can be laminated, painted or wrapped.</p>

<h2>Strengths and limits</h2>
<div class="pros-cons">
  <div><span class="pros-cons__title">Strengths</span><ul><li>Fully waterproof; does not swell or delaminate</li><li>Termite- and borer-proof</li><li>No formaldehyde glue</li><li>Smooth surface for paint</li></ul></div>
  <div><span class="pros-cons__title">Limits</span><ul><li>Heavier than plywood</li><li>More flexible: long shelves sag</li><li>Lower screw-holding; needs pilot holes</li><li>Softens near direct heat</li></ul></div>
</div>

