<p>A walk-in closet is a small room lined with storage that you step into to dress. It takes clothes off the bedroom walls and puts everything in view at once. In Indian homes it usually sits between the master bedroom and its bathroom, in an alcove or in a small spare room. This page sets out the sizes it needs, the layouts that work and what it costs. It is part of our <a href="/wardrobe/">wardrobe design guide</a>.</p>
