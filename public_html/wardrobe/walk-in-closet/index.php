<h2>Light and air</h2>
<ul>
  <li><strong>Light the clothes:</strong> LED strips under shelves and inside hanging bays, on a door sensor or motion sensor, plus a general ceiling light. Use 4,000 K or a high-CRI 3,000 K strip so colours look true.</li>
  <li><strong>Ventilate:</strong> a small exhaust fan or a louvered door. In the monsoon, a closed closet without air movement grows mildew within weeks.</li>
  <li><strong>Keep it dry:</strong> if the closet shares a wall with a bathroom, waterproof that wall and use BWR plywood for the carcass.</li>
</ul>

