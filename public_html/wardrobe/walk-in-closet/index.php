<p>The numbers come from two figures: storage about 2 ft deep (hanging) or 1.25–1.5 ft (shelves), and a walkway of about 3 ft. With a central island of drawers, add the island depth plus 3 ft on each side.</p>

<h2>Planning the storage</h2>
<ul>
  <li><strong>Hanging:</strong> one long-hang bay (60–66 inches) for sarees, kurtas and coats; double short-hang bays (about 40 inches each) for shirts and trousers.</li>
  <li><strong>Shelves:</strong> 12–15 inches apart for folded clothes, no wider than about 3 ft.</li>
  <li><strong>Drawers:</strong> at waist height for innerwear, accessories and a lockable jewellery drawer.</li>
  <li><strong>Shoes:</strong> low, tilted shelves or a dedicated shoe tower.</li>
  <li><strong>Loft:</strong> to the ceiling for suitcases and out-of-season clothes.</li>
  <li><strong>Mirror:</strong> full-length at the end wall, lit from both sides.</li>
</ul>
<p>The same method as for any wardrobe applies: count what you hang, fold and store first. See <a href="/wardrobe/wardrobe-internal-design/">wardrobe internal design</a>.</p>

