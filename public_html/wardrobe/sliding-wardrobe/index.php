<p>A sliding wardrobe replaces swinging doors with panels that run along tracks in front of the carcass. In a bedroom where the bed sits close to the wardrobe wall, that can be the difference between a usable room and a daily obstacle course. This page covers when to choose sliding doors, the sizes they need, the hardware that decides how long they glide smoothly, and what they cost. It is part of our <a href="/wardrobe/">wardrobe design guide</a>.</p>
