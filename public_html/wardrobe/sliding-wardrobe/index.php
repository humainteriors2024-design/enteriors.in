<h2>Door finishes</h2>
<ul>
  <li><strong>Laminate on board:</strong> toughest and least expensive; any colour.</li>
  <li><strong>Mirror:</strong> replaces a dressing mirror; use one door, with safety film behind it. See <a href="/rooms/vanity-dressing/">vanity and dressing</a>.</li>
  <li><strong>Lacquered or frosted glass in aluminium frames:</strong> slim and modern; heavier, so check the roller rating. See <a href="/materials/lacquered-glass/">lacquered glass</a>.</li>
  <li><strong>Acrylic:</strong> deep gloss or soft matte; gloss shows fingerprints. See the <a href="/materials/acrylic-finish/">acrylic guide</a>.</li>
  <li><strong>Veneer:</strong> real wood; keep doors under about 3 ft wide to limit warping.</li>
</ul>

<h2>Planning the inside</h2>
<p>With sliding doors only one or two bays are open at a time, so plan each bay to be useful on its own: one long-hang bay, one short-hang bay with shelves, and drawers in a bay that does not sit behind the overlap. Internal drawers need about 2 inches of clearance behind the door track. The full method is in <a href="/wardrobe/wardrobe-internal-design/">wardrobe internal design</a>.</p>

