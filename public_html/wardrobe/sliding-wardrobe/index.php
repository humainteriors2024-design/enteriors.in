<h2>When sliding doors make sense</h2>
<ul>
  <li><strong>The gap to the bed is under about 2.5 ft.</strong> Hinged doors need about 2 ft to swing and you need room to stand.</li>
  <li><strong>The wall is at least 6 ft wide.</strong> On narrower walls, two sliding doors leave half the wardrobe closed at any time.</li>
  <li><strong>You want a flat, uninterrupted front</strong> in a single colour, mirror or glass.</li>
  <li><strong>The room door or a window would clash</strong> with an opening shutter.</li>
</ul>
<p>The full comparison is in <a href="/compare/sliding-vs-hinged-wardrobe/">sliding vs hinged wardrobes</a>.</p>

