<h2>Room by room</h2>
<h3>Living room</h3>
<p>One microcement or brick-look wall behind the TV or sofa, black metal open shelving, a leather or cognac sofa, a wool rug and metal pendants on a track. See <a href="/wall-design/stone-wall-cladding/">stone and brick cladding</a> and <a href="/wall-design/texture-paint/">texture paint</a>.</p>
<h3>Kitchen</h3>
<p>Charcoal or concrete-look laminate base units, wood-grain wall units or open metal shelves, a black granite or concrete-look quartz top, subway tiles with dark grout and black fittings. See <a href="/blogs/kitchen-colour-combinations/">kitchen colour combinations</a>.</p>
<h3>Bedroom</h3>
<p>A metal-frame bed, a walnut or oak wardrobe, a concrete-texture wall behind the bed, and warm lighting. Keep the bedroom softer than the living room.</p>
<h3>Bathroom</h3>
<p>Concrete-look tiles, black fittings and a wood-look vanity in BWP plywood.</p>

<h2>Materials that suit Indian conditions</h2>
<ul>
  <li><strong>Microcement</strong> needs a skilled applicator and a sealed finish; good for walls and dry floors.</li>
  <li><strong>Black metal</strong> should be powder-coated, not just painted, to resist rust in humid months.</li>
  <li><strong>Brick-look cladding</strong> is easier to clean than real exposed brick.</li>
  <li><strong>Laminates</strong> in concrete and rustic wood looks are the most practical way to carry the style into cabinets.</li>
</ul>

<h2>Avoiding a cold, dark home</h2>
<ol>
  <li>Limit raw texture to one wall per room.</li>
  <li>Use light-to-mid greys, not charcoal, in small rooms.</li>
  <li>Add warm wood, leather, a big rug and plenty of plants.</li>
  <li>Light warmly: 2,700–3,000 K bulbs.</li>
</ol>

<h2>What it costs</h2>
<p>Industrial interiors cost about the same as other styles of the same grade. Microcement walls cost about ₹250–450 per sq ft applied; brick-look cladding ₹150–350; custom metal shelving ₹1,500–3,000 per running ft. Whole-home budgets are in the <a href="/cost/">interior cost guide</a>.</p>
