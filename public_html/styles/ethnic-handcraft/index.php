<h2>How to use them</h2>
<ol>
  <li><strong>Start with a calm base:</strong> warm white or soft neutral walls, plain floors, simple furniture.</li>
  <li><strong>Pick a thread:</strong> indigo and white, brass and teak, or terracotta and cane.</li>
  <li><strong>One textile, one metal, one wood piece per room.</strong></li>
  <li><strong>Give pieces space:</strong> a single brass urli on a console looks better than ten on a shelf.</li>
  <li><strong>Build-in craft:</strong> jaali partitions, cane shutters or carved pooja doors become part of the architecture. See <a href="/doors/pooja-room-door-design/">pooja room doors</a>.</li>
</ol>

<h2>Buying well</h2>
<ul>
  <li>Buy from makers, cooperatives and state emporiums where possible.</li>
  <li>Look for Geographical Indication (GI) tags on crafts such as Channapatna toys and Bidriware.</li>
  <li>Check natural dyes and hand finishing; machine prints have perfectly regular repeats.</li>
  <li>Ask about care: some dyes bleed in the first wash; brass darkens unless lacquered.</li>
</ul>

