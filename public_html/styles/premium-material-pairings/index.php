<h2>Rules that make pairings work</h2>
<ol>
  <li><strong>Two or three pairs per home,</strong> repeated room to room.</li>
  <li><strong>Matte and satin finishes:</strong> they read as quality; high gloss everywhere reads as a showroom.</li>
  <li><strong>One hero surface per room,</strong> the rest quieter.</li>
  <li><strong>Match metals:</strong> one metal finish for handles, lights and taps in each room.</li>
  <li><strong>Light it well:</strong> warm, layered lighting makes veneer and stone glow. See the <a href="/planning/lighting-design/">lighting guide</a>.</li>
</ol>

<h2>Spending smart</h2>
<p>Put real veneer, stone or fluted glass where you see it first: the TV wall, the kitchen island, the headboard wall and the foyer. Use textured laminates that echo those materials on wardrobes and kitchen base units. Upgrade handles; brushed brass or bronze pulls lift plain laminate shutters for a small cost. Finish comparisons: <a href="/compare/veneer-vs-laminate/">veneer vs laminate</a>, <a href="/compare/matte-vs-glossy-finish/">matte vs glossy</a>, <a href="/materials/wood-veneer/">wood veneer</a>.</p>

