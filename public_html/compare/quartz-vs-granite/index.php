<p>Section 06 — Water, Stains &amp; Chemicals</p>
<h2>Water, Stain, Chemical &amp; Acid Resistance</h2>
<h3>Water &amp; Moisture Absorption</h3>
<p><strong>Quartz is virtually non-porous</strong> (water absorption rate &lt;0.03%), making it inherently resistant to moisture penetration. Granite, while denser than most natural stones, is porous to varying degrees — water absorption rates typically range from 0.1% to 0.6%, depending on mineral density. An unsealed or under-sealed granite surface left with standing water will eventually allow moisture to penetrate, causing staining and potentially fostering mold growth.</p>
<h3>Stain Resistance</h3>
<p>Quartz's non-porous surface means spills — red wine, coffee, turmeric, olive oil, beet juice — sit on the surface and can be wiped clean with a damp cloth and mild detergent. Staining essentially requires leaving a spill unaddressed for an extended period, which rarely happens in normal use.</p>
<p>Granite's stain resistance depends entirely on the quality and freshness of its sealant. A properly sealed granite countertop resists staining admirably. An aging or missing seal is where problems begin — and granite countertops must be re-sealed every 1–3 years to maintain this protection.</p>
<h3>Chemical &amp; Acid Resistance</h3>
<p><strong>Quartz is more chemically resistant</strong> than granite. Its non-porous resin surface does not react with lemon juice, vinegar, wine, coffee, or most common household cleaners. However, <strong>harsh chemicals — bleach, strong alkaline cleaners, acetone-based nail polish remover</strong> — can break down the resin binders and dull the surface.</p>
<p>Granite is more vulnerable to acids. Lemon juice, vinegar, and acidic foods can etch the surface of unsealed granite — breaking down calcium carbonates in some mineral compositions. Sealed granite is significantly more resistant, but acid should still be cleaned promptly.</p>
