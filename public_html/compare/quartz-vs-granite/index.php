<p>Section 13 — When Things Go Wrong</p>
<h2>Repair, Refinishing &amp; Restoration</h2>
<h3>Granite: More Repairable</h3>
<p>Granite's natural stone composition means chips and cracks can often be <strong>filled with color-matched epoxy</strong> and polished to a near-invisible finish by a skilled stone restoration professional. Because granite is solid stone throughout, re-polishing and re-honing are genuine options — an aging granite countertop can be professionally restored to near-original condition. Minor etching and dullness can be addressed with diamond polishing pads.</p>
<h3>Quartz: Harder to Repair Well</h3>
<p>Quartz chips and cracks can be filled with resin-based color-matched compounds, but perfect invisibility is harder to achieve because the engineered pattern is difficult to replicate exactly. <strong>Heat damage to quartz is almost always permanent</strong> — discoloration and warping caused by hot pots cannot be polished away. In severe damage cases, full slab replacement may be the only option.</p>
