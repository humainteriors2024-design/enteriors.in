<p>Section 01 · The Basics</p>
<h2>What Are Plywood and MDF?</h2>
<p>Before comparing, it's essential to understand how each material is made — because how they're manufactured directly dictates what they're good and bad at.</p>
<div class="callout"><span class="callout__title">Plywood</span><ul>
  <li>✓ Made from thin wood veneers (plies) glued together with grain alternating 90°</li>
  <li>✓ Each layer adds cross-directional strength — the key reason plywood is so tough</li>
  <li>✓ Available in 3-ply, 5-ply, 7-ply and higher configurations</li>
  <li>✓ Core is real wood — holds screws, withstands stress, handles moisture better</li>
  <li>✗ Edges are rough, show layers, and require edging tape or lipping</li>
  <li>✗ Surface grain can be uneven — needs sanding before paint</li>
</ul>
<p>MDF</p>
<ul>
  <li>✓ Medium Density Fibreboard — made from broken-down wood fibres + resin, compressed under heat</li>
  <li>✓ Extremely smooth, uniform surface — the best substrate for paint finishes</li>
  <li>✓ No grain, no knots, no voids — completely consistent sheet to sheet</li>
  <li>✓ Machines beautifully — ideal for CNC routing, shaped edges, detailed profiles</li>
  <li>✗ Significantly heavier than plywood for the same thickness</li>
  <li>✗ Swells and crumbles when exposed to moisture unless sealed</li>
</ul></div>
<p>📌 Key Mental Model</p>
<p>Think of plywood as a <strong>structural workhorse</strong> — strong, resilient, screw-holding. Think of MDF as a <strong>finishing artisan's canvas</strong> — perfectly smooth, cuts cleanly, paints flawlessly. Neither is universally better; they're optimised for different outcomes.</p>
