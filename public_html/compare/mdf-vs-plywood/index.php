<div class="callout callout--tip"><span class="callout__title">🔴 Critical Insight</span><strong>Edge screw strength is where MDF fails most dramatically.</strong> MDF edge screws have 40–55% less holding power than plywood. In furniture with hinges, drawer runners, or structural connections at edges, this matters enormously. If you use MDF for cabinet carcasses, always use dowels, dominoes, or connector bolts — never rely on edge screws alone.</div>
<p>Section 04 · Water Performance</p>
<h2>Moisture Resistance — The Critical Factor</h2>
<p>In Indian conditions — monsoons, humid coastal cities, steam from kitchens, water spray in bathrooms — moisture resistance is arguably the most important factor when choosing between these two materials.</p>
<p>Plywood — Moisture Grades</p>
<ul>
  <li><strong>MR Grade</strong> — Moisture Resistant. Interior use only. Fails if directly wet.</li>
  <li><strong>BWR Grade</strong> — Boiling Water Resistant. Good for kitchen cabinets, semi-exposed areas.</li>
  <li><strong>BWP Grade (Marine)</strong> — Boiling Water Proof. Full waterproofing. Best for bathrooms, wet areas, exteriors.</li>
  <li><strong>Fire Retardant</strong> — Special grade for fire-rated applications.</li>
</ul>
<p>MDF — Moisture Grades</p>
<ul>
  <li><strong>Standard MDF</strong> — No water resistance. Swells and crumbles when wet.</li>
  <li><strong>Moisture-Resistant MDF (Green MDF)</strong> — Has additives; handles humidity, not direct water contact.</li>
  <li><strong>Exterior MDF</strong> — Treated for outdoor use; rare and expensive in India.</li>
  <li><strong>Limitation</strong> — Even MR-MDF must be fully sealed on all edges to prevent any absorption.</li>
</ul>
