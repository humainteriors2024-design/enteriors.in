<h3>Why Weight Matters in Practice</h3>
<ul>
  <li><strong>Wall-mounted units:</strong> MDF wall cabinets exert significantly more load on wall anchors. In older buildings with weak masonry, plywood is safer.</li>
  <li><strong>Floor loads:</strong> A full MDF wardrobe can weigh 180–240 kg; the equivalent plywood unit 120–160 kg. Relevant for upper-floor apartments.</li>
  <li><strong>Transport &amp; installation:</strong> MDF sheets require two people and proper lifting technique; back strain is a real risk with thicker MDF sheets.</li>
  <li><strong>Sagging shelves:</strong> MDF shelves over 600mm unsupported spans sag noticeably under load due to lower stiffness-to-weight ratio. Plywood shelves of the same thickness sag far less.</li>
  <li><strong>Kitchen top sections:</strong> MDF wall units above the kitchen stove/hob area accumulate more heat and moisture weight — use plywood here.</li>
</ul>
