<p>Section 11 · Application Guide</p>
<h2>Room-by-Room Use Cases</h2>
<p>Theory is useful; practical guidance is better. Here's where each material shines, room by room, application by application.</p>
<h3>Kitchen</h3>
<p><strong>Carcass / Cabinet Box:</strong> Always use BWR or BWP plywood — steam, spills, and cleaning chemicals disqualify standard MDF. <strong>Door Shutters:</strong> MDF with acrylic, PU lacquer, or membrane finish gives the best-looking kitchen. The hybrid approach is standard in premium kitchens.</p>
<h3>Bedroom / Wardrobe</h3>
<p>For full wardrobes with sliding doors, plywood carcasses are preferred — they hold the rail/track screws far better under daily use. For wardrobe shutter finishes, MDF gives superior painted results. For loft sections above 7 feet, MDF shutter weight becomes a concern — use thin plywood shutters here.</p>
<h3>Living Room</h3>
<p>Living room furniture is generally dry and away from moisture. MDF is appropriate for TV units, feature wall panels, display shelves (short spans), and decorative niches. For floor-to-ceiling bookshelves with books (heavy load, long spans), use plywood shelves at minimum 18mm thickness.</p>
<h3>Bathroom</h3>
<p>Plywood only — specifically BWP (Marine) grade. Even MR-MDF will fail within 2–3 years in a bathroom environment. Vanity cabinets, mirror frame boxes, and any storage in the bathroom must use Marine ply, sealed on all faces, with PU finish or polyurethane paint.</p>
<h3>Study / Home Office</h3>
<p>Both materials work well in dry study rooms. MDF is preferred for desktops with paint or laminate finish (better flat surface). Plywood is better for drawer units and filing pedestals that take weight and opening/closing stress. For floating desks mounted to walls, use plywood for the mounting structure.</p>
<h3>Kids' Room</h3>
<p>Impact resistance and safety matter in children's rooms. Plywood is preferred for structural elements — it doesn't chip or crack with bumps the way MDF edges do. For décor elements (name boards, cloud shelves, painted shapes), MDF cuts and paints beautifully. Use E0/E1 grade wherever possible.</p>
