<p>Section 13 · The Final Call</p>
<h2>The Decision Guide — Choose Your Material</h2>
<p>Use this matrix to make the right call for your specific situation. No material is universally better; the right answer depends on what you're building, where it will live, and what finish you want.</p>
<p>✅ Choose Plywood When...</p>
<ul>
  <li>→ The furniture is in a kitchen, bathroom, or any moisture-prone area</li>
  <li>→ You need the piece to last 15–25+ years</li>
  <li>→ The application involves hinges, drawer runners, or heavy hardware</li>
  <li>→ Long unsupported shelves will carry heavy loads</li>
  <li>→ Children or pets will use the furniture (impact resistance)</li>
  <li>→ You want a veneer / natural wood look</li>
  <li>→ The unit will be wall-mounted (weight concern)</li>
  <li>→ The piece needs to be moved or relocated later</li>
  <li>→ You're building structural elements: flooring base, wall panelling substrate</li>
  <li>→ Indoor air quality / emissions are a priority (children's rooms)</li>
</ul>
<p>✅ Choose MDF When...</p>
<ul>
  <li>→ You want a flawless painted surface — PU, acrylic, high-gloss lacquer</li>
  <li>→ Kitchen or wardrobe door shutters with high-gloss or matt paint</li>
  <li>→ Decorative CNC-routed profiles, dado rails, wainscoting</li>
  <li>→ TV unit or living room décor in dry interior conditions</li>
  <li>→ Budget is a constraint and the application is non-structural</li>
  <li>→ Shaped or curved profiles via CNC (MDF routes cleanly)</li>
  <li>→ Short-span shelves carrying light loads (books, ornaments)</li>
  <li>→ Signage, display boards, interior partition fills</li>
  <li>→ Speaker enclosures (MDF's density reduces resonance)</li>
  <li>→ Feature walls and 3D decorative wall panels</li>
</ul>
<h3>The Hybrid Rule of Thumb (Best of Both)</h3>
<div class="callout callout--tip"><span class="callout__title">🔴 The Professional Standard</span>For any project where both structure AND finish matter, use the <strong>Plywood Carcass + MDF Shutter</strong> formula. The box, base, sides, and shelves in plywood — the visible door faces in MDF. This is what premium modular kitchen brands, high-end wardrobe companies, and serious joinery workshops use. It adds roughly 10–15% to material costs but delivers a product that neither material achieves alone.</div>
