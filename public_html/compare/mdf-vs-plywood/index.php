<table>
  <thead>
    <tr><th>Property</th><th>Plywood (BWR/BWP)</th><th>MDF (Standard)</th></tr>
  </thead>
  <tbody>
    <tr><td>Bending Strength (MOR)</td><td>35–50 N/mm²</td><td>25–35 N/mm²</td></tr>
    <tr><td>Tensile Strength</td><td>40–60 N/mm²</td><td>20–30 N/mm²</td></tr>
    <tr><td>Compressive Strength</td><td>30–45 N/mm²</td><td>18–28 N/mm²</td></tr>
    <tr><td>Screw Withdrawal (face)</td><td>1,200–1,800 N</td><td>700–1,000 N</td></tr>
    <tr><td>Screw Withdrawal (edge)</td><td>800–1,200 N</td><td>300–550 N</td></tr>
    <tr><td>Impact Resistance</td><td>High</td><td>Low — dents, chips</td></tr>
    <tr><td>Delamination Risk</td><td>Present (low grade)</td><td>None (uniform material)</td></tr>
