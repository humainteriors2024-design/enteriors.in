  <li>Am I budgeting for branded hardware (hinges or track) rather than the cheapest available option?</li>
  <li>Have I planned for 15–20% extra storage capacity to account for future needs?</li>
  <li>If choosing sliding, has the installer confirmed top-hung vs bottom-track based on my ceiling and floor condition?</li>
  <li>Does the finish I've picked suit the room's lighting — mirror and glass perform very differently in low natural light?</li>
  <li>Have I asked about soft-close mechanisms, especially in homes with children or elderly residents?</li>
  <li>Does the wardrobe placement follow good Interior Planning Checklist principles relative to the bed and door?</li>
</ul>
<div class="callout callout--tip"><span class="callout__title">Pro Tip</span>Get a written warranty on hardware specifically — not just the overall wardrobe — since hinges and track systems are the components most likely to need replacement first.</div>
