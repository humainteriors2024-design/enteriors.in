<h2>Villas and larger homes</h2>
<h3>5. U-shape with a tall pantry</h3>
<p>Three walls of storage with a tall pull-out pantry beside the fridge. Needs at least 8 ft of width. See <a href="/modular-kitchen/l-shape-vs-u-shape/">L-shape vs U-shape</a>.</p>
<h3>6. Peninsula with a breakfast counter</h3>
<p>An L or U with one arm extended as a counter facing the dining area. Gives an open feel without the floor space an island needs.</p>
<h3>7. Island kitchen with a wet kitchen behind</h3>
<p>A show kitchen with an island for preparation and serving, and a separate wet kitchen or utility for heavy Indian cooking. See <a href="/modular-kitchen/island-kitchen/">island kitchens</a>.</p>
<h3>8. Sage and ivory with brass</h3>
<p>Soft sage base units, ivory uppers and brushed brass handles: calm and distinctive in villas with good daylight.</p>

<h2>Independent houses and rental floors</h2>
<h3>9. One repeated rental kitchen</h3>
<p>The same straight or L-shape design on every rental floor: BWR plywood with BWP at the sink, laminate shutters, black granite, branded basic hardware. Cheaper to make, quick to repair.</p>
<h3>10. Owner's kitchen with a tall unit</h3>
<p>The owner's floor gets the same board and hardware brand, with an acrylic upgrade on wall units and a tall unit for the oven and microwave.</p>
<h3>11. Open kitchen with a glass partition</h3>
<p>For homes that want light but not smoke in the living room: a fluted glass sliding partition. See <a href="/blogs/kitchen-living-partition-ideas/">kitchen partition ideas</a>.</p>
<h3>12. Traditional teak-look kitchen</h3>
<p>Teak-grain laminate shutters, cream walls, brass handles and a pooja niche nearby, for families who prefer a traditional look.</p>

