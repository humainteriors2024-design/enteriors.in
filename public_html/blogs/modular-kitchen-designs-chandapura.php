<p>Chandapura has every kind of home, from compact 2 BHK flats along Hosur Road to villas off the Anekal and Dommasandra roads and independent houses with rental floors. One kitchen design does not fit all of them. Here are twelve designs that work in Chandapura homes, grouped by home type, with the board, finish and budget for each. For the design process, see our <a href="/modular-kitchen/">modular kitchen design guide</a>.</p>

<h2>Flats along Hosur Road and Anekal Road</h2>
<h3>1. Warm white and walnut L-shape</h3>
<p>Warm white wall units over walnut-grain base units, black granite and brushed-steel handles. It hides daily wear on the lower run, works with any floor and resells easily. Standard grade: about ₹1.9–2.6 lakh.</p>
<h3>2. Parallel kitchen with a utility beyond</h3>
<p>Hob and chimney on one run, sink and dishwasher on the other, washing machine in the utility. Keep 3.5–4 ft between the runs. See <a href="/blogs/parallel-kitchen-designs/">parallel kitchen designs</a>.</p>
<h3>3. Graphite and oak L-shape</h3>
<p>Graphite base units, oak-grain wall units, a dark quartz top. Modern and forgiving of turmeric and oil.</p>
<h3>4. Pearl greige compact kitchen</h3>
<p>Two light, warm tones that make a small kitchen feel bigger without stark white. Good for 1 BHK and rental flats.</p>
