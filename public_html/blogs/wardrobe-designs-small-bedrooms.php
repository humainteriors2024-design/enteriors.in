<p>Bedrooms in many Indian flats are 10×10 or 10×11 ft, with a bed, a window, a door and an AC competing for the same walls. A well-designed wardrobe can still hold a couple's clothes without crowding the room. Here are ten ideas. For types, sizes and costs, see the <a href="/wardrobe/">wardrobe design guide</a>.</p>

<h2>Ten space-saving ideas</h2>
<ol>
  <li><strong>Go floor to ceiling.</strong> A loft over the wardrobe adds 25–30% storage for suitcases and seasonal clothes.</li>
  <li><strong>Sliding doors where the bed is close.</strong> Under about 2.5 ft of clearance, sliding doors are the only comfortable option. See <a href="/wardrobe/sliding-wardrobe/">sliding wardrobes</a>.</li>
  <li><strong>One mirror shutter.</strong> Replaces a dresser and bounces light.</li>
  <li><strong>Light, matte shutters.</strong> Warm white, light oak or pearl greige make the wall recede.</li>
  <li><strong>A corner wardrobe.</strong> An L-shaped wardrobe uses a corner that a bed cannot.</li>
  <li><strong>Shallow units for folded clothes.</strong> 15–18 inches deep beside a window or over a desk.</li>
  <li><strong>Wardrobe around the bed.</strong> Tall units either side of the bed with a bridging loft over the headboard.</li>
  <li><strong>Storage bed.</strong> Hydraulic storage under the mattress for bedding and suitcases.</li>
  <li><strong>Handle-less or slim handles.</strong> Nothing to catch on in a tight passage.</li>
  <li><strong>Internal lights.</strong> A sensor strip makes a deep wardrobe usable at night.</li>
</ol>
