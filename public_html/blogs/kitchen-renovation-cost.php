<h3>5. Lighting</h3>
<p>Good kitchen lighting is a 3-layer system — and this is where budget kitchens often feel unfinished despite decent materials.</p>
<ul>
  <li><strong>Ambient (ceiling):</strong> Recessed LED downlights or a flush-mount fixture. Budget ₹4,000–₹12,000 for the kitchen area.</li>
  <li><strong>Task (under-cabinet):</strong> LED strip lights under wall cabinets illuminate the countertop. Essential for safe chopping. Cost: ₹1,500–₹4,000 per running metre installed.</li>
  <li><strong>Accent / Decorative:</strong> Pendant over island, LED profiles inside glass cabinets, toe-kick lighting. Budget ₹8,000–₹30,000 for this layer.</li>
</ul>
<h3>6. Plumbing &amp; Electrical</h3>
