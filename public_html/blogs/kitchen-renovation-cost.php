  <li>New plumbing outlet (inlet/drain): ₹2,000–₹6,000 per point</li>
  <li>Full pipe replacement (galvanized → CPVC): ₹8,000–₹20,000 for kitchen area</li>
  <li>Waterproofing sink zone: ₹4,000–₹12,000</li>
