<h3>1. Cabinets &amp; Storage</h3>
<p>Cabinets typically eat <strong>40–50% of the total kitchen budget</strong> and are the single biggest quality lever. Here's what the material tiers mean in practice:</p>
<ul>
  <li><strong>HDHMR (High-Density High-Moisture Resistant) board:</strong> ₹600–₹900 per sq ft of shutter. Best value for money. Resists moisture, termite-proof if treated. Good for 10–15 years.</li>
  <li><strong>Commercial/Marine Plywood:</strong> ₹750–₹1,100 per sq ft. Stronger, takes screws better. Preferred by carpenters for custom sizes.</li>
  <li><strong>Boiling Waterproof (BWP) Ply:</strong> ₹1,000–₹1,500 per sq ft. Premium substrate, mostly for platforms and base cabinets near sink.</li>
  <li><strong>MDF (Medium-Density Fibreboard):</strong> ₹500–₹750 per sq ft. Budget-friendly but NOT suitable near moisture without edgebanding.</li>
</ul>
<div class="callout callout--warn"><span class="callout__title">Watch out</span>⚠️</p>
<div class="callout callout--tip"><span class="callout__title">Tip</span><strong>Don't Skimp Here</strong><p>Saving ₹20,000 on cheap MDF boards near the sink can cost ₹80,000 in replacement within 3–5 years. Invest in BWP ply or HDHMR for base units and moisture-exposed areas.</div></div>
<p><strong>Shutter finishes</strong> add another layer of cost: PVC membrane (₹150–₹250/sq ft), acrylic gloss (₹250–₹450/sq ft), lacquered glass (₹450–₹700/sq ft), or handleless profile shutters (₹600–₹1,200/sq ft) for a luxury European look.</p>
<h3>2. Countertops</h3>
<p>The countertop is the visual centrepiece and daily workhorse. Material choice dramatically shifts both cost and maintenance commitment:</p>
<p>Kota Stone</p>
