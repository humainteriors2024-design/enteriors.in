<h2>Costly Mistakes to Avoid</h2>
<h3>Mistake 1: Changing the Layout After Civil Work</h3>
<p>Every layout change after the slab or wall is opened adds ₹10,000–₹40,000 in rectification costs and 1–2 weeks of delay. Lock the layout in writing before work begins.</p>
<h3>Mistake 2: Ignoring the Kitchen Triangle Rule</h3>
<p>The working triangle (sink–hob–refrigerator) should have each side between 1.2m and 2.7m. Layouts that ignore this make cooking genuinely tiring and reduce the kitchen's functional value regardless of how beautiful it looks.</p>
<h3>Mistake 3: Under-buying Storage</h3>
<p>Indian kitchens need 40% more storage than a standard modular catalogue suggests because of masalas, pressure cookers, steel utensils, and seasonal items. Plan dedicated zones for: dry storage, wet cleaning, cooking tools, and pantry items.</p>
<h3>Mistake 4: Skipping the Waterproofing Layer</h3>
<p>The area within 600mm of the sink and 300mm around any plumbing outlet needs polymer-based waterproofing before tiling. Skipping this leads to seepage within 2–3 years and full re-tiling costs.</p>
<h3>Mistake 5: Choosing Materials Without Checking Lead Times</h3>
<p>Some quartz brands have 4–6 week lead times. Imported handles and specialty tiles can take 8–12 weeks. Confirm delivery timelines before finalising any item — order early, especially post-GST materials that aren't stocked locally.</p>
<h2>Pre-Renovation Checklist</h2>
<p>Before your contractor starts, make sure you've ticked every box on this list:</p>
<ul>
  <li>Finalised and approved 2D layout drawing (with measurements)</li>
  <li>3D render or mood board approved by all decision-makers in the household</li>
  <li>Full BOQ (Bill of Quantities) from contractor — line item wise, not lump sum</li>
  <li>All material samples physically approved (tile, shutter, countertop swatch)</li>
  <li>Appliance models shortlisted and delivery dates confirmed</li>
  <li>Electrical load chart reviewed with electrician</li>
  <li>Waterproofing scope written into contract</li>
  <li>Payment milestones defined (never pay &gt;40% upfront)</li>
  <li>Site access plan agreed (who holds the key, work hours, debris disposal)</li>
  <li>10–15% contingency budget set aside for surprises</li>
</ul>
