<p>Traditional choice. Low cost, durable. Needs polishing periodically. Not recommended for modern kitchens aesthetically.</p>
<p>Granite</p>
<p>₹150 – ₹500/sq ft</p>
<p>Heat-resistant, scratch-resistant, huge variety. Best value in mid-range segment. Ideal for Indian cooking.</p>
<p>Quartz / Engineered</p>
<p>₹350 – ₹900/sq ft</p>
<p>Non-porous, zero maintenance, consistent look. Best for hygienic Indian kitchens. Top pick for 2024–25.</p>
<div class="callout"><span class="callout__title">Marble / Statuario</span>₹600 – ₹2,500/sq ft<br><br>Stunning but high maintenance. Stains from turmeric and acids. Best for baking zones or statement islands.</div>
