  <li><strong>Vitrified tiles (anti-skid, matt finish):</strong> ₹90–₹180/sq ft — most popular, easy to clean, good aesthetics</li>
  <li><strong>Large-format tiles (800×800 or 1200×600 mm):</strong> ₹140–₹300/sq ft — fewer grout lines, premium look</li>
  <li><strong>Natural stone (kota/kotah polished):</strong> ₹80–₹150/sq ft — classic, needs periodic sealing</li>
  <li><strong>Epoxy flooring:</strong> ₹60–₹120/sq ft — seamless, very easy to clean, industrial aesthetic</li>
</ul>
