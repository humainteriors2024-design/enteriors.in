<p>The shared living-dining hall is the busiest space in a 2 BHK. It has to seat the family for TV, host guests, serve meals and carry everyone from the front door to the kitchen and bedrooms. Here are eight layouts for the three hall shapes most flats have. For clearances, see <a href="/planning/furniture-layout/">furniture layout planning</a>; for the rooms themselves, our <a href="/rooms/">room guides</a>.</p>

<h2>L-shaped halls</h2>
<ol>
  <li><strong>Classic L:</strong> living in the long leg with the sofa facing the TV wall; dining in the short leg by the kitchen.</li>
  <li><strong>L with a corner sofa:</strong> an L-shaped sofa tucked into the inside corner, leaving the long wall for a TV and storage.</li>
  <li><strong>L with a crockery divider:</strong> a low crockery unit at the junction defines both zones.</li>
</ol>
