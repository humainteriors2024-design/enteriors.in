<p>Section 10 · Project Timeline</p>
<h2>Realistic Interior Design Timeline for a 2BHK</h2>
<p>One of the biggest surprises for first-time homeowners is how long a complete interior project actually takes. The typical range is <strong>45 to 120 days</strong> from design sign-off to handover. Here's a realistic phase-by-phase breakdown:</p>
<p>01</p>
<p>Design Consultation &amp; Concept Development</p>
<p>Week 1–2 (7–14 days)</p>
<p>Site visit, measurements, mood board creation, 3D visualization rendering, material shortlisting, and quote finalization. Most delays happen here — don't rush the brief.</p>
<p>02</p>
<p>Material Procurement &amp; BOQ Approval</p>
<p>Week 2–3 (7–10 days)</p>
<p>Bill of Quantities is drafted, materials are ordered — plywood, hardware, tiles, paint. Kitchen and wardrobe shutters go into fabrication at the factory. This phase can extend if materials are imported or out of stock.</p>
<p>03</p>
<p>Civil &amp; Prep Work On-Site</p>
<p>Week 3–5 (10–15 days)</p>
<p>Demolition of old tiles/fixtures, levelling, waterproofing (bathrooms), electrical conduit laying, false ceiling framework erection. Dusty and disruptive — plan to vacate if you live there.</p>
<p>04</p>
<p>Flooring &amp; Tiling</p>
<p>Week 4–6 (10–14 days)</p>
<p>Floor tiles are laid, bathroom walls tiled, grouting done. Curing time required before moving on to finish work — at least 3–5 days before foot traffic.</p>
<p>05</p>
<p>False Ceiling &amp; Electrical Finishing</p>
<p>Week 6–8 (10–14 days)</p>
<p>Gypsum/POP ceiling is installed, cove details added, LED strips laid in, light fittings roughed in. Painting of ceiling follows immediately.</p>
<p>06</p>
<p>Carpentry Installation</p>
<p>Week 7–10 (14–21 days)</p>
<p>Factory-made modular kitchen units, wardrobe carcasses, and shutters are installed on-site. Countertop is cut and fitted after cabinets are fixed. Longest phase — any delay here cascades to the project end.</p>
<p>07</p>
<p>Painting &amp; Wall Treatments</p>
<p>Week 9–11 (10–14 days)</p>
<p>Wall putty, primer, 2 coats of emulsion. Accent wall texture or wallpaper applied. Doors and window frames painted last. Do not rush drying — 24 hrs between coats minimum.</p>
<p>08</p>
<p>Finishing, Snag List &amp; Handover</p>
<p>Week 11–14 (10–20 days)</p>
<p>Light fittings, switch plates, bathroom accessories, door hardware installed. Furniture delivered. Snag list walkthrough with designer, punch items rectified. Final cleaning and handover.</p>
<p>⏱️</p>
<p><strong>Realistic summary:</strong> Budget 60–75 days for a standard 2BHK (1000–1100 sq ft) with a decent-sized modular kitchen and 2 wardrobes. For larger flats (1300–1500 sq ft) or premium projects with imported materials, plan <strong>90–120 days</strong>. Any contractor promising a full turnkey in under 30 days is cutting corners somewhere.</p>
