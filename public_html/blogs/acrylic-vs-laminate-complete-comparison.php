<p>Section 14 • When Things Go Wrong</p>
<h2>Repair &amp; Replacement</h2>
<p>Acrylic — Repair Reality</p>
<ul>
  <li><strong>Minor scratches:</strong> Can be polished out with PMMA polish (Novus, 3M)</li>
  <li><strong>Deep scratches:</strong> Permanent — panel replacement required</li>
  <li><strong>Heat damage (bubbling):</strong> Irreversible — full panel swap</li>
  <li><strong>Colour matching:</strong> Difficult — acrylic batches vary; keep spare panels</li>
  <li><strong>Panel replacement cost:</strong> Higher — skilled labour required</li>
  <li><strong>DIY repair:</strong> Polishing only; everything else needs professional</li>
</ul>
<p>Laminate — Repair Reality</p>
<ul>
  <li><strong>Minor scratches:</strong> Often hidden naturally by texture; wax-fill for small chips</li>
  <li><strong>Deep scratches:</strong> Panel replacement — easier to source matching sheets</li>
  <li><strong>Edge delamination:</strong> Re-glue with contact adhesive — common DIY fix</li>
  <li><strong>Colour matching:</strong> Easier — laminate sheets are standardised and widely available</li>
  <li><strong>Panel replacement cost:</strong> Lower — any skilled carpenter can do it</li>
  <li><strong>Long-term serviceability:</strong> Significantly better than acrylic</li>
</ul>
