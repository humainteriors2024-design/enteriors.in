<p>Section 01 • Foundation</p>
<h2>What Are Acrylic and Laminate Finishes?</h2>
<p>⚡ Quick Definition</p>
<p><strong>Acrylic</strong> is a high-gloss polymer sheet bonded onto MDF or plywood, creating a mirror-like surface. <strong>Laminate</strong> is a multi-layer paper-resin composite (HPL) pressed under high heat, available in 1,000+ textures and patterns. Both are shutter finish materials used on modular kitchen cabinets, wardrobes, and furniture.</p>
<p>What is Acrylic?</p>
<ul>
  <li>PMMA (polymethyl methacrylate) polymer sheet, 1–5mm thick</li>
  <li>Applied via heat bonding or UV-cure adhesive to MDF substrate</li>
  <li>Achieves optical clarity comparable to glass</li>
  <li>Available in solid colours, metallic, and pearlescent finishes</li>
  <li>Manufactured using casting or extrusion process</li>
  <li>Common thickness: 1.5–3mm sheet on 18mm MDF</li>
</ul>
<p>What is Laminate (HPL)?</p>
<ul>
  <li>High Pressure Laminate — layers of kraft paper + resin pressed at 140°C / 70–100 bar</li>
  <li>Décor paper on top gives the pattern; phenolic resin base gives strength</li>
  <li>Standard thickness: 0.6mm, 0.8mm, 1mm (interior) and 1.2–1.5mm (post-form)</li>
  <li>Applied via contact adhesive or hot-press bonding to ply/MDF</li>
  <li>Available in 1,000+ patterns including wood, stone, metal, abstract</li>
  <li>Major Indian brands: Merino, Greenlam, Century Laminates, Sunmica</li>
</ul>
