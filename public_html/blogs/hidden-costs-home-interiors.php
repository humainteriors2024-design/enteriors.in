<h2>Questions Every Homeowner Should Ask Their Interior Designer</h2>
<p>Q1</p>
<h4>What exactly is included in this price?</h4>
<p>Ask for a unit-by-unit breakdown. "Full home interior" is not an answer.</p>
<p>Q2</p>
<h4>What is explicitly excluded?</h4>
<p>Demand a written exclusions list — GST, transport, loose furniture, appliances, false ceiling, painting.</p>
<p>Q3</p>
<h4>What can increase the cost after I sign?</h4>
<p>Ask the designer to name the top 5 things that most often add to the final bill on projects like yours.</p>
<p>Q4</p>
<h4>Are material prices fixed once I approve them?</h4>
<p>If prices can change after approval due to supplier cost increases, this should be in writing with a cap.</p>
<p>Q5</p>
<h4>How are change requests after sign-off handled?</h4>
<p>What is the process, timeline impact, and cost for a change request made after design approval?</p>
<p>Q6</p>
<h4>Is transportation included or separate?</h4>
<p>If separate, get the exact amount — not "it depends." This should be a fixed cost at quotation stage.</p>
<p>Q7</p>
<h4>Are taxes (GST) included in the quoted amount?</h4>
<p>The most common budget surprise of all. Get a clear written confirmation: "This quote is GST inclusive / exclusive."</p>
<p>Q8</p>
<h4>What happens if site conditions require extra civil work?</h4>
<p>Establish who is responsible and how additional civil work is priced before it becomes a dispute mid-project.</p>
