<h2>Understanding Interior Design Quotation Exclusions</h2>
<p>Learning to read an interior quotation correctly is the single most powerful skill a homeowner can develop. A quotation is a legal document — what it includes and what it excludes defines exactly what you are entitled to receive for the stated price.</p>
<h3>What Is Usually Included in a Quotation</h3>
<ul>
  <li>Fixed modular woodwork — kitchen carcasses and shutters, wardrobes, TV unit, study unit</li>
  <li>Specified materials at the stated grade (always verify the grade explicitly)</li>
  <li>Basic hardware at the specified level (ask for brand names, not just "soft close")</li>
  <li>Labour for installation of included units</li>
  <li>Sometimes: transportation and installation (verify)</li>
</ul>
<h3>What Is Usually Excluded</h3>
<ul>
  <li>GST (18%) — unless explicitly stated as "inclusive of GST"</li>
  <li>Loose furniture (sofas, beds, dining sets, mattresses)</li>
  <li>Appliances (chimney, hob, refrigerator, washing machine, AC)</li>
  <li>Curtains, blinds, rugs, décor, and artwork</li>
  <li>False ceiling and painting (sometimes included, often separate)</li>
  <li>Electrical work beyond basic connection of included units</li>
  <li>Civil or correction work for builder defects</li>
  <li>Transportation, loading, and floor-shifting charges</li>
</ul>
<p><strong>How to Compare Two Quotations:</strong> Never compare total numbers alone. List out every item in both quotations and identify what is missing from the lower one. A quote that is ₹1.5 lakhs cheaper but excludes transportation, GST, and electrical work may actually cost more in total. Always compare "apples to apples."</p>
