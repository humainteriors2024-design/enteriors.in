<h2>Hidden Costs During Site Execution</h2>
<p>Site conditions are the most genuinely unpredictable source of additional costs. No matter how good the design or how thorough the planning, the actual site sometimes reveals problems that were not visible during the initial measurement visit.</p>
<ul>
  <li><strong>Wall unevenness:</strong> walls that are out of plumb by more than 15–20mm require POP or plastering correction before installation — cost: ₹15,000–₹50,000</li>
  <li><strong>Flooring level variations:</strong> if the floor is not level, base cabinet plinths need custom shimming or correction — cost: ₹5,000–₹20,000</li>
  <li><strong>Waterproofing failures:</strong> discovered after demolition in renovation projects — cost: ₹20,000–₹80,000 depending on area</li>
  <li><strong>Structural obstacles:</strong> hidden beams, columns, or conduit runs that conflict with planned unit positions require design changes mid-project</li>
</ul>
