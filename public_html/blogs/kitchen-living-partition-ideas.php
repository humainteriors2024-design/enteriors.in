<h2>Five designs that work</h2>
<ol>
  <li><strong>Full-height sliding glass</strong> in a slim black frame, the most flexible option.</li>
  <li><strong>Fluted glass pocket doors</strong> that disappear into the wall when open.</li>
  <li><strong>Breakfast counter with a fixed glass panel above</strong>, leaving a pass-through gap.</li>
  <li><strong>Half wall with open shelves</strong> for cookbooks and plants on the living side.</li>
  <li><strong>Jaali screen</strong> in CNC-cut MDF or wood, for a traditional look and airflow.</li>
</ol>

<h2>Practical points</h2>
<ul>
  <li>Use toughened glass, 8–10 mm, with a frosted band at eye level if clear.</li>
  <li>Choose a top-hung sliding system so the floor track does not collect crumbs.</li>
  <li>Keep the chimney ducted; a partition only contains what the chimney does not remove.</li>
  <li>Check walls with the builder before opening anything.</li>
</ul>
