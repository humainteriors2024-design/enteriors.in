<p>In most master bedrooms, the wardrobe wall is the only long, uninterrupted wall. Building the dressing area into it frees floor space and makes the room look calmer. Here are ten ways to do it. It is part of our <a href="/wardrobe/">wardrobe design guide</a>.</p>

<h2>Ten ideas</h2>
<ol>
  <li><strong>Dressing bay between two wardrobe sections:</strong> a 2.5–3 ft counter with a mirror and drawers.</li>
  <li><strong>Lit mirror with side lights</strong> in the bay for even light on the face.</li>
  <li><strong>Floating dresser</strong> with an open space below for a stool.</li>
  <li><strong>Pull-out mirror inside the wardrobe</strong> for tight rooms.</li>
  <li><strong>Mirror shutter</strong> on one wardrobe door with a drawer unit inside.</li>
  <li><strong>Corner vanity</strong> where the wardrobe meets the window wall.</li>
  <li><strong>Fold-down dresser</strong> that closes flush with the wardrobe.</li>
  <li><strong>Glass display bay</strong> above the dresser for perfumes and accessories.</li>
  <li><strong>Jewellery drawer with velvet dividers</strong> and a lock.</li>
  <li><strong>Charging and dryer socket</strong> inside the bay, with a cable grommet.</li>
</ol>
