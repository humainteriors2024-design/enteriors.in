<h2>06 — AvoidSix mistakes we see every month</h2>
<ol>
  <li><strong>Choosing laminates under showroom light.</strong> Showroom LEDs are tuned to flatter samples. Always take three or four shortlisted samples home and look at them on the actual wall, at the actual time of day you use the kitchen.</li>
  <li><strong>Picking gloss everywhere in an Indian kitchen.</strong> Gloss looks stunning for two weeks. Then every fingerprint, water drop and tadka mark shows up. Use gloss on one element at most; matte or textured elsewhere.</li>
  <li><strong>Matching the wood-finish laminate to the floor.</strong> Two woods of the same tone fight each other. Either go significantly lighter on the cabinets than the floor, or significantly darker. Never the same.</li>
  <li><strong>Forgetting the handles.</strong> Hardware is the 10% accent that decides whether your combination feels finished or unfinished. Brushed brass warms; matte black sharpens; chrome flattens. Pick deliberately.</li>
  <li><strong>Picking a trend colour without sampling.</strong> Sage green, forest green, navy and burgundy all shift dramatically across brands and finishes. The colour on a brochure is almost never the colour you will get.</li>
  <li><strong>Trying to match laminate to wall paint.</strong> They are different materials reflecting light differently. Aim for a tonal relationship, not a match — close enough to feel intentional, different enough to feel layered.</li>
</ol>
<h2>07 — FinishMatte, gloss or textured?</h2>
<p>The same colour in three different finishes is three different kitchens. A quick guide to which finish to ask for:</p>
<h3>Matte</h3>
<p><strong>Best for:</strong> dark colours, daily-cook kitchens, anyone tired of cleaning fingerprints. Matte black, matte navy, matte burgundy all look richer than their glossy versions and forgive more.</p>
<h3>Gloss</h3>
<p><strong>Best for:</strong> light colours in small kitchens that need to bounce light. White gloss uppers in a small flat will visually open the room. But never use gloss on lowers — they take more wear and grease, and you will see every mark.</p>
<h3>Textured (suede, woodgrain, fabric-finish)</h3>
<p><strong>Best for:</strong> wood-finish laminates and green-family colours. Texture adds a layer of realism that flat finishes cannot match. Slightly more expensive per square foot, almost always worth it on the colour that leads your palette.</p>
<h4>Studio rule of thumb</h4>
<p>If you must pick one finish across your whole kitchen, pick matte. It dates the slowest, photographs the most consistently, and survives daily Indian cooking better than the other two.</p>
