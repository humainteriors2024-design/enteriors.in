<h2>Veneer Cutting Patterns</h2>
<p>The way a log is sliced determines the grain you see on the finished panel — this is one of the most overlooked decisions in veneer selection.</p>
<h3>Rotary Cut</h3>
<p>The log is rotated against a blade like unrolling paper from a roll, producing wide, dramatic, irregular grain patterns at an efficient yield.</p>
<h3>Crown Cut</h3>
<p>Slicing through the centre of the log produces a cathedral-arch grain pattern, one of the most popular cuts for decorative panels.</p>
<h3>Quarter Cut</h3>
<p>The log is quartered before slicing, producing straighter, more uniform grain lines favoured for formal, classic interiors.</p>
<h3>Rift Cut</h3>
<p>A variation of quarter cutting at a slight angle, eliminating the fleck pattern seen in true quarter-cut oak for an even straighter grain.</p>
<h3>Plain Slice</h3>
<p>The most common cutting method, sliced parallel to the centre of the log to produce a mix of cathedral and straight grain in one sheet.</p>
<h3>Half Round Slice</h3>
<p>A cut between rotary and plain slicing that produces a unique, slightly cathedral grain with wider sheet yields.</p>
<h2>Understanding Wood Grain</h2>
<h4>Straight Grain</h4>
<p>Long, parallel grain lines that create a calm, orderly visual, common in quarter-cut species.</p>
<h4>Cathedral Grain</h4>
<p>Arched, V-shaped patterns formed by plain or crown slicing, often used for statement wardrobe doors.</p>
<h4>Curly Grain</h4>
<p>A rippling, almost three-dimensional shimmer that shifts as light moves across the surface.</p>
<h4>Bird's Eye Grain</h4>
<p>Small, circular figures resembling tiny eyes, found in select maple logs and used as a rare luxury accent.</p>
<h4>Burl Grain</h4>
<p>Swirling, chaotic patterns from a tree's burl growth, the most dramatic and expensive grain type.</p>
<h4>Flamed Grain</h4>
<p>A grain pattern that appears to ripple like flames, often seen in certain mahogany and sapele cuts.</p>
<h4>Cross Grain</h4>
<p>Grain running at an angle to the length of the panel, sometimes used deliberately for a contemporary, irregular look.</p>
<h2>Veneer Matching Techniques</h2>
<h3>Book Match</h3>
<p>Adjacent sheets from the same log are opened like a book so the grain mirrors symmetrically across the seam, the most popular matching style for wardrobe and kitchen panels.</p>
<h3>Slip Match</h3>
<p>Sheets are laid side by side in the same orientation rather than mirrored, producing a repeating rather than symmetrical pattern.</p>
<h3>Random Match</h3>
<p>Sheets are joined without specific pattern alignment, giving a casual, organic look suited to rustic interiors.</p>
<h3>End Match</h3>
<p>Sheets are matched both horizontally and vertically, often used for tall panel sections like floor-to-ceiling wardrobes.</p>
<h3>Diamond Match</h3>
<p>Four sheets are arranged to form a diamond shape, a striking centrepiece technique for feature walls and table tops.</p>
<h3>Sunburst Match</h3>
<p>Multiple sheets radiate outward from a central point, creating a dramatic starburst effect for ceiling medallions or table inlays.</p>
<h3>Reverse Slip Match</h3>
<p>Alternate sheets are flipped to create subtle tonal variation while keeping the grain direction consistent.</p>
