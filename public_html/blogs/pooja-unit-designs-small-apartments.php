<h2>Materials and details</h2>
<ul>
  <li><strong>Box:</strong> MR or BWR plywood with laminate or veneer.</li>
  <li><strong>Back panel:</strong> Corian, quartz or marble, which do not stain with oil or kumkum.</li>
  <li><strong>Base for lamps:</strong> stone, quartz or brass, never laminate.</li>
  <li><strong>Doors:</strong> CNC jaali, glass or a two-leaf door. See <a href="/doors/pooja-room-door-design/">pooja room door designs</a>.</li>
