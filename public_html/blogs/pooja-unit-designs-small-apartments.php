  <li><strong>Cabinet with folding doors:</strong> closes completely when not in use, for open living rooms.</li>
  <li><strong>Niche in the TV or crockery wall:</strong> a recessed, back-lit bay kept apart from the screen.</li>
  <li><strong>Slim floor unit:</strong> 3 ft wide with storage below and a jaali door.</li>
  <li><strong>Kitchen shrine:</strong> a small shelf in the north-east part of the kitchen, away from the hob.</li>
</ol>
