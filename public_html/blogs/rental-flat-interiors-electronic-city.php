<h2>A durable rental specification</h2>
<ul>
  <li><strong>Kitchen:</strong> BWP plywood under the sink, BWR elsewhere, laminate shutters, black granite, branded basic hinges and channels.</li>
  <li><strong>Wardrobes:</strong> hinged, floor to ceiling with lofts, MR plywood, laminate; avoid sliding tracks.</li>
  <li><strong>Bathrooms:</strong> BWP vanity, mainstream branded taps, a geyser.</li>
  <li><strong>Lights and fans:</strong> LED panels and BEE star-rated fans from mainstream brands.</li>
  <li><strong>Curtains:</strong> lined, on rods rather than tracks, easy to wash.</li>
  <li><strong>Walls:</strong> washable emulsion in a warm neutral, easy to touch up between tenants.</li>
</ul>

<h2>What to skip</h2>
<ul>
  <li>Gloss acrylic and PU shutters, which show scratches.</li>
  <li>Elaborate false ceilings with colour-changing lights.</li>
  <li>Wallpaper and textured feature walls that are hard to patch.</li>
  <li>Premium European hardware that local technicians cannot service.</li>
</ul>

<h2>Payback</h2>
<p>A semi-furnished flat typically commands a higher rent than a bare one in Electronic City, and lets faster. Check current asking rents for your building before deciding, and keep receipts: interiors may be relevant to your tax planning, so ask your accountant.</p>

<h2>Between tenants</h2>
<ol>
  <li>Inspect hinges, channels and the sink unit; tighten and adjust.</li>
  <li>Touch up paint; deep-clean the kitchen and bathrooms.</li>
  <li>Reseal granite and check for leaks under sinks.</li>
  <li>Photograph the flat again for the listing.</li>
</ol>
