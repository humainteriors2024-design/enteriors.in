<p>Most flats in Electronic City share the same living room: an L-shaped hall with the living area at one end and the dining area near the kitchen, a balcony that often faces the afternoon sun, and ceilings around 9.5–10 ft. Here are fifteen ideas that work in that room, with what each costs. The planning detail is in our <a href="/rooms/living-room-electronic-city/">living room guide for Electronic City apartments</a>.</p>

<h2>Layout ideas</h2>
<ol>
  <li><strong>Sofa on the long wall, facing the TV.</strong> Keep the walkway from the door behind or beside the sofa, never between the sofa and the screen.</li>
  <li><strong>A rug to define the living zone.</strong> About 5×8 ft, with the front legs of every seat on it.</li>
  <li><strong>Dining by the kitchen door.</strong> A four-seater with a bench fits most 9×10 ft dining areas. See <a href="/rooms/dining-room/">dining room design</a>.</li>
</ol>
