<p>Most kitchen regrets do not show up on handover day. They show up a year later, as a swollen sink cabinet, a mixer cable stretched across the hob or a corner nobody can reach. Here are fifteen we see repeatedly in Bangalore homes, and how to avoid each. For the full design process, see the <a href="/modular-kitchen/">modular kitchen design guide</a>.</p>

<h2>Materials</h2>
<ol>
  <li><strong>The wrong board under the sink.</strong> Use BWP plywood or WPC. See <a href="/materials/marine-plywood/">marine plywood</a>.</li>
  <li><strong>Unsealed edges.</strong> Ask for machine-pressed edge banding on all four edges of every panel.</li>
  <li><strong>Gloss everywhere.</strong> Matte on base units; gloss on a few uppers at most.</li>
  <li><strong>A light, porous counter with hard water.</strong> Choose quartz or dark granite, sealed. See the <a href="/modular-kitchen/countertop-guide/">countertop guide</a>.</li>
</ol>
<?= img('swollen-sink-cabinet-vs-bwp-plywood', caption: 'A swollen particle-board sink cabinet beside a BWP plywood one after the same leak') ?>

<h2>Planning</h2>
<ol start="5">
  <li><strong>Too few sockets.</strong> Plan eight to ten, including the chimney, RO and spares. See <a href="/planning/electrical-points/">electrical points</a>.</li>
  <li><strong>A chimney with no proper duct.</strong> Ducted, short, two bends at most. See the <a href="/blogs/kitchen-chimney-hob-guide/">chimney and hob guide</a>.</li>
  <li><strong>No home for the bin, cylinder or RO.</strong> Draw each into the plan.</li>
  <li><strong>Hob next to the sink.</strong> Leave 2 ft of counter between them.</li>
  <li><strong>Ordering before plumbing and tiling.</strong> Services first, then measure, then the factory.</li>
</ol>

<h2>Storage</h2>
<ol start="10">
  <li><strong>Shelves where drawers should be.</strong> Drawers under the hob show everything.</li>
  <li><strong>A dead corner.</strong> Fit a carousel or magic corner in every corner.</li>
  <li><strong>Stopping short of the ceiling.</strong> Lofts hold festival vessels; the gap collects grease.</li>
</ol>

<h2>Finishing</h2>
<ol start="13">
  <li><strong>No under-cabinet light.</strong> Wall units shadow the counter exactly where you chop.</li>
  <li><strong>Choosing colours from a brochure.</strong> See full sheets in your kitchen light.</li>
  <li><strong>Skipping the snag check.</strong> Check hinges, drawer closure, sink sealant and the chimney duct before final payment.</li>
</ol>

<h2>A pre-order checklist</h2>
<ul class="ticks">
  <li>Board grade and brand named for each cabinet group</li>
  <li>Finish and hardware brand and series in the quote</li>
  <li>All sockets, gas, water and duct positions on the drawing</li>
  <li>Drawers under the hob; a fitting in every corner</li>
  <li>Bin, cylinder, RO and dishwasher spaces drawn</li>
  <li>Countertop chosen for your water</li>
</ul>
