<p>₹20,000–60,000</p>
<p>Moving existing points, upgrading wiring to accommodate new layouts and appliances.</p>
<p>🪟</p>
<p>Civil Modifications</p>
<p>₹15,000–50,000</p>
<p>Breaking walls, filling gaps, box-up columns, or fixing uneven floors before interiors.</p>
<p>🚿</p>
<p>Plumbing Changes</p>
<p>₹10,000–35,000</p>
<p>Shifting sink, adding new point in utility or kitchen island. Often discovered mid-project.</p>
<p>📦</p>
<p>Transportation / Delivery</p>
<p>₹8,000–20,000</p>
<p>Furniture, appliances, and material delivery — especially for high-floor flats without service lifts.</p>
<p>📋</p>
<p>GST (18%)</p>
<p>18% of all work</p>
<p>Applies to material and labour if your contractor is GST-registered. Often excluded from quotes.</p>
<p>🧱</p>
<p>Material Wastage</p>
<p>5–10% of material</p>
<p>Tiles, laminates, and plywood ordered extra to account for cuts, breakage, and defects.</p>
<p>🏠</p>
<p>Society Charges</p>
<p>₹5,000–25,000</p>
<p>Security deposit, maintenance charges, material lift access, and parking for contractor vehicles.</p>
<p>🔧</p>
<p>Post-Completion Fixes</p>
<p>₹5,000–20,000</p>
<p>Touch-ups, hardware adjustments, snag list work. Always reserve a small post-completion budget.</p>
