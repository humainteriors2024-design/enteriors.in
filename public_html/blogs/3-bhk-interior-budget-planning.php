<p>03</p>
<p>Budget Framework</p>
<h2>Where Does Your Interior Budget Go?</h2>
<p>Understanding how budgets are split helps you make smarter trade-offs. The kitchen and wardrobes together consume nearly half of any interior budget — plan these first.</p>
<div class="callout"><span class="callout__title">Note</span><strong>Rule of thumb:</strong> Allocate a maximum of 50% of your total budget to kitchen + wardrobes combined. This leaves enough for false ceiling, lighting, painting, and furniture that transform the look and feel of your home.</div>
