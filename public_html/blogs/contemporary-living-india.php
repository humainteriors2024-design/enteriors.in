<p>08 — Before You Begin</p>
<h2>Your contemporary interior checklist</h2>
<p>Before you speak to a designer, brief a contractor, or purchase a single piece of furniture — go through this checklist. These are the questions that separate a coherent contemporary home from an expensive but disjointed one.</p>
<h3>Pre-design checklist for homeowners</h3>
<p>Have I defined my dominant palette — walls, floors, and ceilings first?</p>
<p>Is my lighting plan done before furniture is placed?</p>
<p>Have I chosen one signature Indian element per room?</p>
<p>Is all storage accounted for and concealed in the plan?</p>
<p>Have I tested paint colours in natural daylight?</p>
<p>Is my AC and electrical plan done before civil work?</p>
<p>Have I budgeted 15–20% buffer for surprises?</p>
<p>Do I have a timeline with buffer for deliveries?</p>
<p>Have I chosen hardware finishes consistently throughout?</p>
<p>Are curtain tracks planned before wall finishes are done?</p>
