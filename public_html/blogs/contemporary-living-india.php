<h4>The 60–30–10 rule</h4>
<p>60% dominant neutral, 30% secondary tone, 10% accent colour. This ratio works for every room size.</div>
<div class="callout callout--tip"><span class="callout__title">Tip</span>3×</p>
<h4>Three textures minimum</h4>
<p>Any well-designed contemporary room has at least three tactile surfaces working together to create depth.</div>
<div class="callout callout--tip"><span class="callout__title">Tip</span>1st</p>
<h4>Lighting is always first</h4>
<p>Plan your lighting before furniture. Retrofitting good lighting into a finished room is expensive and disruptive.</div></div>
