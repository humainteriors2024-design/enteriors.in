<p>New apartment projects in Chandapura, Bommasandra and Electronic City often hand over hundreds of flats in a few weeks. Owners who plan ahead move in on time; those who start after the keys arrive often wait an extra month for a designer. Here is a week-by-week plan. It is part of our <a href="/planning/">home planning guide</a>.</p>

<h2>Before handover (weeks −8 to 0)</h2>
<ul>
  <li>Set the budget with the <a href="/calculators/interior-cost/">interior cost calculator</a>.</li>
  <li>Shortlist two or three firms; visit finished homes and factories. See the <a href="/interior-designers-bangalore/chandapura/">Chandapura area guide</a>.</li>
  <li>Get the builder's floor plan and electrical layout.</li>
  <li>Read the society's interior rules: work hours, deposit, lift slots.</li>
</ul>

<h2>Week by week after handover</h2>
<ol class="steps">
  <li><small>Week 1</small><strong>Handover and snag list</strong>Check damp, tiles, doors, plumbing and electrics; get the builder to fix them. See the <a href="/planning/new-home-handover-checklist/">handover checklist</a>.</li>
  <li><small>Weeks 2–3</small><strong>Measure, design and sign</strong>Site measurement, 3D design, 2D drawings, material schedule, itemised quote, milestones.</li>
  <li><small>Weeks 4–6</small><strong>Site work and factory in parallel</strong>Electrical and plumbing changes, ceiling framing and kitchen tiles on site; kitchen and wardrobes in the factory.</li>
  <li><small>Weeks 7–9</small><strong>Installation</strong>Kitchen, wardrobes, TV, foyer and pooja units; ceiling boarding and putty.</li>
  <li><small>Weeks 10–11</small><strong>Paint, lights and curtains</strong>Paint, light fittings, fans, curtains and accessories.</li>
  <li><small>Week 12</small><strong>Snag, clean and move in</strong>Snag list, deep cleaning, final payment against a closed snag list.</li>
</ol>
