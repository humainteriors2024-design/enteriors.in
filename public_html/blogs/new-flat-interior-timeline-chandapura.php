<h2>Local tips</h2>
<ul>
  <li><strong>Society rules:</strong> many large communities restrict work to weekdays and set lift slots; ask the firm to plan deliveries around them.</li>
  <li><strong>Monsoon:</strong> June–October painting needs longer drying; boards must be stored indoors and off the floor.</li>
  <li><strong>Hard water:</strong> plan an RO point and the right sink before the kitchen is designed.</li>
  <li><strong>Power:</strong> plan an inverter circuit before the ceiling goes up.</li>
</ul>

<h2>How to save two to three weeks</h2>
<ol>
  <li>Sign the design within two weeks of handover.</li>
  <li>Choose a firm with its own factory nearby, so production starts immediately.</li>
  <li>Finish electrical and plumbing changes while modules are in production.</li>
  <li>Approve samples and colours early; late changes stop the factory.</li>
</ol>
