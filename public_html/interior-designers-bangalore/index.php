<h2>Local factors that affect your choice</h2>
<h3>Distance and traffic</h3>
<p>A firm across the city can take two hours to reach your site. Designers and supervisors visit less often when the trip is long, and small fixes wait longer. Prefer firms whose office, factory or active projects are within reasonable reach of your home, whether that is Whitefield, Sarjapur Road, Electronic City, Hebbal or elsewhere.</p>
<h3>Where the furniture is made</h3>
<p>Many modular factories sit in industrial belts on the city's edges, such as Peenya, Bommasandra and along Hosur Road. Ask where your modules will be made and visit if you can. A firm that hesitates to show its production is telling you something.</p>
<h3>Apartment society rules</h3>
<p>Most associations set work hours, noise limits, service-lift slots and a refundable deposit, and some restrict weekend work. These rules can stretch a schedule. A firm that already works in your building or area will know them.</p>
<h3>Monsoon humidity</h3>
<p>From June to October, humidity is high. Boards should be stored off the floor and indoors, edges sealed, and paint given enough drying time. Ask how the firm handles material storage during the rains, and insist on BWP plywood for kitchen base units.</p>
<h3>Builder handover timing</h3>
<p>New projects in areas such as Sarjapur, Devanahalli or North Bangalore often hand over many flats at once, and good firms get booked. Start the selection process six to eight weeks before your keys arrive.</p>

