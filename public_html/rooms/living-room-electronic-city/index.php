<h2>Dining, crockery, foyer and pooja</h2>
<ul>
  <li><strong>Dining table:</strong> a six-seater needs about 6×3 ft plus 3 ft clear around it. In a 9×10 ft dining area, a four-seater with a bench fits better.</li>
  <li><strong>Crockery unit:</strong> 4–5 ft wide, with glass shutters on top and drawers below. Ideas in <a href="/rooms/crockery-unit/">crockery unit designs</a>.</li>
  <li><strong>Foyer:</strong> a shallow shoe cabinet with a seat, a mirror and a key drawer. See <a href="/furniture/shoe-rack-design/">shoe rack designs</a>.</li>
