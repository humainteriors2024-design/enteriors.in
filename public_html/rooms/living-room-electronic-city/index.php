<p>Zone the two parts clearly. A rug and the sofa define the living area; a pendant over the table and the crockery unit define the dining. Keep a straight, 3 ft wide walking line from the front door to the kitchen and the bedrooms so nobody walks between the sofa and the TV.</p>

<h2>The TV wall</h2>
<p>The TV wall is the one built-in that every guest sees. Three common treatments suit flats here:</p>
<ul>
  <li><strong>Laminate or veneer panel with a floating unit.</strong> A 7–8 ft wall-hung unit with drawers, on a panelled backdrop 4 ft wider than the TV. Clean, easy to wipe, and the wiring hides behind the panel.</li>
  <li><strong>Fluted panel feature.</strong> Vertical fluted MDF or WPC panels behind the TV, with a cove light. Adds texture without paint. See <a href="/trends/fluted-panels/">fluted panels</a>.</li>
  <li><strong>Stone-look or textured wall.</strong> Large-format porcelain or a stone-look laminate behind the TV with open niches either side. See <a href="/wall-design/wall-panelling/">wall panelling</a>.</li>
</ul>
<?= img('tv-unit-wall-with-fluted-panels', caption: 'A floating TV unit on a fluted panel wall with concealed wiring and a cove light') ?>
<p>Plan the electrical points before the panel goes up: two sockets and an HDMI conduit behind the TV, a socket for a set-top box or soundbar in the unit, and a separate point for a cove light. Sizes and materials are in <a href="/furniture/tv-unit-design/">TV unit design</a>.</p>

<h2>Ceilings and lighting</h2>
<p>Ceilings in most towers here are about 9.5–10 ft. A full false ceiling lowers the whole room; a peripheral ceiling does not.</p>
<ul>
  <li><strong>Peripheral gypsum ceiling, 6–8 inch drop,</strong> around the edges of the living and dining areas. It hides AC piping and carries cove lights and spots.</li>
  <li><strong>Three layers of light:</strong> a general layer (panel or spot lights), a mood layer (cove and TV backlight) and a task layer (a reading lamp by the sofa, a pendant over the dining table).</li>
  <li><strong>Warm white, 3,000–4,000 K,</strong> in living areas. Cool white makes the room feel like an office.</li>
</ul>
<p>Ceiling types and their costs are in the <a href="/false-ceiling/">false ceiling guide</a> and <a href="/cost/false-ceiling-cost/">false ceiling cost</a>; lighting layouts in the <a href="/planning/lighting-design/">lighting design guide</a>.</p>

