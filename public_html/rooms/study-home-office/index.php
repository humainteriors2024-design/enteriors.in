<h2>Light</h2>
<ul>
  <li><strong>Daylight from the side:</strong> place the desk at right angles to the window to avoid glare and silhouettes on calls.</li>
  <li><strong>Task light:</strong> a 4,000 K desk lamp or an under-shelf strip on the side opposite your writing hand.</li>
  <li><strong>Face light for calls:</strong> a soft light in front of you, not behind.</li>
</ul>
<p>Lighting layers are explained in the <a href="/planning/lighting-design/">lighting design guide</a>.</p>

<h2>Power and data</h2>
<p>Plan four to six sockets at desk height, a network point if the router is far away, a USB charging point and a cable tray or grommet in the desk. If power cuts are common, put the desk and router on the inverter circuit. See <a href="/planning/electrical-points/">electrical points</a>.</p>

<h2>Storage and backdrop</h2>
<ul>
  <li>Closed cabinets for files and printer supplies; open shelves for books you use.</li>
  <li>A pin-board or magnetic board for children's study areas.</li>
  <li>A calm wall or tidy bookshelf behind your chair for video calls.</li>
  <li>Acoustic panels or a rug to cut echo in bare rooms.</li>
</ul>

