<h2>Shapes for different rooms</h2>
<ul>
  <li><strong>Rectangular:</strong> the most seats per square foot; suits long dining areas.</li>
  <li><strong>Round:</strong> suits square areas and conversation; no corners to bump.</li>
  <li><strong>Bench on one side:</strong> pushes against a wall and seats children three to a bench.</li>
  <li><strong>Extendable:</strong> a four-seater daily that opens to six or eight for guests.</li>
  <li><strong>Wall-mounted or fold-down:</strong> for 1 BHKs and studio flats.</li>
</ul>

<h2>Layouts for open living-dining halls</h2>
<p>In an L-shaped hall, put the dining table in the short leg near the kitchen and the sofa in the long leg facing the TV. Keep a 3 ft walking line from the front door to the kitchen that does not cut between the sofa and the TV. A rug under the sofa and a pendant over the table define the two zones without a wall. For the full hall, see the <a href="/rooms/living-room/">living room guide</a> and our <a href="/rooms/living-room-electronic-city/">living-dining guide for Electronic City apartments</a>.</p>

<h2>Storage: the crockery unit</h2>
<p>A crockery unit 4–5 ft wide on the wall nearest the kitchen holds serving dishes and the good dinner set. Glass shutters above, drawers for cutlery and table linen below, and a counter at about 3 ft for serving. Ideas and costs are in <a href="/rooms/crockery-unit/">crockery unit designs</a>.</p>

<h2>The wash basin</h2>
<ul>
  <li>Place it on a side wall or in a niche, not facing the table.</li>
  <li>Use a counter of granite or quartz with a small cabinet below in BWP plywood.</li>
  <li>Tile or waterproof the wall to 4 ft and add a mirror and a light.</li>
</ul>

<h2>Lighting</h2>
<p>Hang one large pendant or a row of two or three small ones 28–32 inches above the table, on a dimmer. Add soft background light from a cove or wall lights so the table is not the only bright spot. Lighting layouts are in the <a href="/planning/lighting-design/">lighting design guide</a>.</p>

