<p>Plan for ventilation: louvred or jaali shutters, a perforated back panel or a gap of an inch at the base. Use laminate inside and BWR plywood in the carcass; wet shoes are hard on boards. More designs are in <a href="/furniture/shoe-rack-design/">shoe rack design</a>.</p>

<h2>Creating a foyer in an open flat</h2>
<ol>
  <li><strong>A partition:</strong> a slatted wood, jaali or fluted-glass screen 2–4 ft wide beside the door. See <a href="/doors/glass-partition-design/">glass partition design</a>.</li>
  <li><strong>A floor change:</strong> a border of different tile, a stone inlay or a rug marks the zone.</li>
  <li><strong>A ceiling change:</strong> a small false ceiling with a pendant or spot.</li>
  <li><strong>A wall feature:</strong> a panel, a niche or a piece of art on the wall you see first.</li>
</ol>

<h2>Lighting</h2>
<p>Use a warm downlight or pendant over the foyer and a small light in the shoe cabinet or under a floating unit. A motion-sensor light is useful when you come home with your hands full. The first switch inside the door should control it.</p>

<h2>Flooring and the door</h2>
<p>Choose a hard-wearing, easy-to-mop floor here: vitrified tile, granite or a stone border. A coir or rubber-backed mat outside and a washable rug inside catch grit. For the door itself, see <a href="/doors/main-door-design/">main door designs</a> and <a href="/vastu/main-door-vastu/">main door vastu</a>.</p>

