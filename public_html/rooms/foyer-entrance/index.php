<p>The foyer is the smallest space in a home and one of the hardest working. It is where shoes come off, keys and bags land, umbrellas drip in the monsoon and guests get their first look at the home. In many flats there is no separate foyer at all, just a door into the living room. This guide shows how to create one in any home. It is part of our <a href="/rooms/">room guides</a>.</p>

<h2>What a foyer needs</h2>
<ul>
  <li><strong>Shoe storage</strong> for the whole family, closed and ventilated.</li>
  <li><strong>A seat</strong> to put on shoes, about 17 inches high.</li>
  <li><strong>A mirror</strong> for a last check, at least 2×3 ft.</li>
  <li><strong>A key and wallet drawer</strong>, ideally with a charging socket.</li>
  <li><strong>Hooks or a tall bay</strong> for bags, umbrellas and helmets.</li>
  <li><strong>Light</strong> on a switch right beside the door.</li>
</ul>
