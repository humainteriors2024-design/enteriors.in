<h3>Common Vastu Mistakes in Pooja Rooms</h3>
<ul>
  <li>Placing the Pooja room in the south zone without alternative orientation for the worshipper</li>
  <li>Positioning idols directly against the back wall with no space behind them — Vastu recommends at least 25mm clearance from the wall</li>
