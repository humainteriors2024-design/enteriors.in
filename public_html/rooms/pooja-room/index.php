<h2>Seating Planning</h2>
<p>Seating requirements depend on the family's worship style, the age profile of the household, and the floor area available. Seating must be planned as part of the initial layout — retrofitting seating into an already-designed space is one of the most common regrets in dedicated Pooja rooms.</p>
<p>Traditional Floor Seating</p>
<p>A yoga mat, asan (prayer mat), or cushion at floor level. Requires the idol shelf to be at 600–800mm height. Needs 900mm × 600mm clear floor space per person in front of the unit.</p>
<p>Raised Platform</p>
<p>A 100–150mm raised timber or stone platform defines the seating area and creates a level change that signals the transition into the worship zone. A popular solution in dedicated rooms.</p>
<p>Folding / Stackable Seating</p>
<p>For spaces that need to accommodate varying numbers during festivals. Foldable padded prayer seats that stack in a side cabinet are the most space-efficient solution.</p>
<p>Senior Citizen Seating</p>
<p>A low stool or backed chair at 350–400mm seat height allows elderly family members to worship comfortably without floor seating. The idol shelf height must be recalculated to 900–1100mm for this use case.</p>
<h2>Pooja Room Planning for Apartments</h2>
<p>Urban apartment living demands creative, space-efficient solutions that respect both the sacred nature of the Pooja space and the practical constraints of a compact floor plan. The following strategies address the most common apartment planning challenges.</p>
<div class="callout"><span class="callout__title">Note</span><h3>Key Strategies for Apartments</h3>
<ul>
  <li><strong>Integrate into joinery:</strong> A Pooja unit within a living room wall cabinet run is the most space-efficient solution. Consistent materials and finishes ensure the unit reads as designed rather than afterthought.</li>
  <li><strong>Prioritize ventilation from the start:</strong> In apartments, incense smoke has nowhere to go without active ventilation planning. Specify a small exhaust fan or ensure the unit opens to a ventilated room — not an enclosed corridor.</li>
  <li><strong>Use jaali or glass doors:</strong> Closed-door units require less frequent cleaning and protect idols from dust. The right door ensures the unit can function in a visible social space without constant management.</li>
  <li><strong>Vertical thinking:</strong> In a compact space, use wall height. A tall unit from floor to ceiling can accommodate idol shelves at mid-height, storage above and below, and concealed lighting at multiple levels.</li>
  <li><strong>Stone for the functional zone:</strong> Even in an otherwise laminate or lacquered unit, specify granite or marble for the idol shelf and lamp platform. This improves fire safety, simplifies cleaning, and increases long-term durability.</li>
</ul></div>
<h2>Pooja Room Planning for Villas</h2>
<p>Villas offer the space to create a dedicated Pooja room that truly reflects the family's spiritual tradition and design vision. The key challenge shifts from space efficiency to execution quality — ensuring the room justifies the floor area allocated to it and functions at the highest level for decades.</p>
<div class="callout"><span class="callout__title">Note</span><h3>Villa Pooja Room Priorities</h3>
