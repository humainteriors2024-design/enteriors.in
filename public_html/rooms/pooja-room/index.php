<h2>Pooja Room Layout Planning</h2>
<p>A functional layout resolves the placement of idols, lamps, storage, seating, and accessories in a way that supports natural worship movement without requiring reaching, bending uncomfortably, or navigating obstacles.</p>
<h3>Idol Shelf</h3>
<p>The idol shelf should be positioned so the primary deity's eyes are level with the worshipper's eyes when seated, or slightly above. For floor seating, this is typically 600–800mm from the floor. For standing use, 1400–1600mm. The shelf should have a minimum depth of 300mm to accommodate idols with extended elements (arms, Ganesha's trunk) without risk of toppling.</p>
<h3>Lamp &amp; Deepam Placement</h3>
<p>The lamp position is one of the most critical safety decisions in the layout. Place the lamp holder to the right of the idol (from the worshipper's perspective), on a dedicated platform or shelf with a minimum 300mm clearance above it to any flammable surface or overhead element. Never position a lamp directly below a shelf.</p>
<h3>Storage Zone</h3>
<p>Daily-use items — agarbatti, matchboxes, camphor — should be within arm's reach from the seated position, ideally in a drawer or small door cabinet at the side of the unit. Festival storage (larger vessels, additional lamps, brass items) can occupy deeper cabinets below or above the idol zone.</p>
<div class="callout callout--tip"><span class="callout__title">Enteriors Insight</span>Map your typical daily worship sequence before finalizing placement. The natural left-to-right or right-to-left flow of your ritual should determine where each element sits — not standard drawings or catalogue layouts.</div>
