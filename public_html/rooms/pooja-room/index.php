<p>Idol placement, lamp positioning, and accessory arrangement. Final lighting adjustment for balance between electrical lighting and deepam flame.</p>
<h2>Common Pooja Room Mistakes</h2>
<p>These are the errors most consistently identified after installation — all avoidable with proper planning at the design stage.</p>
<ol>
  <li>01<strong>Oversized idols in an undersized unit</strong><p>Selecting idols after the unit is built results in idols that overflow the shelf, obstruct lamp placement, and make daily worship feel cramped. Confirm idol dimensions before finalizing shelf sizes.</p></li>
  <li>02<strong>No ventilation in an enclosed unit</strong><p>A sealed unit with regular incense and lamp use will blacken the interior within months. Specify jaali doors, an exhaust fan, or a ventilation gap from the outset.</p></li>
  <li>03<strong>Combustible surface directly below the lamp</strong><p>Placing the diya or oil lamp on a laminate, wood, or MDF surface is the single greatest fire risk in the Pooja room. Always specify stone for the lamp platform.</p></li>
  <li>04<strong>Cool white lighting</strong><p>4000K+ lighting in a Pooja space is jarring — it conflicts with the warm glow of the lamp and makes the space feel clinical rather than sacred. Always specify 2700–3000K throughout.</p></li>
  <li>05<strong>Inadequate storage planning</strong><p>When storage is not planned around actual items, the top surface of the unit becomes the default storage zone — creating the clutter that makes the space feel neglected.</p></li>
  <li>06<strong>No electrical provision</strong><p>Not running a conduit for lighting, bell, or speaker during the rough-in stage means surface-run wiring or extension leads — both visually disruptive and potentially unsafe near open flames.</p></li>
  <li>07<strong>Wrong idol shelf height</strong><p>A shelf designed for standing worship is inaccessible during seated prayer, and vice versa. Confirm the primary worship position before fixing shelf heights in the design.</p></li>
  <li>08<strong>Pooja unit in the bedroom without enclosed doors</strong><p>An open Pooja unit in the bedroom with idols visible during sleep is considered inappropriate in most traditions. If the bedroom is the only option, fully enclosed doors are essential.</p></li>
  <li>09<strong>Porous stone without sealing</strong><p>Marble and light-coloured stone will permanently stain from haldi and kumkum within the first weeks of use if left unsealed. Seal all stone surfaces before installation and annually thereafter.</p></li>
</ol>
<h2>Pooja Room Maintenance Guide</h2>
<p>A Pooja room that is difficult to maintain will not stay clean — and a clean space is the most fundamental expression of respect for the sacred area. Design for ease of cleaning from the outset, and establish a simple routine that can be sustained.</p>
<h3>Daily Maintenance</h3>
<ul>
  <li>Wipe the idol shelf with a dry soft cloth to remove fallen flowers, petals, and dust</li>
  <li>Remove used agarbatti stubs and camphor residue from the holder immediately after worship</li>
  <li>Wipe the lamp stand and surrounding stone surface of oil drips after each use</li>
  <li>Replace water in any vessel offerings; stagnant water encourages mould on stone surfaces</li>
</ul>
<h3>Weekly Maintenance</h3>
<ul>
  <li>Clean idols with a damp soft cloth; dry immediately — do not leave moisture on marble or brass</li>
  <li>Wipe all stone surfaces with a damp cloth; follow with a dry cloth to prevent water marks</li>
  <li>Clean glass or jaali doors of smoke film and fingerprints</li>
  <li>Dust CNC-cut carved panels with a soft brush — a narrow paintbrush reaches into cuts effectively</li>
  <li>Check the exhaust fan or ventilation pathway for blockages</li>
</ul>
