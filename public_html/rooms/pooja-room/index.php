<h2>Door Design Guide</h2>
<p>The door is both a functional and spiritual threshold for the Pooja space. It controls visibility, privacy, and the degree to which the sacred zone is visually separated from the living area. The wrong door choice is one of the most common post-installation regrets.</p>
<p>Open (No Door)</p>
<p>Suitable where the Pooja unit is a permanent display element in the living room. Requires higher discipline in daily maintenance as dust and kitchen fumes affect idols continuously.</p>
<p>Jaali Doors</p>
<p>Perforated or lattice panels in wood, brass, or CNC-cut material. Allow the glow of the lamp to be visible when closed. The traditional choice — ventilated, beautiful, and spiritually appropriate.</p>
<p>CNC-Cut Panels</p>
<p>Laser or CNC-cut patterns in MDF or plywood. Highly customizable — geometric, floral, traditional, or contemporary motifs. Cost-effective and widely available from joinery workshops.</p>
<p>Glass Doors</p>
<p>Clear, frosted, or etched glass panels. Modern aesthetic; allows visual connection to the idols when closed. Frosted glass diffuses the interior lamp glow beautifully. Easy to clean.</p>
<p>Solid Wooden Doors</p>
<p>Full panel timber doors. Maximum privacy; completely encloses the space. Best for rooms where the Pooja unit shares space with other functions and needs to be fully closed.</p>
<p>Brass-Detailed Doors</p>
<p>Wooden doors with applied brass repoussé panels or brass inlay work. The most premium traditional option. Adds significant visual weight and authenticity to the entry.</p>
<p>For apartment units integrated into the living area, jaali or glass doors offer the best balance — they allow the lamp glow to remain visible from the room even when the unit is closed, maintaining the sense of an active spiritual presence without requiring the unit to be permanently open.</p>
<h2>Lighting Design Guide</h2>
<p>Lighting in a Pooja room serves multiple roles simultaneously: it illuminates idols for worship, creates an atmosphere of reverence, enhances the visual depth of carved and decorative elements, and works alongside the natural light of the deepam. Each requirement points to a different lighting type — and all of them should be planned together.</p>
<p>Ambient Ceiling Light</p>
<p>The base layer of illumination for the room or unit. A single recessed downlight or surface-mounted fitting at the ceiling. Warm white (2700–3000K) is essential — cool white disrupts the warm tone of the lamp flame.</p>
<p>Accent Spotlights</p>
<p>Small directional recessed spotlights or adjustable surface spotlights aimed at the idol shelf. Creates a focused zone of light that draws the eye and elevates the idols as the visual centrepiece of the space.</p>
<p>LED Strip — Shelf Edge</p>
<p>Warm white LED strip concealed behind the idol shelf lip. Creates a soft uplight or downlight around the idols. One of the most effective and affordable ways to elevate the quality of the Pooja unit after dark.</p>
<p>Backlit Panel</p>
<p>A translucent panel — marble, glass, or Corian — lit from behind. Creates a radiant glow effect behind the idols that reinforces the sense of the sacred. Requires careful installation to conceal the LED source.</p>
<p>Deepam / Lamp Light</p>
<p>The open flame of the diya or oil lamp is both functional and spiritual. Design other lighting to complement, not compete with, the flame. Dimmer switches on electric lighting allow the lamp to become the primary light source during worship.</p>
<p>Dimmable Control</p>
<p>All electric lighting in the Pooja zone should be dimmable. The ability to dim the electrical lighting during active worship allows the lamp flame to dominate — which is both spiritually appropriate and experientially more powerful.</p>
<div class="callout"><span class="callout__title">Note</span><h3>Colour Temperature Guidelines</h3>
<ul>
  <li><strong>2700K (warm white)</strong> — Closest to candlelight. Best for the idol zone and surrounding areas. Complements the flame colour of the deepam.</li>
  <li><strong>3000K (soft warm white)</strong> — Slightly cooler but still warm. Acceptable for ambient and accent zones.</li>
  <li><strong>4000K+ (neutral to cool white)</strong> — Avoid entirely. Disrupts the warmth of the space and makes the lamp flame appear insignificant.</li>
</ul></div>
<h2>False Ceiling Design</h2>
<p>The ceiling above the Pooja space creates the architectural frame that defines the zone and signals its importance. Even in a unit within a larger room, a distinct ceiling treatment above the Pooja area elevates its presence significantly.</p>
<p>Traditional Stepped Ceiling</p>
<p>A lowered stepped or coved ceiling in plaster. Creates a canopy effect over the worship zone. Can accommodate concealed cove lighting at each step. Traditional and highly effective.</p>
<p>Wooden Ceiling Panel</p>
<p>A timber-panelled or slatted ceiling section over the idol zone. Warm, organic, and dramatic. Particularly effective with warm backlit concealed lighting integrated into the panel structure.</p>
<p>Coffered Ceiling</p>
<p>Grid-patterned recessed ceiling panels. Creates depth and formality above the worship space. Works best in larger dedicated rooms where ceiling height allows the coffers to read clearly.</p>
<p>Minimal Flat Ceiling</p>
<p>A clean flat surface in the same finish as the room ceiling but at a slightly lower level to define the zone. The right choice for contemporary and minimalist designs.</p>
<p>Decorative Carved Ceiling</p>
<p>CNC-cut or cast plaster panels with traditional motifs — lotus, Om symbol, geometric patterns. The signature element in premium traditional and temple-style Pooja rooms.</p>
