<h3>Idol Material Considerations</h3>
<p>Marble Idols</p>
<p>White marble is the most commonly used material for premium idols. Non-porous with sealing; resists haldi staining better than porous stone. Heavy — verify shelf load capacity.</p>
<p>Brass Idols</p>
<p>Traditional, durable, and heat-resistant. Develops a natural patina. Requires periodic polishing with tamarind or brass polish to maintain brightness.</p>
<p>Panchaloha</p>
<p>Five-metal alloy used in South Indian temple tradition. Rare, expensive, and considered sacred. Requires periodic temple-style cleaning — obtain guidance from the supplier.</p>
<p>Stone (Black Granite / Saligrama)</p>
<p>Dense, non-porous, and extremely durable. Common for Shivlingas and certain deity forms. Requires no sealing; cold to the touch; very long-lasting.</p>
<div class="callout callout--tip"><span class="callout__title">Enteriors Insight</span>Plan the idol shelf after confirming the final collection of idols and photographs — not before. The number, height, and spread of items determines the minimum shelf width, depth, and clearance. Designing the shelf first and fitting idols later is a common cause of overcrowded, impractical Pooja units.</div>
<h2>Storage Planning</h2>
<p>Inadequate storage is the primary reason Pooja units become cluttered and difficult to maintain. Map out every item that will be stored before the design is finalized, then design the storage zones around those real requirements.</p>
<h3>Daily-Use Storage (Within Arm's Reach)</h3>
<ul>
  <li><strong>Agarbatti / incense sticks</strong> — Shallow drawer or vertical slot within the unit; accessible without opening multiple compartments</li>
  <li><strong>Matchboxes / lighter</strong> — Small dedicated drawer; keep away from the lamp zone</li>
  <li><strong>Camphor (kapoor)</strong> — Separate sealed compartment; camphor fumes can affect adjacent materials over time</li>
  <li><strong>Lamp oil</strong> — Small enclosed base cabinet; oil must not be stored near an active flame</li>
  <li><strong>Kumkum, haldi, vibhuti</strong> — Individual small containers within a dedicated shallow tray</li>
  <li><strong>Fresh flowers</strong> — A small tray or stand at idol level; flowers should not sit directly on the idol shelf in a way that obstructs access</li>
  <li><strong>Pooja books / prayer cards</strong> — A book slot or small shelf at a reachable height</li>
</ul>
<h3>Festival &amp; Occasional Storage</h3>
<ul>
  <li>Large brass lamps and deepam stands — Deep base cabinet with full-extension drawer runners</li>
  <li>Additional framed photographs for festival use — Flat storage behind daily items</li>
  <li>Festival flowers, garlands, banana leaf — Short-term tray storage only; not permanent</li>
  <li>Brass and silver vessels — Closed cabinet with soft lining to prevent tarnishing</li>
  <li>Additional prasad items — Closed airtight containers in base storage only</li>
</ul>
<h2>Ventilation Planning</h2>
<p>Ventilation is the most overlooked functional requirement in Pooja room planning — and the one that creates the most significant long-term problems. Incense smoke, camphor fumes, and lamp combustion all produce particulates and volatile compounds that discolour surfaces, stain idols, and create air quality issues over time in a poorly ventilated space.</p>
<p>Natural Cross-Ventilation</p>
<p>The most effective solution. If the dedicated Pooja room is located in the northeast, a window to the east allows both natural light and air movement. Always specify an operable window, not a fixed pane.</p>
<p>Exhaust Fan</p>
<p>For enclosed rooms or units without natural ventilation. A 150–200mm exhaust fan at high level (near ceiling) draws smoke and fumes out effectively. Run during and for 10–15 minutes after active worship.</p>
<p>Jaali / Perforated Doors</p>
<p>For units within larger rooms, jaali doors provide passive ventilation even when closed. Incense smoke can dissipate into the room rather than concentrating within the unit.</p>
<p>Door Threshold Gap</p>
<p>For fitted units within an open-plan space, a 10–15mm clearance gap at the base of the unit door allows passive air circulation without requiring the door to be open during worship.</p>
<div class="callout callout--warn"><span class="callout__title">⚠ Ventilation Warning</span>An enclosed Pooja unit or room with no ventilation provision and regular incense and lamp use will accumulate soot on idols, ceilings, and walls within 6–12 months. This damage is difficult and expensive to reverse. Plan ventilation before installation — retrofitting is significantly more disruptive.</div>
<h2>Fire Safety Guide</h2>
<p>Fire safety in the Pooja room is rarely covered in design guides — but it is critically important. Open flame lamps, camphor burning, and incense create a genuine fire risk when surfaces, clearances, and material choices have not been planned carefully. These guidelines are non-negotiable.</p>
<ul>
  <li><strong>300mm minimum clearance</strong> above any open flame to any overhead surface, shelf, or element. This is a hard minimum — increase to 500mm wherever possible.</li>
  <li><strong>Fire-safe lamp platform</strong> — The lamp must sit on granite, marble, or stone. Never on wood, laminate, MDF, or any combustible surface.</li>
  <li><strong>Diya containment</strong> — Use a metal diya plate or stone tray beneath oil lamps to contain oil spillage. A diya knocked over onto a wooden surface is the most common fire cause.</li>
  <li><strong>Camphor burning zone</strong> — Camphor burns at high temperature. Always burn on a metal or stone dish, never directly on a shelf surface.</li>
  <li><strong>Electrical safety</strong> — Any electrical lighting within 600mm of an open flame must be rated for heat exposure. Avoid plastic fittings near lamp positions.</li>
  <li><strong>Agarbatti placement</strong> — Incense sticks in holders must be upright and in a non-tipping holder. Falling incense on a laminate or fabric surface is a common ignition source.</li>
  <li><strong>Fire extinguisher access</strong> — In a dedicated Pooja room, a small dry powder extinguisher should be accessible within 10 metres — typically in the adjacent corridor or kitchen.</li>
  <li><strong>No synthetic fabrics near flames</strong> — Festival draping, curtains, and decorative cloths near the lamp zone must be natural fibres (cotton, silk) only. Synthetic fabrics ignite rapidly.</li>
</ul>
<div class="callout callout--warn"><span class="callout__title">⚠ Fire Safety Note</span>Most house fires associated with Pooja rooms occur at night when lamps are left unattended after evening prayers. Always ensure all flames are confirmed extinguished before sleeping. Never leave a burning lamp in an enclosed unit with the doors closed.</div>
