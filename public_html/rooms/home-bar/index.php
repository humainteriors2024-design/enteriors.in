<h2>Materials and finishes</h2>
<ul>
  <li><strong>Carcass:</strong> BWR plywood; spills happen.</li>
  <li><strong>Counter:</strong> quartz or granite, which shrug off spills and rings. See the <a href="/modular-kitchen/countertop-guide/">countertop guide</a>.</li>
  <li><strong>Back panel:</strong> tinted mirror or lacquered glass to multiply light.</li>
  <li><strong>Shutters:</strong> veneer or PU in a dark tone, fluted glass for display.</li>
  <li><strong>Hardware:</strong> a lock on the main shutter, soft-close hinges, a stemware rail.</li>
</ul>

<h2>Lighting</h2>
<p>Back-light the glass shelves with warm LED strips, add a small pendant or spot over the counter, and keep everything on a dimmer. Light from behind and below makes glassware glow without glare.</p>

<h2>Services</h2>
<ul>
  <li>A dedicated socket for an under-counter fridge or ice-maker, with ventilation behind it.</li>
  <li>A small bar sink only if the counter is near a plumbing wall; otherwise use the kitchen.</li>
</ul>

