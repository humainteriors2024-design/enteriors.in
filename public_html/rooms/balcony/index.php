<h2>Flooring</h2>
<ul>
  <li><strong>Deck tiles (WPC or composite):</strong> click together over the existing floor; water drains beneath.</li>
  <li><strong>Artificial grass:</strong> soft and green; choose a drainable backing.</li>
  <li><strong>Anti-skid vitrified tile:</strong> the most durable if you are re-flooring.</li>
  <li><strong>Avoid:</strong> polished tile, untreated wood and indoor rugs.</li>
</ul>
<p>Keep the floor drain clear and sloped. Water standing against the balcony door is the commonest cause of damp skirting in the living room.</p>

<h2>Shade, rain and privacy</h2>
<ul>
  <li><strong>Outdoor roller blinds</strong> in PVC-coated or sunscreen fabric cut glare and rain.</li>
  <li><strong>Slatted screens</strong> in WPC or bamboo give privacy from neighbours.</li>
  <li><strong>Vertical planters</strong> make a green screen.</li>
  <li>Check society rules before fixing anything to the facade or railing.</li>
</ul>

<h2>Safety</h2>
<p>For homes with children or pets, fit invisible grilles (nylon-coated steel cables about 2–3 inches apart) or safety nets. Do not place furniture a child could climb near the railing.</p>

<h2>Furniture and plants</h2>
<ul>
  <li>Weather-proof materials: powder-coated metal, teak, HDPE wicker, WPC.</li>
  <li>A storage bench hides cushions, a hose and gardening tools.</li>
  <li>Hardy plants for Indian balconies: money plant, snake plant, areca palm, tulsi, curry leaf, hibiscus.</li>
  <li>Planters with saucers, raised on feet, so water does not stain the floor.</li>
</ul>

<h2>Lighting</h2>
<p>A weather-proof wall light (IP65), solar string lights or a lantern give a warm evening glow. Plan an outdoor-rated socket if you want a fan or a fountain.</p>

