<h2>15. Electrical Planning</h2>
<p>Electrical planning is the foundation that must be laid before any walls are plastered, any false ceiling is built, and any furniture is placed. Changes after execution are expensive, messy, and disruptive. Plan this in detail, upfront.</p>
<h3>Living Room Electrical Planning Checklist</h3>
<ul>
  <li>✅ <strong>TV Wall:</strong> 1× TV power point (at TV mounting height), 1× set-top box socket, 1× broadband/LAN port, 1× HDMI conduit pipe in wall</li>
  <li>✅ <strong>Sofa area:</strong> 2× sockets on side wall or behind sofa for phone charging and floor lamp</li>
  <li>✅ <strong>AC unit:</strong> Dedicated 16A power point; separate MCB in DB</li>
  <li>✅ <strong>Lighting circuits:</strong> Separate circuits for ambient ceiling lights, cove lights, and accent lights (allows independent control)</li>
  <li>✅ <strong>Smart home prep:</strong> If considering automation, install conduit pipes now even if you don't install smart switches immediately</li>
  <li>✅ <strong>UPS point:</strong> If you have smart home devices or a router that needs uninterrupted power</li>
  <li>✅ <strong>Switch locations:</strong> Main light switch near entry; dimmer switch accessible from sofa position</li>
  <li>✅ <strong>Concealed wiring:</strong> All wires run through PVC conduit inside walls — never surface run in a living room</li>
</ul>
<h2>16. Window &amp; Curtain Planning</h2>
<p>Curtains do far more than block light — they frame the room, add softness to hard architectural surfaces, and control privacy, acoustics, and thermal comfort. A room without curtains almost always looks unfinished.</p>
<h3>Curtain Types</h3>
<ul>
  <li><strong>Sheer Curtains:</strong> Light, ethereal, allows diffused natural light. Always pair with a heavier layer for privacy and light control.</li>
  <li><strong>Blackout Curtains:</strong> Complete light block. Essential for entertainment rooms; also great for west-facing rooms that get harsh afternoon sun.</li>
  <li><strong>Layered Curtains (Sheer + Blackout):</strong> The most versatile setup. Full flexibility from full light to complete darkness.</li>
  <li><strong>Roller Blinds:</strong> Clean, minimal, and space-efficient. Perfect for modern rooms or windows where you don't want to lose wall space.</li>
  <li><strong>Roman Blinds:</strong> Fabric that folds neatly upward. Elegant and space-efficient; popular in Scandinavian and Japandi styles.</li>
  <li><strong>Zebra Blinds (Dual Shade):</strong> The most popular modern choice — alternating sheer and solid bands allow precise light control.</li>
</ul>
<h3>Fabric Guide</h3>
<ul>
  <li><strong>Linen:</strong> Breathable, textured, beautifully natural. Premium look; wrinkles easily but that's part of its charm.</li>
  <li><strong>Polyester:</strong> Affordable, wrinkle-resistant, colourfast. The practical choice for daily-use curtains.</li>
  <li><strong>Cotton Blends:</strong> The best of both — the natural look of cotton with the durability of polyester. Recommended for most homes.</li>
</ul>
<p><strong>⚠️ Common Curtain Mistake:</strong> Hanging curtains at window-frame height makes the ceiling look low. Always hang curtain rods 15–20 cm above the window frame, or as close to the ceiling as possible. This simple trick makes every room feel taller and more luxurious.</p>
