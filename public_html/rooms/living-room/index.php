<h3>Proven Colour Schemes for Indian Living Rooms</h3>
<ul>
  <li><strong>Beige + Natural Wood:</strong> The safest and most timeless combination. Works across all styles. Easy to update with cushions and accessories.</li>
  <li><strong>White + Warm Grey:</strong> Modern and clean. Requires good maintenance but always feels fresh and expensive.</li>
  <li><strong>Earthy Palette (terracotta, ochre, olive):</strong> Trending strongly in 2024–25. Feels rooted, warm, and uniquely Indian.</li>
  <li><strong>Pastels (dusty rose, muted sage, powder blue):</strong> Gentle and romantic. Works best in rooms with ample natural light.</li>
  <li><strong>Dark Feature Wall + Light Surrounds:</strong> One dark wall (charcoal, forest green, navy) with three light walls creates sophisticated drama without overwhelming the space.</li>
</ul>
<h3>Choosing Colour Based on Your Room's Conditions</h3>
<ul>
  <li><strong>Small room:</strong> Light, cool, or neutral walls + mirrors to expand perceived space</li>
  <li><strong>Low ceiling:</strong> Vertical stripes or a ceiling 1–2 shades lighter than walls to draw the eye upward</li>
  <li><strong>Dark room (low natural light):</strong> Warm whites (not stark white) and warm lighting to compensate</li>
  <li><strong>Large room:</strong> Can handle deeper, bolder colours without feeling oppressive</li>
</ul>
