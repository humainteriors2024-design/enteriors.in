<h2>How to choose</h2>
<ol>
  <li><strong>Start with care.</strong> If you mop wet daily, choose tile, marble or SPC, not laminate or engineered wood.</li>
  <li><strong>Think about who walks on it.</strong> Elders and small children need matte, slip-resistant finishes.</li>
  <li><strong>Size to the room.</strong> Large-format tiles make a room look bigger; small tiles in a big room look busy.</li>
  <li><strong>Match the rest of the home.</strong> Use one floor through living and dining so the hall reads as one space.</li>
  <li><strong>Check the base.</strong> Large tiles and planks need a level floor; budget for levelling if not.</li>
</ol>
