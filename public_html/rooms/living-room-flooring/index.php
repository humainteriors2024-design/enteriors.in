<h2>Tile finishes</h2>
<ul>
  <li><strong>Matte:</strong> safest and hides footprints; looks modern.</li>
  <li><strong>Satin or carving finish:</strong> slight sheen, still grippy.</li>
  <li><strong>High gloss:</strong> reflects light but shows every mark and gets slippery when wet.</li>
</ul>

<h2>Rugs</h2>
<p>A rug under the sofa and coffee table defines the seating area, softens sound and protects the floor. Size it so at least the front legs of every seat sit on it: about 5×8 ft for a 2 BHK living room, 8×10 ft for a larger one. Flat-weave and wool-blend rugs are easiest to clean.</p>

<h2>In new flats</h2>
<p>Builders usually lay 2×2 ft vitrified tile. If it is undamaged and you can live with the colour, keep it: spend on a good rug and furniture instead. If you want a change without demolition, SPC plank laid over the tiles is quick and clean. More ideas for the room are in the <a href="/rooms/living-room/">living room guide</a> and, for flats in South-East Bengaluru, our <a href="/rooms/living-room-electronic-city/">Electronic City living room guide</a>.</p>
