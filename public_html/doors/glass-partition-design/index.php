<h2>Terms explained</h2>
<dl class="terms">
  <dt>Toughened (tempered) glass</dt><dd>Glass heat-treated to be several times stronger than ordinary glass; breaks into small, blunt pieces.</dd>
  <dt>Laminated glass</dt><dd>Two or more sheets bonded with a plastic interlayer that holds the pieces together if broken.</dd>
  <dt>Fluted (reeded) glass</dt><dd>Glass with parallel rounded grooves that blur the view while passing light.</dd>
  <dt>Acid-etched glass</dt><dd>Glass made permanently matt and translucent by acid treatment.</dd>
  <dt>Patch fitting</dt><dd>A metal clamp that holds frameless glass panels or doors at their corners.</dd>
  <dt>Mullion</dt><dd>A vertical or horizontal bar dividing a framed glass partition into panels.</dd>
</dl>
