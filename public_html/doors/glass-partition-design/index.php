<h2>How a partition is installed</h2>
<ol>
  <li><strong>Survey:</strong> measure floor-to-ceiling heights at several points; slabs and floors are rarely perfectly level.</li>
  <li><strong>Drawings:</strong> the fabricator draws panel sizes, door swing and fixing details for approval.</li>
  <li><strong>Glass ordered:</strong> toughened glass is cut, edged and drilled before toughening; this takes about one to three weeks.</li>
  <li><strong>Channels fixed:</strong> floor and ceiling channels anchored into concrete; a hidden timber or steel member is added where the ceiling is gypsum.</li>
  <li><strong>Panels set</strong> with packers and gaskets, then doors hung and adjusted.</li>
  <li><strong>Sealing and cleaning:</strong> silicone or gaskets at walls, manifestation applied, glass cleaned.</li>
</ol>
<p>Plan partitions after flooring and before final painting. Electrical switches should not fall where glass meets a wall.</p>

<h2>Before you decide</h2>
<ul>
  <li>What do you want to separate: sound, smell, view, or only space?</li>
  <li>Who uses the area: children, elderly family members, pets? Choose laminated glass and visible markings accordingly.</li>
  <li>Is the floor finished and the ceiling fixing solid?</li>
  <li>Do you need a door, and which way should it open or slide?</li>
  <li>Will the profile colour match handles, lights and other metalwork?</li>
</ul>
