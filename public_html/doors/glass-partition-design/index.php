  <li><strong>CNC jaali panels:</strong> pattern and airflow, traditional or modern.</li>
  <li><strong>Open shelving units:</strong> divide and store; see <a href="/furniture/">furniture design</a>.</li>
  <li><strong>Curtains on ceiling tracks:</strong> the cheapest, softest, fully reversible option.</li>
</ul>
