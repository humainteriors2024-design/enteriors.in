<h2>Cleaning and care</h2>
<ul>
  <li>Clean with a mild glass cleaner and a microfibre cloth; dry with a squeegee for streak-free glass.</li>
  <li>Use a soft brush along fluted glass grooves.</li>
  <li>Check door hinges, patch fittings and seals yearly.</li>
  <li>Never use abrasive pads or blades on coated or etched glass.</li>
</ul>

<h2>Alternatives to glass</h2>
<ul>
