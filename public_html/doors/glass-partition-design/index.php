<h2>Safety details</h2>
<ul>
  <li><strong>Safety glass only.</strong> Toughened or laminated; ordinary float glass breaks into sharp shards.</li>
  <li><strong>Manifestation:</strong> frosted dots, a band or a logo at 850–1000 mm and 1400–1600 mm height on clear glass, so nobody walks into it.</li>
  <li><strong>Polished edges</strong> on exposed glass, and rubber bumpers where doors meet glass.</li>
  <li><strong>Solid fixing</strong> into concrete or steel, not only into gypsum ceilings.</li>
</ul>

