<h2>Framed or frameless</h2>
<ul>
  <li><strong>Framed (aluminium or steel profiles):</strong> slim 20–40 mm profiles in black, bronze or champagne; can use thinner glass; the "industrial" grid look. Easier to fit in typical apartments.</li>
  <li><strong>Frameless:</strong> 12 mm toughened glass held in floor and ceiling channels or with patch fittings; minimal look; needs level floors and a strong ceiling fixing.</li>
  <li><strong>Half-height:</strong> a solid base (cabinet or wall) with glass above; useful behind sofas and in kitchens.</li>
</ul>

