<h2>Digital locks: what to check</h2>
<ul>
  <li><strong>Mechanical override:</strong> a physical key for flat batteries or electronic faults.</li>
  <li><strong>Lock body:</strong> a mortise or multi-point body, not just an electronic latch.</li>
  <li><strong>Door thickness range:</strong> confirm it fits your shutter (often 40–80 mm).</li>
  <li><strong>Access methods:</strong> PIN, fingerprint, card, app; choose what the family will actually use.</li>
  <li><strong>Emergency power:</strong> an external terminal (often USB-C or 9 V) to power the lock if batteries die.</li>
  <li><strong>Privacy and data:</strong> for app-connected locks, check where access logs are stored.</li>
  <li><strong>Installation:</strong> by the brand's trained installer; poor cutting weakens the door.</li>
</ul>

