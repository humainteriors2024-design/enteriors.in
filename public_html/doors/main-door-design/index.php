<h2>Design details that make a difference</h2>
<ul>
  <li><strong>Full-height pull handle</strong> (1200–1800 mm) in brass, bronze or black: a strong modern statement.</li>
  <li><strong>Matching cladding:</strong> extending the door veneer onto the wall around it makes a flat entrance feel grand.</li>
  <li><strong>Name plate and lighting:</strong> a warm wall light or downlight at the entrance for safety and welcome.</li>
  <li><strong>Threshold:</strong> a granite or marble sill protects the floor and marks the entrance.</li>
  <li><strong>Toran and rangoli space:</strong> leave a clear wall above and floor in front for festive decoration.</li>
</ul>
