<h2>Common mistakes</h2>
<ul>
  <li>Thin (30–32 mm) shutters on heavy main doors; they warp and the lock loosens.</li>
  <li>Unsealed top and bottom edges: moisture enters where nobody sees.</li>
  <li>A good lock in a weak frame.</li>
  <li>Digital locks with no mechanical override.</li>
  <li>Ignoring society or fire rules for the corridor face.</li>
</ul>

<h2>Before you decide</h2>
<ul>
  <li>What is the clear opening, and can it be made taller?</li>
  <li>Does the door face weather (villa) or a corridor (flat)?</li>
  <li>Do building or fire rules apply to the corridor face?</li>
  <li>Which lock will the family actually use daily, and is there a mechanical backup?</li>
  <li>Are frame, hinges, lock and finish all written into one quote?</li>
</ul>
