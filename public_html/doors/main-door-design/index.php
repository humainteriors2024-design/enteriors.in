<h2>Terms explained</h2>
<dl class="terms">
  <dt>Engineered solid-core door</dt><dd>A door with a laminated timber or LVL core and hardwood or veneer faces; more stable than solid timber.</dd>
  <dt>Multi-point lock</dt><dd>A lock that throws bolts at several points along the door edge with one key turn.</dd>
  <dt>Deadbolt</dt><dd>A bolt that cannot be pushed back without the key or thumb-turn, unlike a spring latch.</dd>
  <dt>Safety door</dt><dd>A second outer door, usually a steel grille or mesh, fitted outside the main door.</dd>
  <dt>Six-face sealing</dt><dd>Finishing both faces and all four edges of a door so it absorbs moisture evenly and stays straight.</dd>
</dl>
