<h2>Size and proportion</h2>
<ul>
  <li><strong>Flats:</strong> usually about 1000–1050 mm wide by 2100 mm high; a 2400 mm tall door looks noticeably more generous if the lintel allows.</li>
  <li><strong>Villas and independent houses:</strong> 1200 mm single doors, or double doors 1500–1800 mm wide, often with a fixed side panel.</li>
  <li><strong>Thickness:</strong> 35 mm minimum, 40–45 mm for tall or double doors.</li>
</ul>

<h2>Security: lock, hinges and frame</h2>
<ul>
  <li><strong>Lock:</strong> a mortise lock with a deadbolt, or a multi-point lock that throws bolts at several heights. Digital locks should have a mechanical override and a multi-point body.</li>
  <li><strong>Hinges:</strong> four heavy-duty stainless steel ball-bearing hinges for doors over about 40 kg; consider security (dog) bolts on the hinge side.</li>
  <li><strong>Frame:</strong> seasoned hardwood or steel, anchored into the wall; a weak frame is the easiest point to force.</li>
  <li><strong>Extras:</strong> a door viewer or video doorbell, a door closer, and a safety chain.</li>
</ul>

<h2>Weather and warping</h2>
<p>Doors warp when one face absorbs moisture faster than the other. Seal all six faces (including the top and bottom edges) before hanging, leave even gaps of 2–3 mm, and protect exposed doors with a canopy or recess. For villa entrances facing west or south, choose engineered or steel-wood construction, or a teak door with a UV-resistant exterior finish, and re-coat it every few years.</p>

<h2>Style options</h2>
<ul>
  <li><strong>Modern:</strong> flush veneer with vertical grooves, a full-height pull handle, concealed hinges.</li>
  <li><strong>Contemporary Indian:</strong> teak with brass inlay lines or a carved central panel.</li>
  <li><strong>Traditional:</strong> carved teak with brass studs, sometimes with a kalash or floral motif.</li>
  <li><strong>Double doors:</strong> for villas and wide openings; consider one fixed leaf with bolts.</li>
</ul>

<h2>Safety doors for apartments</h2>
<p>A second door outside the main door, either a powder-coated steel grille or a mesh door, lets air in while the main door is open and adds a layer of security. Choose one with a proper lock rather than a padlock, and confirm the society allows it in the corridor.</p>

