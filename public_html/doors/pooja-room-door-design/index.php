<h2>Terms explained</h2>
<dl class="terms">
  <dt>Jaali</dt><dd>A perforated screen with a repeating pattern, traditionally carved in stone or wood, now often CNC-cut.</dd>
  <dt>CNC cutting</dt><dd>Computer-controlled routing that cuts precise patterns in board or wood.</dd>
  <dt>HDHMR</dt><dd>High-density, high-moisture-resistance board, dense enough to hold fine CNC patterns.</dd>
  <dt>Kalash</dt><dd>A sacred pot motif, often used as a finial or carved detail on pooja doors.</dd>
  <dt>Toughened glass</dt><dd>Heat-treated safety glass several times stronger than ordinary glass, breaking into small blunt pieces.</dd>
</dl>
