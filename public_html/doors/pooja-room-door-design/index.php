<h2>Sizes and proportions</h2>
<ul>
  <li><strong>Walk-in pooja room:</strong> double doors 900–1200 mm wide, about 2100 mm high; leaves open fully.</li>
  <li><strong>Wall unit:</strong> shutter height to suit the shrine, typically 600–900 mm for an upper cabinet, or full height for a floor unit.</li>
  <li><strong>Shrine shelf height:</strong> about 900–1100 mm from the floor if you pray standing; 300–600 mm if you sit on the floor.</li>
  <li><strong>Depth:</strong> 450–600 mm for a unit, enough for idols, lamps and a plate.</li>
</ul>
