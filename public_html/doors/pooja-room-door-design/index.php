<h2>Regional styles of pooja doors</h2>
<ul>
  <li><strong>South Indian:</strong> teak doors with carved temple motifs, brass bells and lamps, sometimes with a decorative brass or wood frame around the opening.</li>
  <li><strong>Gujarati and Rajasthani:</strong> intricate jaali and carved wood, often with mirror or colourful details.</li>
  <li><strong>Bengali and eastern:</strong> simpler wood with a central motif; shrine areas often open.</li>
  <li><strong>Modern minimal:</strong> fluted glass, slatted wood or a single CNC motif with warm lighting.</li>
</ul>
<p>Choose a style that matches the rest of the home: a carved temple door looks best when echoed in a few other traditional elements, while a minimal home suits a slatted or glass door with one meaningful motif.</p>

<h2>Before you decide</h2>
<ul>
  <li>Walk-in room or wall unit? It decides door size and swing.</li>
  <li>Do you light lamps and camphor daily? Plan ventilation and clearances.</li>
  <li>Do you want the deity visible when the doors are closed? Choose jaali or glass.</li>
  <li>Where will bells and handles be fixed so they do not strike glass?</li>
  <li>Is the finish heat- and oil-resistant near the lamp shelf?</li>
</ul>
