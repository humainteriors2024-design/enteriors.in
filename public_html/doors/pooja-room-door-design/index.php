<h2>Materials in detail</h2>
<ul>
  <li><strong>Teak:</strong> the traditional choice; stable, termite-resistant and carvable. Ask for well-seasoned wood.</li>
  <li><strong>HDHMR for CNC jaali:</strong> dense enough to hold fine cut patterns without crumbling; seal the cut edges with PU, as exposed fibre absorbs moisture and oil. See the <a href="/materials/hdhmr-board/">HDHMR guide</a>.</li>
  <li><strong>Glass:</strong> toughened or laminated, 5–8 mm in doors; etched, frosted or fluted for privacy. See <a href="/materials/glass-finish/">glass finishes</a>.</li>
  <li><strong>Brass:</strong> handles, bells, kalash finials and inlays; solid brass ages well, plated metal flakes.</li>
</ul>

<h2>Design details that matter</h2>
<ul>
  <li><strong>Double leaves</strong> open the full width of the shrine; a single leaf hides part of it.</li>
  <li><strong>Threshold:</strong> a raised wooden or stone step marks the space and stops floor water reaching the shrine.</li>
  <li><strong>Lighting inside:</strong> warm 2700 K LED strips or a small downlight behind the jaali make the pattern glow at night.</li>
  <li><strong>Ventilation:</strong> with glass doors, add a vent at the top or keep the upper panel in jaali.</li>
  <li><strong>Hardware:</strong> lift-off or pivot hinges for heavy carved doors; magnetic catches instead of latches for a clean face.</li>
</ul>

<h2>Safety with lamps and incense</h2>
<div class="callout callout--warn"><span class="callout__title">Keep flames away from the door</span>Place diyas and camphor on a metal or stone plate at least 300 mm from the door line and from any wood shelf above. Avoid fabric curtains behind jaali, and do not fit PVC or acrylic sheet panels near flames.</div>

<h2>Pooja units without a separate room</h2>
<p>In compact apartments the pooja space is often a wall unit or a niche in the living or dining room. Here the "door" is a pair of shutters on the unit, usually 600–1000 mm wide, in jaali, fluted glass or wood. Keep the unit at least 900 mm above the floor if you pray standing, or at sitting height if you sit. Costs for complete units are in <a href="/cost/pooja-room-cost/">pooja room cost</a>, and traditional placement guidance is in <a href="/vastu/pooja-room-vastu/">pooja room vastu</a>.</p>
