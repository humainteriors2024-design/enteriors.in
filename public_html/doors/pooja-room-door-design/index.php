<h2>Materials for the shrine around the door</h2>
<ul>
  <li><strong>Marble or Corian shelf</strong> for lamps: heat-resistant, easy to clean.</li>
  <li><strong>Back panel:</strong> CNC-cut motif with backlight, or veneer.</li>
  <li><strong>Drawers below:</strong> for incense, matches, oil and books; line with laminate.</li>
  <li><strong>Brass fittings:</strong> bells, kalash finials, handles; avoid plated metal near lamps.</li>
</ul>

<h2>Care and cleaning</h2>
<ul>
  <li>Wipe soot weekly from the shelf and the jaali above lamps.</li>
  <li>Polish brass with a non-abrasive brass cleaner; lacquered brass needs only a dry cloth.</li>
  <li>Keep the PU finish away from oil spills; wipe immediately.</li>
  <li>Check lamp positions after festivals, when extra diyas are often lit.</li>
</ul>
