<h2>Before you decide</h2>
<ul>
  <li>Which doors are near water? Specify BWP cores or WPC there.</li>
  <li>Which door needs security? Main door: thicker, solid, better lock and frame.</li>
  <li>Do you want carving or panels? Only solid or engineered hardwood does it well.</li>
  <li>How will the finish be maintained? Laminate is lowest maintenance; veneer and solid wood need occasional care.</li>
  <li>Is the core type, thickness and standard written into the quote?</li>
</ul>
<p>A sensible split for most apartments: solid-core flush doors with laminate or veneer for bedrooms, WPC for bathrooms, and an engineered or solid hardwood main door.</p>
