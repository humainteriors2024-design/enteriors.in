<h2>Face finishes for flush doors</h2>
<ul>
  <li><strong>Laminate:</strong> toughest and cheapest to maintain; many wood and solid patterns.</li>
  <li><strong>Veneer with PU or melamine polish:</strong> real wood look; needs care at edges.</li>
  <li><strong>Membrane or paint:</strong> for routed designs; check heat and moisture resistance.</li>
</ul>
<p>Finish options are compared in the <a href="/compare/veneer-vs-laminate/">veneer vs laminate</a> guide and the <a href="/materials/pu-finish/">PU finish</a> guide.</p>

<h2>Buying checklist</h2>
<ul>
  <li>Ask for the core type in writing: solid timber, particle board or honeycomb.</li>
  <li>Prefer IS 2202-marked solid-core shutters; BWP grade near water.</li>
  <li>Check the shutter thickness (30–35 mm internal, 35–45 mm main) and weight; a very light "solid" door is not solid.</li>
  <li>Hardwood lipping on all four edges, and all six faces sealed.</li>
  <li>For solid wood, ask for the species, moisture content after seasoning and the joinery method.</li>
</ul>
