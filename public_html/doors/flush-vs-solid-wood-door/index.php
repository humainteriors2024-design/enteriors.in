<p>"Wooden door" in Indian quotations can mean three very different things: a solid hardwood door, a solid-core flush door with a wood veneer face, or a hollow-core door painted to look like wood. They differ in strength, stability and price by a factor of ten. This comparison, part of the <a href="/doors/">doors guide</a>, explains what is inside each.</p>

<h2>How each door is built</h2>
<h3>Flush door</h3>
<ul>
  <li><strong>Core:</strong> solid timber battens or blocks glued edge to edge (solid core); or particle board; or a frame with a paper honeycomb (hollow core).</li>
  <li><strong>Stiles and rails:</strong> a hardwood frame around the core holds hinges and locks.</li>
  <li><strong>Faces:</strong> plywood cross-bands both sides, then veneer, laminate or paint.</li>
  <li><strong>Lipping:</strong> solid wood strips on the edges hide the core and protect it.</li>
</ul>
<h3>Solid wood door</h3>
<ul>
  <li>Stiles, rails and panels in hardwood (teak, sal, sheesham, mahogany), joined with mortise and tenon joints; or boards joined into a solid slab.</li>
  <li>Engineered "solid" doors use laminated timber cores with hardwood faces, more stable than a single solid slab.</li>
</ul>
