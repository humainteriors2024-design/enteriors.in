<h2>Terms explained</h2>
<dl class="terms">
  <dt>Flush door</dt><dd>A door with flat faces over a core, finished with veneer, laminate or paint.</dd>
  <dt>Frame-and-panel door</dt><dd>A door of stiles and rails with panels set into grooves, allowing the wood to move without cracking.</dd>
  <dt>Stile and rail</dt><dd>The vertical (stiles) and horizontal (rails) members of a door frame or shutter.</dd>
  <dt>Seasoning</dt><dd>Drying timber to a stable moisture content before use, to prevent warping and cracking.</dd>
  <dt>BWP</dt><dd>Boiling Water Proof: the highest water-resistance grade of glue and plywood.</dd>
</dl>
