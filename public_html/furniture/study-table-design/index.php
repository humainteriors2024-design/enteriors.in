<h2>Light and position</h2>
<ul>
  <li>Place the desk <strong>at right angles to the window</strong>: daylight from the side, no glare on screens.</li>
  <li>Add a <strong>task lamp of about 4000 K</strong> on the side opposite the writing hand.</li>
  <li>Keep <strong>general room light on</strong> while using a screen to reduce eye strain.</li>
  <li>Plan <strong>sockets above the desk</strong> (with USB) and a cable tray under it.</li>
</ul>

<h2>Storage</h2>
<ul>
  <li>An overhead shelf or cabinet with its bottom about 450–500 mm above the desk, so it does not hit your head.</li>
  <li>A drawer pedestal 400–450 mm wide on one side; keep the knee space clear.</li>
  <li>A pin-board or magnetic board at eye level for schedules.</li>
  <li>Closed storage for books in humid cities, to reduce dust and fungus.</li>
</ul>

