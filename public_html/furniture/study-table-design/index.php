<h2>Home office in a bedroom or living room</h2>
<ul>
  <li><strong>Video calls:</strong> face a plain wall or a bookshelf; light your face from the front or side, not from a window behind you.</li>
  <li><strong>Acoustics:</strong> a rug, curtains and a fabric or slatted panel behind the desk reduce echo.</li>
  <li><strong>Separation:</strong> a sliding door, glass partition or even a curtain marks work time from home time. See <a href="/doors/glass-partition-design/">glass partitions</a>.</li>
  <li><strong>Power and data:</strong> a LAN point near the desk is more reliable than Wi-Fi for calls.</li>
</ul>
