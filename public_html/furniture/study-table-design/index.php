<h2>Materials and finishes for study furniture</h2>
<ul>
  <li><strong>Desk top:</strong> laminate (tough, writeable, wipeable) or veneer with PU; avoid high gloss, which reflects light into the eyes.</li>
  <li><strong>Edges:</strong> rounded or PVC-edged at the front edge, comfortable for forearms.</li>
  <li><strong>Colour:</strong> mid-tone, matt desk tops reduce glare compared with white gloss.</li>
  <li><strong>Hardware:</strong> soft-close drawers; keyboard trays on full-extension channels if used.</li>
</ul>

<h2>Common mistakes</h2>
<ul>
  <li>Adult-height desks for small children, with no footrest.</li>
  <li>Desks facing a window, causing glare and squinting.</li>
  <li>Shelves too low over the desk, hitting heads.</li>
  <li>No sockets above the desk; extension cords on the floor.</li>
  <li>Desks under 500 mm deep for screen work.</li>
</ul>

<h2>A desk that grows with a child</h2>
<p>Children grow about 5–6 cm a year through primary school, so a fixed desk fits well for only a year or two. Options that last:</p>
<ul>
  <li><strong>Height-adjustable desk</strong> (manual crank or legs with set positions) covering roughly 520–760 mm.</li>
  <li><strong>Fixed adult-height desk + adjustable chair + footrest:</strong> the most common approach in built-in study walls.</li>
  <li><strong>Tilting desktop section</strong> for drawing and reading.</li>
  <li><strong>Modular shelves</strong> that move up as the child grows.</li>
</ul>
<p>Review the set-up at the start of each school year: chair height, footrest, screen height and lighting.</p>
