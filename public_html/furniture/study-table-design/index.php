<h2>Posture check: is the desk right?</h2>
<ol>
  <li>Feet flat on the floor (or a footrest), knees at about 90 degrees.</li>
  <li>Thighs level, with a little space between the seat front and the back of the knees.</li>
  <li>Elbows close to the body, forearms level with the desk.</li>
  <li>Shoulders relaxed, not raised.</li>
  <li>Eyes level with the top of the screen; screen at arm's length.</li>
  <li>Lower back supported by the chair.</li>
</ol>
<p>If the desk is too high, raise the chair and add a footrest. If it is too low, raise the desk or monitor. A laptop used for long hours needs a stand plus a separate keyboard and mouse.</p>
