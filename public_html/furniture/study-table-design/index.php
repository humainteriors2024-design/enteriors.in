<h2>Before you decide</h2>
<ul>
  <li>Who will use the desk, for what, and for how many hours a day?</li>
  <li>Laptop only, or one or two monitors? It sets the depth.</li>
  <li>Where does the daylight come from, and which hand writes?</li>
  <li>Are sockets, USB and LAN where the desk will be?</li>
  <li>Is the chair adjustable, and is there a footrest for children?</li>
</ul>

