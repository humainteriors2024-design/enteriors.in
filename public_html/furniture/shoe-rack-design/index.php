<h2>Common mistakes</h2>
<ul>
  <li>Cabinets that are too shallow for flat shelves, so shoes stick out and doors will not close.</li>
  <li>Sealed cabinets with no ventilation.</li>
  <li>Unsealed board bases that swell from mopping water.</li>
  <li>No seat, so people balance on one leg to put shoes on.</li>
  <li>Planning for today's shoes only; children's feet grow.</li>
</ul>

<h2>Ventilation and odour, in more detail</h2>
<p>Shoe odour comes from bacteria feeding on sweat in warm, damp conditions, which is why monsoon months are the worst. A cabinet design helps in three ways:</p>
<ol>
  <li><strong>Airflow:</strong> openings at the bottom and top of the cabinet let air move by convection. A 20–30 mm gap at the back, slotted shelves and louvred doors are enough in most homes.</li>
  <li><strong>Drying:</strong> wet shoes should dry outside the cabinet or on a ventilated lower shelf before going in.</li>
  <li><strong>Cleanable surfaces:</strong> laminate interiors and removable shelf mats can be washed; bare board absorbs odour.</li>
</ol>
<p>Activated charcoal or silica sachets reduce moisture and smell in closed cabinets; replace or recharge them every few months.</p>

