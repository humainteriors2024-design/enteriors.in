<h2>Ventilation and hygiene</h2>
<ul>
  <li>Louvred, slotted, cane or perforated shutters; or a 20–30 mm gap at the back and top.</li>
  <li>Wire, slatted or perforated shelves let air move and let sand fall through.</li>
  <li>Laminate inside the cabinet, not bare board, so it can be wiped.</li>
  <li>Keep a drip tray or a ventilated lower shelf for wet monsoon shoes.</li>
</ul>

<h2>Materials</h2>
<p>Use BWR plywood or HDHMR with laminate; avoid unsealed MDF and particle board, which swell when wet shoes and mopping water reach them. Metal shelves and perforated steel work well in utility areas. See the <a href="/materials/">materials guide</a> for board grades.</p>

