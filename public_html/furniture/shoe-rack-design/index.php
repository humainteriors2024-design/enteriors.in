<h2>Shoe storage and tradition</h2>
<p>Many Indian families keep shoes out of the main living areas and away from the pooja room and kitchen, which is one reason the entrance shoe cabinet is so important. Traditional guidance also discusses where shoes are kept relative to the main door; see <a href="/vastu/main-door-vastu/">main door vastu</a>. Practically, a closed, ventilated cabinet just inside the door keeps dust and odour out of the home and the corridor clear.</p>
