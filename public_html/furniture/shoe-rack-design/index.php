<p>Most Indian homes keep shoes at the entrance, which makes the shoe rack the first piece of furniture anyone sees. It also has a tough brief: a family's worth of shoes in a narrow space, without smell or clutter. Planning starts with a count, not a catalogue. This guide is part of the <a href="/furniture/">furniture design guide</a>.</p>

<h2>Step 1: count and size</h2>
<ol>
  <li>Count the pairs each person keeps at the entrance (not every pair they own).</li>
  <li>Add 20% for guests and growth.</li>
  <li>Allow about 2–3 adult pairs per foot of flat shelf, fewer for sports shoes and boots.</li>
</ol>
<div class="callout"><span class="callout__title">Example</span>A family of four with 6 pairs each at the door: 24 pairs + 20% ≈ 29 pairs. At about 2.5 pairs per foot, that is 11–12 ft of shelf: a 3 ft wide cabinet with four shelves.</div>

