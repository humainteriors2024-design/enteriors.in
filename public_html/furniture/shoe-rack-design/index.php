  <li><strong>Under the stairs</strong> in duplexes: pull-out drawers.</li>
  <li><strong>Inside a wardrobe:</strong> pull-out shoe racks for formal and occasion shoes.</li>
  <li><strong>Wall-mounted floating cabinet:</strong> leaves the floor clear for mopping and a bench underneath.</li>
  <li><strong>Utility or balcony:</strong> open racks for sports shoes and gardening footwear.</li>
</ul>
