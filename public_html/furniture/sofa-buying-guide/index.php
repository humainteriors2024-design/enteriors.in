<h2>Sofa types</h2>
<ul>
  <li><strong>Three-seater + two chairs:</strong> flexible, works in most rooms.</li>
  <li><strong>L-shaped / sectional:</strong> seats more in a corner; check that the chaise suits the room orientation.</li>
