<p>A sofa is the piece of furniture used most hours of the day, and the one whose quality is hardest to judge in a showroom: two sofas can look identical and feel the same for the first month, then age completely differently. The difference is in the frame, the suspension, the foam and the fabric. This guide, part of the <a href="/furniture/">furniture design guide</a>, explains each.</p>

