<h2>Upholstery: fabric and leather</h2>
<ul>
  <li><strong>Performance fabrics</strong> (polyester, olefin, blends): stain-resistant, colourfast; check a rub count of 25,000+ for family use.</li>
  <li><strong>Cotton and linen:</strong> breathable and soft; crease and stain more; use removable covers.</li>
  <li><strong>Velvet:</strong> rich and durable when made of polyester; shows pressure marks.</li>
  <li><strong>Bouclé:</strong> textured and fashionable; loops can snag with pets. See <a href="/trends/boucle-fabrics/">bouclé and textured fabrics</a>.</li>
  <li><strong>Leather:</strong> full-grain and top-grain last and patinate; corrected-grain is cheaper; bonded leather and PU peel within a few years.</li>
</ul>
<p>In humid cities, choose fabrics with good colourfastness and a removable, washable cover; keep sofas out of direct afternoon sun to avoid fading.</p>

