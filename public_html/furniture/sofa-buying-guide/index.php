<h2>Foam explained</h2>
<p>Foam is where most budget sofas cut corners, and the difference shows within a year or two. Two numbers matter:</p>
<ul>
  <li><strong>Density (kg/m³):</strong> how much material is in the foam. Higher density means more durable. Seat cushions of about 32–40 kg/m³ hold shape for years; under about 28 kg/m³ they flatten quickly.</li>
  <li><strong>Firmness (hardness):</strong> how soft it feels. Firmness is separate from density: a high-density foam can be soft or firm.</li>
</ul>
<p>High-resilience (HR) foam springs back quickly and feels lively; memory foam moulds slowly to the body but can feel warm in Indian summers. Many good cushions combine a firm HR core with a softer top layer and a polyester fibre wrap.</p>
