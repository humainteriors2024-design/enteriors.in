<h2>Terms explained</h2>
<dl class="terms">
  <dt>Kiln-dried hardwood</dt><dd>Hardwood dried in a kiln to a stable moisture content, so frames do not warp or loosen.</dd>
  <dt>Sinuous spring (S-spring)</dt><dd>A zig-zag steel spring running front to back under the seat.</dd>
  <dt>Pocket spring</dt><dd>Individual coil springs in fabric pockets, each moving independently.</dd>
  <dt>HR foam</dt><dd>High-resilience polyurethane foam that recovers quickly and lasts longer than standard foam.</dd>
  <dt>Martindale rub count</dt><dd>The number of abrasion cycles a fabric survives in the ISO 12947 test before visible wear.</dd>
  <dt>Top-grain leather</dt><dd>The outer layer of the hide, sanded and finished; durable and more uniform than full-grain.</dd>
  <dt>Bonded leather</dt><dd>Leather scraps bonded to a backing and coated; it peels and cracks within a few years.</dd>
</dl>
