<h2>Showroom checklist</h2>
<ol>
  <li>Sit for five minutes in your usual position, including leaning back.</li>
  <li>Lift one front corner about 100 mm: if the other front leg does not lift soon after, the frame is twisting.</li>
  <li>Press the seat: it should spring back evenly with no hard edges or hollows.</li>
  <li>Ask for the frame wood, foam density, spring type and fabric rub count in writing.</li>
  <li>Check the warranty separately for frame, springs and foam.</li>
</ol>
