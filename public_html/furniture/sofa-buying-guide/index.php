<h2>Care through the Indian year</h2>
<ul>
  <li><strong>Monsoon:</strong> keep sofas off damp external walls; air the room; watch for mildew on cotton and linen.</li>
  <li><strong>Summer sun:</strong> use sheers or blinds; strong afternoon sun fades fabrics and dries leather.</li>
  <li><strong>Dust:</strong> vacuum weekly with an upholstery brush; rotate and flip cushions monthly.</li>
  <li><strong>Stains:</strong> blot (do not rub) spills immediately; follow the fabric's cleaning code.</li>
  <li><strong>Leather:</strong> condition every 6–12 months; keep away from AC vents and heaters.</li>
</ul>

<h2>Custom-made vs ready-made</h2>
<p>Local workshops in Indian cities can build sofas to exact sizes and fabrics, often at good value. The risk is invisible quality: ask to see an unfinished frame, specify foam density and spring type in writing, and choose the fabric yourself from a supplier that lists rub counts. Ready-made brands show the finished product and often give longer warranties, but sizes are fixed.</p>
