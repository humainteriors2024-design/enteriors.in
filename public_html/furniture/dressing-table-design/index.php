<h2>Dressing tables for different users</h2>
<ul>
  <li><strong>Couples sharing:</strong> a wider counter (1200–1500 mm) with two mirror zones and separate drawers.</li>
  <li><strong>Elderly family members:</strong> a seated counter with a stable chair with arms, a slightly higher seat (about 480 mm) and bright, glare-free light.</li>
  <li><strong>Teenagers:</strong> a compact counter that doubles as a study desk, with a flip-up mirror.</li>
  <li><strong>Men's grooming:</strong> often a standing counter near the wardrobe with a socket for trimmers and a closed cabinet for products.</li>
</ul>

<h2>Before you decide</h2>
<ul>
  <li>Seated or standing, and who will use it?</li>
  <li>Where is the daylight, and where will face-level lights go?</li>
  <li>Is there a socket within reach, and is the counter heat-resistant?</li>
  <li>Will the stool slide fully under the counter?</li>
  <li>Does the dressing area work with the wardrobe and full-length mirror?</li>
</ul>
