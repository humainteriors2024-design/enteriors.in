<h2>Organising cosmetics and jewellery</h2>
<ul>
  <li><strong>Top drawer:</strong> daily make-up in shallow trays, brushes upright in cups.</li>
  <li><strong>Jewellery:</strong> velvet-lined trays with ring rolls and earring slots; a lockable drawer or a small safe in the wardrobe for valuables.</li>
  <li><strong>Hair tools:</strong> a deeper drawer with a heat-resistant liner and a socket nearby.</li>
  <li><strong>Perfumes:</strong> away from sunlight and heat, in a closed cabinet.</li>
  <li><strong>Humidity:</strong> silver jewellery tarnishes faster in humid cities; use anti-tarnish strips.</li>
</ul>
