<h2>Lighting that shows true colour</h2>
<ul>
  <li><strong>Position:</strong> light from the front (around the mirror) or both sides at face height. Overhead light alone casts shadows.</li>
  <li><strong>Colour temperature:</strong> 3000–4000 K. Very warm light hides redness; cool light makes skin look grey.</li>
  <li><strong>CRI 90 or more:</strong> make-up and clothing colours look as they will outdoors.</li>
  <li><strong>Backlit mirrors</strong> add a soft glow but should be combined with front light for make-up.</li>
  <li><strong>Daylight:</strong> place the table at right angles to a window when possible.</li>
</ul>
<p>More on colour temperature and CRI in <a href="/planning/lighting-design/">lighting design</a>.</p>

<h2>Storage</h2>
<ul>
  <li><strong>Shallow top drawers (60–80 mm)</strong> with dividers for jewellery, cosmetics and brushes.</li>
  <li><strong>A lockable jewellery drawer</strong> with a velvet insert.</li>
  <li><strong>Deeper lower drawers</strong> for hair dryers and bottles, with a socket inside or beside the unit.</li>
  <li><strong>Open shelves</strong> only for items you use daily; the rest collects dust.</li>
  <li><strong>Heat:</strong> keep hot styling tools on a heat-resistant surface; laminate tops handle this better than painted finishes.</li>
</ul>

