<h2>Common mistakes</h2>
<ul>
  <li>Light only from the ceiling, casting shadows under the eyes.</li>
  <li>Cool white (6500 K) or low-CRI lights that make skin look grey.</li>
  <li>No socket nearby, so hair dryer cables cross the room.</li>
  <li>Deep drawers that become jumbled; shallow drawers with dividers work better.</li>
  <li>A stool that does not slide under the counter, blocking the walkway.</li>
</ul>

