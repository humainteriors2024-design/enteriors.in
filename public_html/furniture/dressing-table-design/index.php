<h2>Dressing areas in larger homes</h2>
<p>In villas and larger apartments, a dressing area between the bedroom and bathroom combines wardrobes, a dressing table and a full-length mirror. Plan it as a passage of at least 1200 mm clear width with storage on one or both sides, good front lighting at the mirror, and a door or glass partition to the bedroom. See the <a href="/wardrobe/">wardrobe guide</a> and <a href="/doors/glass-partition-design/">glass partitions</a>.</p>
