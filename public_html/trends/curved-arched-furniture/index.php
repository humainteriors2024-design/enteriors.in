<h2>Building curves well</h2>
<ul>
  <li>Curved carcasses use bending plywood or kerfed boards on formers.</li>
  <li>Use flexible laminates, veneer or PU paint; standard laminate cracks on tight radii.</li>
  <li>Keep radii generous (300 mm or more) for easier fabrication and cleaning.</li>
  <li>Expect built-in curves to cost about 20–40% more than straight units.</li>
</ul>

<h2>Curves in Indian homes</h2>
<p>Arches are not new to India: temple doorways, jharokhas and colonial verandas all use them. An arched pooja niche or a curved jaali partition can feel traditional and current at once. See <a href="/styles/indo-colonial/">Indo-colonial interiors</a> and <a href="/rooms/pooja-room/">pooja room designs</a>.</p>

