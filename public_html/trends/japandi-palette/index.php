<h2>Materials</h2>
<ul>
  <li><strong>Shutters:</strong> matte oak or ash laminate, or veneer; off-white matte laminate.</li>
  <li><strong>Handles:</strong> slim charcoal or black profiles, or handle-less grooves.</li>
  <li><strong>Walls:</strong> warm matte emulsion; limewash on one wall. See <a href="/trends/limewash-textures/">limewash</a>.</li>
  <li><strong>Fabrics:</strong> linen, cotton, wool in undyed or earthy tones.</li>
  <li><strong>Accessories:</strong> handmade ceramics, cane, paper lamps.</li>
</ul>

<h2>Room palettes</h2>
<ul>
  <li><strong>Living:</strong> off-white walls, oak TV unit, sand sofa, clay cushions, black floor lamp.</li>
  <li><strong>Bedroom:</strong> rice-white walls, low oak bed, linen bedding, sage throw.</li>
  <li><strong>Kitchen:</strong> off-white wall units, oak base units, charcoal quartz or dark granite top.</li>
</ul>

<h2>Will it last?</h2>
<p>Our view: yes. A calm, material-led palette ages well. Keep storage closed, because Japandi depends on clutter being out of sight. See also the <a href="/blogs/japandi-wabi-sabi-meets-scandinavian/">Japandi blog post</a> and <a href="/trends/warm-neutrals/">warm neutrals</a>.</p>
