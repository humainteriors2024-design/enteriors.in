<h2>Plants that cope indoors</h2>
<ul>
  <li><strong>Low light:</strong> snake plant, ZZ plant, pothos, peace lily.</li>
  <li><strong>Bright indirect light:</strong> areca palm, rubber plant, philodendron, fiddle-leaf fig.</li>
  <li><strong>Balcony sun:</strong> tulsi, curry leaf, hibiscus, jasmine, herbs.</li>
</ul>
<p>Use pots with saucers, raise them off wooden floors, and avoid overwatering in the monsoon.</p>

