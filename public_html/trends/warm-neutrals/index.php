<h2>Choosing for Indian light</h2>
<ol>
  <li><strong>Strong sun (south and west):</strong> warm colours look stronger; step towards greige.</li>
  <li><strong>Dim rooms (north-facing):</strong> creamier whites keep them from looking grey.</li>
  <li><strong>Warm white bulbs (3,000 K):</strong> push colours yellower at night; test under your own lights.</li>
  <li><strong>Test two samples</strong> on two walls; look morning, afternoon and night.</li>
</ol>

<h2>Room palettes</h2>
<ul>
  <li><strong>Living:</strong> warm white walls, a taupe feature wall, oak and cane, brass lamps.</li>
  <li><strong>Bedroom:</strong> cream walls, mushroom headboard wall, walnut, linen.</li>
  <li><strong>Kitchen:</strong> warm white wall units, oak or sand base units, a dark granite top. See <a href="/blogs/kitchen-colour-combinations/">kitchen colour combinations</a>.</li>
