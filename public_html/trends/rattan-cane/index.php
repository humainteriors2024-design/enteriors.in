<h2>Where to use it</h2>
<ul>
  <li><strong>Wardrobe and crockery shutters:</strong> cane inserts in wood frames; air flows through.</li>
  <li><strong>Headboards:</strong> a cane panel behind the bed.</li>
  <li><strong>Chairs and benches:</strong> cane seats and backs.</li>
  <li><strong>Lighting:</strong> cane pendants cast patterned light.</li>
  <li><strong>Avoid:</strong> bathrooms, the kitchen sink area and open balconies for natural cane.</li>
</ul>

<h2>Cost</h2>
<p>Cane webbing inserts in a wood frame cost about ₹500–1,200 per sq ft of shutter; synthetic cane is a little cheaper. A cane accent chair costs ₹6,000–25,000.</p>

