<h2>Hard water</h2>
<p>In areas with borewell or tanker water, such as much of South-East Bengaluru, white scale shows immediately on black taps. Wipe dry after use, fit a softener or filter, or choose brushed steel or gunmetal for taps and keep black for handles. Local kitchen advice is in our <a href="/modular-kitchen/electronic-city-chandapura/">kitchen guide for Electronic City and Chandapura</a>.</p>

<h2>Will it last?</h2>
<p>Our view: small doses. Black handles are cheap to change; black taps and shower systems are a bigger commitment. Keep one metal finish per room. Hardware basics: <a href="/modular-kitchen/hardware-guide/">kitchen hardware guide</a>.</p>
