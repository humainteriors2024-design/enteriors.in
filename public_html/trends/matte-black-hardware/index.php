<h2>Where black works best</h2>
<ul>
  <li><strong>Easy:</strong> cabinet handles and profiles, light fittings, curtain rods, shower frames.</li>
  <li><strong>With care:</strong> kitchen taps and sinks, shower heads, in hard-water areas.</li>
