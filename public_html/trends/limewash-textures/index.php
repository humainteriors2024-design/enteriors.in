<h2>Where it suits</h2>
<ul>
  <li>Bedroom headboard walls.</li>
  <li>One living room wall, lit from the side to show the texture.</li>
  <li>Foyers and stairwells.</li>
  <li>Not in kitchens, bathrooms or on walls with seepage.</li>
</ul>

<h2>How it is applied</h2>
<ol>
  <li>Repair and prime the wall; cure any damp first.</li>
  <li>Apply thin coats with a wide brush in crossing, random strokes.</li>
  <li>Let each coat dry; two to three coats build the depth.</li>
  <li>Seal if the product calls for it.</li>
</ol>
<p>Ask the applicator for a sample board in your colour before the wall is done.</p>

<h2>Colours that work</h2>
<p>Warm neutrals, terracotta, ochre, sage and clay tones. See <a href="/trends/warm-neutrals/">warm neutrals</a> and the <a href="/colour/">colour guide</a>.</p>

<h2>Will it last?</h2>
<p>Our view: small doses. Because it is paint, a limewash wall is cheap to change if you tire of it. Other textured options are in <a href="/wall-design/texture-paint/">texture paint designs</a>.</p>
