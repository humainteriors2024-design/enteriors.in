<h2>Will it work for Indian cooking?</h2>
<p>Heavy daily cooking produces oil and steam that a closed cabinet traps. Three approaches work:</p>
<ul>
  <li><strong>Show kitchen plus wet kitchen:</strong> the hidden kitchen faces the living room for tea, breakfast and serving; frying and heavy cooking happen in a utility or wet kitchen with its own chimney.</li>
  <li><strong>Hob on the open wall:</strong> hide the counter appliances and the sink, but keep the hob on a ventilated wall under a ducted chimney.</li>
  <li><strong>Powerful ventilation:</strong> a ducted chimney sized for Indian cooking (1,200 m³/h or more) and doors kept open while cooking.</li>
</ul>
