<h2>Hardware matters most</h2>
<p>Pocket doors are heavy and used daily. Ask for a branded pocket-door system rated for the door's weight and height, with soft-close and a synchronised slide. Push-to-open latches are elegant but wear faster on frequently used doors; a J-profile or a recessed channel lasts longer. See the <a href="/modular-kitchen/hardware-guide/">kitchen hardware guide</a>.</p>

