<h2>Where to use it</h2>
<ul>
  <li><strong>Good:</strong> balconies, verandas, pooja corners, living room accent zones, feature walls.</li>
  <li><strong>With care:</strong> dining areas (seal well against oil).</li>
  <li><strong>Avoid:</strong> kitchens, bathrooms and showers unless heavily sealed; use porcelain there.</li>
</ul>

<h2>Laying and sealing</h2>
<ol>
  <li>Soak handmade tiles before laying so they do not pull water from the mortar.</li>
  <li>Lay with wider joints (6–10 mm) to absorb size variation.</li>
  <li>Clean off cement haze promptly.</li>
  <li>Seal with a penetrating or linseed-based sealer once dry; reseal every 1–2 years.</li>
</ol>

