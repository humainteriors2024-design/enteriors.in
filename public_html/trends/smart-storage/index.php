<h2>Hidden spaces</h2>
<ul>
  <li>Window seats with drawers or lift-up lids.</li>
  <li>Under-stair cabinets in duplexes and houses.</li>
  <li>Above-door shelves in passages.</li>
  <li>A hatch in the false ceiling for suitcases.</li>
  <li>Toe-kick drawers under kitchen base units for trays and boards.</li>
</ul>

<h2>Often not worth it</h2>
<ul>
  <li>Single-purpose pull-outs for one item you rarely use.</li>
  <li>Motorised lifts in standard kitchens.</li>
  <li>Glass-fronted pull-outs for everyday clutter.</li>
</ul>

