<h2>Choosing a pattern</h2>
<ol>
  <li><strong>Calm veining</strong> (Carrara, soft travertine) ages better than bold Statuario or onyx.</li>
  <li><strong>Matte or textured finish</strong> with synchronised veins looks more real than gloss.</li>
  <li><strong>Check the repeat</strong> on a full sheet; obvious repeats give it away.</li>
  <li><strong>Match the grain</strong> across adjacent shutters if the design calls for continuity.</li>
</ol>

