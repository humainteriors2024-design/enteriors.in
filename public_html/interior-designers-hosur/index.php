<h2>Planning a whole house</h2>
<p>Independent houses are far more common in Hosur than in Bangalore's apartment belts. Brief the house as one project:</p>
<ul>
  <li><strong>One specification, repeated.</strong> If there are rental floors, use the same kitchen layout, board, finish and hardware brand on each floor. It is cheaper to make and easier to repair.</li>
  <li><strong>Pooja room.</strong> Often a full room on the ground floor. Plan the door, storage and ventilation together; see the <a href="/rooms/pooja-room/">pooja room guide</a> and <a href="/vastu/pooja-room-vastu/">pooja room vastu</a>.</li>
  <li><strong>Staircase and foyer.</strong> Under-stair cabinets for shoes and utility items; a foyer unit at the main door.</li>
  <li><strong>Main door.</strong> A solid wood or engineered door with a safety grille. See <a href="/doors/main-door-design/">main door designs</a>.</li>
  <li><strong>Heat.</strong> Hosur's summers are slightly warmer than Bangalore's; plan ceiling fans and AC points in every room before the false ceiling goes up.</li>
</ul>

<h2>Choosing a firm for Hosur</h2>
<p>You can choose a local Hosur firm or one based across the border in Attibele, Chandapura or Bommasandra. Distance matters more than the state line.</p>
