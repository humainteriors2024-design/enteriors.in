    <tr><td>7–8 ft</td><td>L-shape, or parallel with a narrow aisle</td></tr>
    <tr><td>8–9 ft</td><td>U-shape with a 4 ft aisle; L-shape with room to spare</td></tr>
    <tr><td>Over 9 ft</td><td>U-shape, or L-shape with an island if the room is long enough</td></tr>
  </tbody>
</table>
