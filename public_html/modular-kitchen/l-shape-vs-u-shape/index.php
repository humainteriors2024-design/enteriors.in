<h2>Corners: the hidden cost</h2>
<p>A corner without a fitting becomes a dark cave. Every L needs one corner solution and every U needs two. Options, from cheapest:</p>
<ul>
  <li><strong>Blind corner with a shelf:</strong> cheapest; the back is hard to reach.</li>
  <li><strong>Corner carousel (magic corner or lazy Susan):</strong> about ₹12,000; good access.</li>
  <li><strong>Pull-out corner unit:</strong> more expensive; the best access to the back.</li>
</ul>
<p>Fittings and brands are compared in the <a href="/modular-kitchen/hardware-guide/">kitchen hardware guide</a> and <a href="/modular-kitchen/storage-solutions/">storage solutions</a>.</p>

<h2>Good alternatives</h2>
<ul>
  <li><strong>Parallel (galley):</strong> for long, narrow kitchens with a utility at the end. Most counter per square foot.</li>
  <li><strong>Peninsula (G-shape):</strong> an L or U with a short arm into the room, often with a breakfast counter.</li>
  <li><strong>Island:</strong> for large open kitchens; see <a href="/modular-kitchen/island-kitchen/">island kitchens</a>.</li>
</ul>
