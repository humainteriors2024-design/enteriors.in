<h2>Measure first: the 8 ft rule</h2>
<p>Measure the clear width of the kitchen between finished walls. Counters are 2 ft deep, and an aisle needs about 3.5–4 ft so that drawers open fully and you can bend down in front of them.</p>
<div class="table-wrap">
<table>
  <thead><tr><th>Clear width</th><th>What fits</th></tr></thead>
