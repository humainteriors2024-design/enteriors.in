<p>Then mark the window, the door, the gas point and the water inlet. A door on one wall usually rules out the U; a window over the counter decides where the sink goes.</p>

<h2>Where the L-shape is the better choice</h2>
<ul>
  <li><strong>Small and medium kitchens.</strong> In a typical 2 BHK kitchen of 7×9 to 8×10 ft, the L keeps a clear floor and a comfortable aisle.</li>
  <li><strong>Open kitchens.</strong> The open side faces the dining area; one leg can become a breakfast counter. See <a href="/modular-kitchen/open-kitchen-ideas/">open kitchen ideas</a>.</li>
  <li><strong>Lower cost.</strong> Fewer running feet and only one corner fitting.</li>
  <li><strong>Two people cooking.</strong> The open side gives space to pass.</li>
</ul>

<h2>Where the U-shape is the better choice</h2>
<ul>
  <li><strong>Large, closed kitchens.</strong> In a kitchen of 100 sq ft or more, the U turns three walls into storage and counter.</li>
  <li><strong>Heavy cooking.</strong> The longest continuous counter for preparation, with the hob, sink and fridge all within a step or two.</li>
  <li><strong>Separate zones.</strong> Washing on one arm, cooking on the base, preparation on the other.</li>
</ul>
