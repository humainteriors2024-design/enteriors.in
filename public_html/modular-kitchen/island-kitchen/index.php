<p>A quick test: add the depth of the wall counter (2 ft), the aisle (3.5–4 ft), the island (2.5–3 ft) and the clearance on the far side (3.5 ft). That is 11.5–12.5 ft of room width for an island to work, which is why most 2 BHK apartment kitchens are too small and a <a href="/modular-kitchen/l-shape-vs-u-shape/">peninsula or L-shape</a> serves better.</p>

