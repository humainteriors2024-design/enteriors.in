<h2>Storage inside an island</h2>
<ul>
  <li><strong>Wide drawers</strong> on the working side for vessels, thalis and cutlery.</li>
  <li><strong>Open shelves or shallow cabinets</strong> on the seating side for cookbooks or serving dishes.</li>
  <li><strong>A bin pull-out</strong> next to the prep area.</li>
  <li><strong>Sockets</strong> on the end panels for a mixer or a laptop, wired through the floor.</li>
</ul>

<h2>Materials and finishes</h2>
<p>The island is the most visible part of an open kitchen, so many homes give it a feature finish: a wood veneer or textured laminate on the sides, a contrasting colour to the wall units, or a waterfall countertop that runs down the ends. Use BWP plywood if the island has a sink; BWR or HDHMR is fine for a dry prep island. Countertop options are compared in the <a href="/modular-kitchen/countertop-guide/">countertop guide</a>.</p>

