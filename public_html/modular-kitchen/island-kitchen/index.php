<h2>Island or peninsula?</h2>
<p>A peninsula is an island joined to the wall run at one end. It needs clear floor on three sides instead of four, services can come from the wall, and it still gives a breakfast counter. In apartments, it is usually the better buy. Islands make most sense in villas and independent houses with large open kitchens, such as the homes described in our <a href="/interior-designers-bangalore/chandapura/">Chandapura area guide</a>.</p>
