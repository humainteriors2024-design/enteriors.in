<h2>Granite: the default for good reason</h2>
<p>Granite is natural stone, very hard and unbothered by heat. Black Galaxy, Absolute Black, Jet Black and Tan Brown are popular because their dark, busy patterns hide stains. Its weaknesses are porosity, which lets oil and turmeric in unless sealed, and acid etching on polished surfaces. A penetrating sealer on the day of fixing and once a year after keeps it looking new. Read the <a href="/materials/granite-guide/">granite guide</a> for colours and grades.</p>

<h2>Quartz: easiest to live with</h2>
<p>Engineered quartz is about 90–93% crushed quartz bound with resin. It is non-porous, so stains and hard-water rings wipe off, and its colour is uniform from slab to slab, which suits light and modern kitchens. The resin is its one weakness: concentrated heat can scorch it. Keep a trivet by the hob and quartz will outlast the cabinets. See <a href="/materials/quartz-countertop/">quartz countertops</a> and <a href="/compare/quartz-vs-granite/">quartz vs granite</a>.</p>

<h2>Sintered stone and large porcelain slabs</h2>
<p>Sintered stone is made by pressing minerals under very high heat, which gives a surface that resists heat, stains, scratches and UV. Slabs are large and often 12 mm thick, so they need a full plywood base and a skilled fabricator for cut-outs. It suits premium kitchens and islands with waterfall ends.</p>

<h2>Materials to use with care</h2>
<ul>
  <li><strong>Nano white:</strong> bright and cheap, but it stains with turmeric and can crack with heat. Keep it for dry counters, not beside the hob.</li>
  <li><strong>Marble:</strong> beautiful but soft and porous; lemon and tamarind etch it within days.</li>
  <li><strong>Solid surface:</strong> seamless with integrated sinks, but hot vessels mark it.</li>
  <li><strong>Wood:</strong> warm for a breakfast counter, impractical near water.</li>
</ul>

<h2>Details that make a top last</h2>
<ol>
  <li><strong>Thickness:</strong> 20 mm slab, front edge built up to about 40 mm.</li>
  <li><strong>Drip groove</strong> under the front edge, so water does not run onto the shutters.</li>
  <li><strong>Slope:</strong> a slight fall towards the sink.</li>
  <li><strong>Under-mount sink</strong> with polished cut-out edges; or a top-mount sink sealed with silicone.</li>
  <li><strong>Joints:</strong> as few as possible, away from the sink and hob, colour-matched epoxy.</li>
  <li><strong>Backsplash:</strong> the same stone 4 inches up, or tiles from the counter to the wall units. See <a href="/materials/kitchen-tiles/">kitchen tiles and backsplash</a>.</li>
</ol>

