<p>Decision Guide</p>
<h2>The Homeowner's Hardware Buying Guide — What to Ask, What to Check</h2>
<h3>Before Signing Your Interior Contract</h3>
<ul>
  <li><strong>Ask for the hardware brand by name</strong> — not just "branded hardware" or "soft-close hardware". Request the exact brand and product series (e.g. "Hettich Sensys 8631i with integrated soft-close").</li>
  <li><strong>Ask for the hinge cycle rating</strong> — any reputable brand will have this in their product data sheet. If the contractor cannot provide it, they are using unbranded or generic hardware.</li>
  <li><strong>Confirm tandem vs conventional drawers</strong> — ask to see a completed installation or a demo unit. Open the drawer. If the sides are wood or MDF, it is not a tandem.</li>
  <li><strong>Check the soft-close action yourself</strong> — open a door fully and let it go at 45° from closed. Premium soft-close catches at approximately 30° and brings the door silently to rest. An economy soft-close barely slows the door.</li>
  <li><strong>Ask which corner solution is included</strong> — a vague answer ("we'll manage the corner") means dead space. Insist on magic corner or Lemans for L-kitchens.</li>
  <li><strong>Get hardware brands listed in the contract</strong> — not in a verbal promise. A signed contract that names Hettich gives you recourse if they substitute cheaper hardware on site.</li>
</ul>
<h3>Hardware Red Flags — What Not to Accept</h3>
<ul>
  <li>Any contractor who says hardware brand "doesn't matter" or "all soft-close is the same" — walk away. This is either ignorance or deliberate misrepresentation.</li>
  <li>A quote that bundles hardware as a line item without brand names — "hardware for kitchen: ₹18,000 lump sum"</li>
  <li>Flat-bottom wooden drawers in the kitchen without tandem box specification — these will deteriorate fastest</li>
  <li>Wardrobe sliding systems with the track carrying the door weight from below — these are bottom-carry and will grind within 3 years</li>
  <li>Hinges with no clip-on mechanism — means the door cannot be easily removed for servicing or adjustment</li>
</ul>
