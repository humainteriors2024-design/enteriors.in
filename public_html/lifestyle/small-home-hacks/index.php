<p>Many first homes in Indian cities are compact 1 and 2 BHK flats. They can feel generous with the right decisions, most of which cost nothing extra if made before the carpentry is ordered. Here are 25, grouped by what they solve. This page is part of the <a href="/planning/">home planning guide</a>.</p>

<h2>Storage</h2>
<ol>
  <li>Build every wardrobe and kitchen wall unit to the ceiling, with a loft.</li>
  <li>Choose a bed with hydraulic storage for bedding and suitcases.</li>
  <li>Use a bench with storage in the foyer and on the balcony.</li>
  <li>Fit a tall pantry pull-out in the kitchen if one wall is free.</li>
  <li>Put a shallow cabinet above the washing machine and the toilet.</li>
  <li>Use the space above doors for slim shelves.</li>
</ol>

<h2>Furniture that does two jobs</h2>
<ol start="7">
  <li>A sofa-bed instead of a separate guest bed.</li>
  <li>An extendable dining table: four daily, six for guests.</li>
  <li>A fold-down wall desk that closes flat.</li>
  <li>Nesting side tables that tuck under each other.</li>
  <li>A TV unit with drawers that replaces a chest of drawers.</li>
</ol>

<h2>Light and colour</h2>
<ol start="12">
  <li>Warm white or soft neutral walls, light ceilings, mid-tone floors.</li>
  <li>Sheer curtains by day, lined ones for night.</li>
  <li>One large mirror beside or opposite a window.</li>
  <li>Glass or fluted-glass shutters on one or two upper units.</li>
  <li>Layered light: cove light, a floor lamp and task lights, not one bright tube.</li>
</ol>
<p>Colour pairings are in <a href="/colour/living-room-colour-combination/">living room colour combinations</a>; lighting in the <a href="/planning/lighting-design/">lighting design guide</a>.</p>

<h2>Layout</h2>
<ol start="17">
  <li>Keep a straight 3 ft walkway from the door through the home.</li>
  <li>Wall-mount the TV unit and floating vanities to show the floor.</li>
  <li>Choose furniture on legs rather than plinths.</li>
  <li>Use sliding wardrobe doors where the bed is close.</li>
  <li>Use a pocket or sliding door for the kitchen or bathroom if a swing door blocks space.</li>
  <li>Open a closed kitchen to the living area with a breakfast counter, if the structure allows.</li>
</ol>
<p>Clearances are listed in <a href="/planning/furniture-layout/">furniture layout planning</a>.</p>

<h2>Habits</h2>
<ol start="23">
  <li>One closed unit per room for clutter.</li>
  <li>A "one in, one out" rule for clothes and kitchen gadgets.</li>
  <li>Seasonal swap: keep only this season's clothes in reach; the rest in lofts.</li>
</ol>
